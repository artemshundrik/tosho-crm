-- Дозаписати собівартість із пулу тим позиціям, що приїхали за посиланням (REQ-285#p10).
--
-- ЩО СТАЛОСЬ. Підстановка ціни з пулу існує з 08.09 і працює для товару,
-- обраного в пошуку: браузер називає РЯДОК пулу, а число читає й пише сама
-- база (`tosho.set_quote_run_cost_from_pool`). Товар, доданий ПОСИЛАННЯМ, до
-- цього механізму під'єднали лише зараз — тож позиції, створені раніше,
-- стоять із порожньою собівартістю, хоч ціна на них у нас є.
--
-- ЧОМУ НЕ ПОКЛИКАТИ САМУ ФУНКЦІЮ. Вона `security definer`, але всередині
-- звіряє `public.is_team_member(v_team)` — а адмінське з'єднання членом
-- команди не є, бо в нього немає `auth.uid()`. Тому повторюємо тут РІВНО ТУ
-- САМУ логіку, включно з прапорцем `tosho.cost_from_pool`, яким вона відмикає
-- гейт посад на цінових полях.
--
-- ПИШЕМО ЛИШЕ ТАМ, ДЕ ЦІНА ОДНОЗНАЧНА. Якщо за адресою стоїть кілька рядків
-- пулу з РІЗНИМИ цінами, ціну визначає колір — і вибрати за менеджера не можна.
-- Живий приклад: «Футболка ST7000 Lux» у TS-0926-0030 має 14 кольорів від
-- 269,99 до 301,35, тож обидві її позиції цей скрипт свідомо пропускає; там
-- ціну назве вибір кольору. А от «Записна книжка Туксон» має чотири кольори з
-- однаковою ціною 287,70 — її пишемо спокійно.
--
-- ТІЛЬКИ В ПОРОЖНЄ (`coalesce(unit_price_model, 0) = 0`) — як і функція.
-- Число, поставлене людиною, не чіпаємо: воно старше за будь-який прайс.
--
-- ТІЛЬКИ ОПТОВА ЦІНА (`price_kind = 'wholesale'`) і тільки активний рядок тієї
-- ж команди — знову ж таки рівно як у функції. `retail` — це вітрина
-- постачальника, з якої нічого не порахуєш, і в собівартість вона не має права.
--
-- ПДВ: ціни постачальників вважаємо з ПДВ (рішення Артема 08.09.2026), тому
-- `unit_price_model_vat = 'incl'`.
--
-- Ідемпотентний: другий прогін нічого не знайде, бо поля вже не порожні.

\set ON_ERROR_STOP on

-- Прапорець вмикає запис у цінові поля повз гейт посад — так само, як це
-- робить сама функція. Скидається в кінці файлу.
select set_config('tosho.cost_from_pool', '1', true);

with pooled as (
  -- Одна ціна на адресу — або жодної. `min = max` і є ознакою однозначності.
  select p.url, p.team_id, min(p.price) as price
  from tosho.supplier_products p
  where p.url is not null
    and p.is_active
    and p.price is not null
    and p.price_kind = 'wholesale'
  group by p.url, p.team_id
  having min(p.price) = max(p.price)
)
update tosho.quote_item_runs r
set unit_price_model = s.price,
    unit_price_model_vat = 'incl',
    updated_at = now()
from tosho.quote_items i
join pooled s on s.url = i.metadata->>'supplierUrl' and s.team_id = i.team_id
where r.quote_item_id = i.id
  and coalesce(r.unit_price_model, 0) = 0;

select set_config('tosho.cost_from_pool', '', true);
