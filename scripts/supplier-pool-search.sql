-- Чесна частка постачальника у вікні пошуку пулу (REQ-250).
--
-- ЩО БУЛО НЕ ТАК. Пул шукався одним запитом PostgREST:
--   .or(name.ilike.*термін*, article.ilike.*термін*).order("name").limit(ліміт × 20)
-- Стеля тут спрацьовує РАНІШЕ за будь-яке сортування, і саме в цьому біда:
-- 800 рядків набираються за абеткою з усіх постачальників упереміш, а вже
-- потім картки сортуються «спершу ті, у кого відома ціна». Тобто сортування
-- рятує лише те, що встигло приїхати.
--
-- Заміряно на проді 08.09.2026, запит «футболка»: 2519 рядків збігу — 1840
-- Аванпринта, 665 Тотобі, 14 Berrytex. У 800 рядків вікна не потрапив ЖОДЕН
-- рядок Тотобі: назви Аванпринта сортуються раніше й вичерпують стелю. На
-- екрані менеджер бачив 36 карток Аванпринта і нуль Тотобі — при тому, що
-- саме в Тотобі лежать 32 футболки з нашою закупівельною ціною, тобто єдині,
-- з яких можна щось порахувати.
--
-- Симптом підступний тим, що виглядає як «у Тотобі немає футболок». Дані на
-- місці, з ними все гаразд — їх просто не спитали.
--
-- ЩО РОБИМО. Стеля стає ПОСТАЧАЛЬНИЦЬКОЮ, а не спільною: `row_number()` у
-- вікні `partition by supplier_slug` дає кожному джерелу однакову квоту. Один
-- великий постачальник більше не може витіснити решту в принципі — не тому,
-- що ми його пересортували, а тому, що він фізично не займає чужі місця.
--
-- ЧОМУ ВСЕРЕДИНІ КВОТИ ПОРЯДОК ЗА НАЗВОЮ. Рядки одного товару (кольори,
-- розміри) мають однакову назву, тож сусідять. Ріжучи за назвою, ми ріжемо по
-- межі товару, а не посеред його кольорів — інакше картка приїхала б у
-- браузер половиною варіантів і показала б неправильний діапазон цін. Це та
-- сама причина, з якої `.order("name")` стояв у первісному запиті; вона
-- лишається чинною, просто діє тепер усередині кожного постачальника.
--
-- ЧОМУ НЕ ПОВЕРТАЄМО РЯДОК ТАБЛИЦІ ЦІЛКОМ. `attrs` на avanprint важить 5,3 МБ
-- (там описи під документи), і `returns setof tosho.supplier_products` тягнув
-- би його в кожну відповідь. Віддаємо рівно ті колонки, які малює вікно, а
-- колір дістаємо як `attrs->>'color'` — точно як робив попередній .select().
--
-- ЧОМУ security invoker (за замовчуванням, лишено явно). На таблиці стоїть RLS
-- `is_team_member(team_id)`. Definer зняв би її й віддав чужі команди — а тут
-- немає жодної причини піднімати права: пошук читає рівно те, що користувачеві
-- і так дозволено.
--
-- ilike any(масив) замість or-ланцюга — щоб і оригінал, і транслітерація
-- («chashka» → «чашка») ішли одним проходом; терміни готує клієнт
-- (`transliterateSearchTerm` у src/lib/supplierPoolRows.ts).
--
-- Ідемпотентний: повторний прогін нічого не дублює.

-- Одна транзакція — від `npm run db:apply` (psql -1); свого `begin` тут немає
-- навмисно: він закривав би її раніше й ламав атомарність усього файлу.
\set ON_ERROR_STOP on

-- Спершу знімаємо стару: `create or replace` не вміє міняти перелік колонок
-- результату, а `size` тут з'явився пізніше за саму функцію (10.09.2026).
drop function if exists tosho.search_supplier_pool(text[], integer);

create or replace function tosho.search_supplier_pool(
  p_terms text[],
  p_per_supplier integer default 200
)
returns table (
  id            uuid,
  supplier_slug text,
  article       text,
  name          text,
  vendor        text,
  category      text,
  price         numeric,
  currency      text,
  price_kind    text,
  url           text,
  image_url     text,
  color         text,
  size          text
)
language sql
stable
security invoker
set search_path = ''
as $fn$
  with pat as (
    -- Терміни коротші за два символи відкидаємо тут, а не покладаємось на
    -- клієнта: «%а%» зібрав би пів пулу й з'їв би всі квоти сміттям.
    select array_agg('%' || t || '%') as arr
    from unnest(p_terms) as t
    where length(btrim(t)) >= 2
  ),
  hit as (
    select
      sp.id, sp.supplier_slug, sp.article, sp.name, sp.vendor, sp.category,
      sp.price, sp.currency, sp.price_kind, sp.url, sp.image_url,
      sp.attrs->>'color' as color,
      -- РОЗМІР ПОТРІБЕН САМЕ ТУТ, а не «колись у attrs». У Trele рядок — це
      -- пара «колір + розмір», і без розміру шість рядків одного кольору
      -- виглядають шістьма однаковими чипами: менеджер тицяє навмання й тягне
      -- в замовлення артикул чужого розміру. Решта джерел розміру не кладе —
      -- у них тут порожньо, і підпис лишається таким, як був.
      sp.attrs->>'size' as size,
      row_number() over (partition by sp.supplier_slug order by sp.name, sp.id) as rn
    from tosho.supplier_products sp
    cross join pat
    where pat.arr is not null
      and sp.is_active
      -- ШУКАЄМО В ЧОТИРЬОХ ДЖЕРЕЛАХ: Аванпринт, Тотобі, Бергамо (Артем,
      -- 08.09.2026) і Е-Сувенір (Артем, 08.09.2026, після заміру перетину).
      -- Беррітекс не показуємо — у нього ціни чужі, роздрібні, а чуже число
      -- гірше за порожнє поле: порожнє менеджер помітить і піде питати,
      -- неправильне просто візьме.
      --
      -- Е-СУВЕНІР ДОДАНО НЕ «БО ЗАЛИЛИ», А ПІСЛЯ ЗАМІРУ. Артем притримав його
      -- показ, поки не з'ясується, чи не дублює він Тотобі. Заміряно на
      -- залитих даних: збігів артикулів із Тотобі, Бергамо й Беррітексом —
      -- НУЛЬ, бренди не перетинаються (Sun Line, Mem'O!, Ritter Pen, Fruit of
      -- the Loom проти Discover/Floyd/Gildan). Усі 106 спільних артикулів — з
      -- Аванпринтом, тобто з нашим власним магазином, і саме там злиття
      -- корисне: в Аванпринта ціни немає, тут вона є. Склеюються 10 карток із
      -- 424, усі пари перевірені очима.
      --
      -- СПИСОК, А НЕ ЛИШЕ ПРАВИЛО ПРО ЦІНУ, і це свідома зміна від 08.09.2026.
      -- Спершу тут стояло саме правило («ховаємо тих, у кого ціна роздрібна»),
      -- і воно давало рівно той самий результат — але мовчки: нове джерело
      -- потрапляло б у пошук менеджера тим, що хтось залив фід, а не тим, що
      -- хтось так вирішив. Тепер щоб з'явитись у пошуку, постачальника треба
      -- дописати сюди — тим самим рухом, яким його додають у реєстр
      -- завантажувача (scripts/load-supplier-feed.mjs).
      --
      -- БЕРРІТЕКС ДОДАНО 09.09.2026, І ПРИЧИНА ЙОГО ВІДСУТНОСТІ ЗНИКЛА, А НЕ
      -- БУЛА ПЕРЕГЛЯНУТА. Досі його фід давав РОЗДРІБ, тож друга сторожа нижче
      -- відсіювала його рядки одне за одним — показувати його не було чого.
      -- Тепер завантажувач заходить у кабінет і 2071 рядок лежить із нашою
      -- ціною (price_kind = 'wholesale'), тобто джерело нарешті відповідає
      -- тій самій умові, що й решта.
      --
      -- ПАПІРУС ДОДАНО 09.09.2026 РІШЕННЯМ АРТЕМА, і саме рішенням: три чверті
      -- його прайсу — канцтовари, школа й творчість, тобто не промо-продукція,
      -- і питання «чи не буде це шумом у пошуку менеджера» вирішувалось окремо
      -- від того, що фід залився. Ціна в нього наша просто з кабінету, з ПДВ.
      --
      -- TRELE ДОДАНО 10.09.2026: однотонний одяг під друк (B&C, Fruit of the
      -- Loom, Gildan, Roly, Russell, Atlantis, Kariban, Just Hoods, Anvil) —
      -- рівно те, з чого починається половина прорахунків. Ціна наша, з-під
      -- логіна, і вона нижча за вітрину в 98,6% рядків.
      --
      -- ENEY ДОДАНО 10.09.2026: промо-продукція й мерч цілим асортиментом —
      -- ручки, павербанки, посуд, сумки, щоденники, текстиль під нанесення,
      -- тобто те саме, що менеджер шукає щодня. Ціна наша, з-під логіна, і
      -- знижка тут рівна на весь каталог (−30%, заміряно на 50 товарах).
      and sp.supplier_slug in (
        'avanprint.ua', 'totobi.com.ua', 'bergamo.ua', 'e-suvenir.com.ua',
        'berrytex.com.ua', 'papirus-opt.com', 'trele.com.ua', 'eney.com.ua'
      )
      -- Друга сторожа лишається: навіть із дозволених джерел не показуємо
      -- рядок, у якому ціна є, але вона НЕ наша. Домовленість про знижку може
      -- відпасти, і тоді джерело замовкне саме, не чекаючи, поки хтось згадає.
      and not (sp.price is not null and sp.price_kind = 'retail')
      and (sp.name ilike any (pat.arr) or sp.article ilike any (pat.arr))
  )
  select
    hit.id, hit.supplier_slug, hit.article, hit.name, hit.vendor, hit.category,
    hit.price, hit.currency, hit.price_kind, hit.url, hit.image_url, hit.color, hit.size
  from hit
  where hit.rn <= greatest(p_per_supplier, 1)
  -- Порядок на виході теж за назвою: групування в браузері не залежить від
  -- нього, але стабільна відповідь робить і кеш, і очі передбачуваними.
  order by hit.name, hit.supplier_slug, hit.id
$fn$;

revoke all on function tosho.search_supplier_pool(text[], integer) from public;
grant execute on function tosho.search_supplier_pool(text[], integer) to authenticated;
