-- Зона роботи й тема картки запиту.
--
-- НАВІЩО ДВІ ОСІ. Тип картки (`kind`: bug / friction / feature) відповідає на
-- питання «що сталось» і його знає той, хто просить. Але він нічого не каже
-- про те, ЯКА це буде робота: «Не працює» — це і зсунути кнопку, і переписати
-- політику доступів. Спроба вкласти обидві осі в один список типів ламається
-- на першому ж реальному запиті: «бухгалтер бачить собівартість» — це
-- одночасно `bug` і робота з RLS, і жодне зі значень не можна викинути.
-- Тому зона — окрема колонка, а не ще кілька значень у `kind`.
--
-- ЧОМУ zone БЕЗ check-констрейнта — з тієї самої причини, що й `module_key`
-- (див. scripts/dev-requests-classification.sql): перелік живе в
-- src/features/devRequests/types.ts і звіряється застосунком. Констрейнт у
-- базі став би другим списком, який неминуче розійдеться з першим.
--
-- ЧОМУ theme — вільний текст, а не окрема таблиця тем. Тема потрібна рівно
-- для одного: побачити разом усі картки однієї роботи («навігація»). Дерево
-- підзадач вирішувало б ту саму задачу ціною статусів, які починають
-- конфліктувати між батьком і дітьми. Вільний рядок дає групування без нової
-- сутності, а якщо теми колись знадобиться нормалізувати — це окремий крок.
--
-- Ідемпотентна, безпечна до повторного запуску.
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/dev-requests-zone-theme.sql

\set ON_ERROR_STOP on

begin;

alter table tosho.dev_requests
  add column if not exists zone  text,
  add column if not exists theme text;

comment on column tosho.dev_requests.zone is
  'Зона роботи: polish | speed | data | access | logic. Перелік у src/features/devRequests/types.ts (REQUEST_ZONES). Порожньо = ще не розібрали; порожнє поле краще за неправильне.';
comment on column tosho.dev_requests.theme is
  'Вільна мітка-тема для групування карток однієї роботи («навігація»). Замінює підзадачі: групує, не заводячи дерева зі статусами.';

-- Фільтр «покажи все про навігацію» ходить по темі в межах команди.
-- Частковий індекс: тема є в меншості карток, і повний був би переважно
-- порожнім.
create index if not exists dev_requests_theme_idx
  on tosho.dev_requests (team_id, theme)
  where theme is not null;

commit;
