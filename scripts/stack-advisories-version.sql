-- ---------------------------------------------------------------------------
-- Дірки безпеки тепер знають, ДО ЯКОЇ версії вони належать.
--
-- ЩО БУЛО НЕ ТАК. `advisories` зберігали відповідь npm про ВСТАНОВЛЕНУ на
-- момент перевірки версію, але сама версія ніде не фіксувалась. Наслідок
-- побачили одразу після REQ-117: оновили pdfjs-dist до 6.2.108, сторінка
-- чесно показала чипс «свіже» — і поруч із ним старий червоний чипс «діра
-- безпеки · висока», бо в рядку лежала відповідь про 5.6.205.
--
-- Дві половини одного рядка суперечили одна одній, і саме червона була
-- неправдою. Для сторінки, яка існує заради довіри до цифр, це найгірший
-- можливий тип помилки: вона не падає, виглядає впевнено й лякає даремно.
--
-- ЯК ЛІКУЄМО. Записуємо версію, про яку питали. Сторінка показує дірки лише
-- тоді, коли ця версія збігається зі встановленою; інакше вважає, що про
-- поточну версію ми ще не питали, — і мовчить замість того, щоб брехати.
--
-- Порожній `advisories_version` у наявних рядках лишається навмисно: це чесне
-- «невідомо, до чого це належало». Найближчий прохід крона перепише всі рядки
-- разом із версією.
--
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/stack-advisories-version.sql
-- ---------------------------------------------------------------------------

alter table tosho.stack_versions
  add column if not exists advisories_version text;

comment on column tosho.stack_versions.advisories_version is
  'Встановлена версія пакета, про яку питали npm, коли складали advisories. Не збігається з поточною — значить перевірка застаріла, і показувати дірки не можна.';

