-- Стандартизовані поля підрядників і постачальників.
--
-- Why: усе, крім назви, заповнювалось вільним текстом, і в полях осіли структури.
-- Розбір бази показав: у полі «телефон» лежать по 2–4 номери разом із поштою,
-- сайтами й примітками; у полі «Нова Пошта» — ЄДРПОУ, юрособа й отримувач; у
-- полі «адреса» — три сайти, хоча воно підключене до довідника адрес.
--
-- ЩО СВІДОМО НЕ ДОДАЄМО: IBAN. Прогін по всіх полях не знайшов ЖОДНОГО —
-- ні рядка «IBAN», ні формату UA+27. Порожнє поле, яке ніхто ніколи не
-- заповнював, лише подовжує форму. З'явиться потреба платити з CRM — додамо.
--
-- Колонки додаються порожніми: перенесення даних із вільного тексту — окремий
-- крок з прев'ю на погодження, щоб нічого не загубилось.

alter table tosho.contractors
  -- Кілька номерів на контрагента — норма: у базі 9 записів із двома, 3 із трьома,
  -- 1 із чотирма. Масив, а не рядок через кому: це справді список значень.
  add column if not exists phones text[] not null default '{}',
  -- Пошта теж множинна: у ТОВ «КОЛОРИТ» їх три в одному полі.
  add column if not exists emails text[] not null default '{}',
  add column if not exists website text,
  add column if not exists edrpou text,
  -- Юрособа окремо від назви: «Планета Сервіс» виставляє рахунки від
  -- ТОВ «Планета Прінт», «Кліше» — від ТзОВ «Підприємство «Кліше».
  add column if not exists legal_name text,
  -- Форма власності потрібна разом із ЄДРПОУ: у юрособи 8 цифр, у ФОП 10.
  add column if not exists ownership_type text;

