#!/usr/bin/env node
/**
 * Чи не бреше документація, за якою працюють агенти (REQ-107).
 *
 * НАВІЩО. Claude Code і Codex починають роботу з читання AGENTS.md, CLAUDE.md і
 * docs/*. Ці файли не документація «для людей» — це ІНСТРУКЦІЇ, за якими агент
 * ухвалює рішення. Коли вони протухають, агент помиляється впевнено.
 *
 * Реальні знахідки аудиту 22.08.2026, усі з наслідками:
 *
 *   «базова лінія лінту червона»  — а лінт чистий. Агент, який це прочитав, міг
 *                                   пройти повз СПРАВЖНЮ помилку: «так і має бути».
 *   «46 тестів»                   — їх 1190. Число, за яким оцінюють, чи варто
 *                                   покладатись на тести взагалі.
 *   розміри чотирьох гігантів     — за ними агент вирішує, з якого рядка читати
 *                                   файл; DesignTaskPage розійшовся на 3 тисячі рядків.
 *
 * ЩО ЦЕ ПЕРЕВІРЯЄ. Лише те, що можна порахувати механічно: числа й факти, які
 * мають одну правильну відповідь у дереві. Тлумачення, поради й «чому саме так»
 * не чіпаємо — там протухання ловить лише людина.
 *
 * ЧОМУ З ДОПУСКОМ. Розмір файлу міняється на кожній правці. Якби перевірка
 * падала на різниці в десять рядків, її б вимкнули на другий день. Тому
 * допуск — 5%: він ловить «документація відстала на версію», а не «файл виріс».
 *
 * ЧОМУ ЦЕ НЕ В pre-push. Протухла документація не ламає прод — вона ламає
 * НАСТУПНУ роботу. Її місце — щотижнева рутина, яка відкриває PR лише з
 * правками docs. Руками: npm run check:docs-drift
 *
 * --fix (він же `npm run docs:sync`): не звіряти, а ПЕРЕПИСАТИ числа з дерева й
 * поставити сьогоднішню дату знімка. Заміряно 27.08.2026: за чотири дні той самий
 * документ правили руками ТРИЧІ («мапа великих файлів знову збігається з кодом»),
 * бо перевірка вміла лише сказати «розійшлось». Похідне від коду має
 * генеруватись, а не переписуватись людиною: інакше кожна правка гіганта тягне
 * за собою окремий коміт про документацію.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, statSync, writeFileSync } from "node:fs";

const ДОПУСК = 0.05;

const рядків = (file) => readFileSync(file, "utf8").split("\n").length - 1;
const кілобайт = (file) => Math.round(statSync(file).size / 1024);

/** Скільки тестів насправді — питаємо самого vitest, а не рахуємо `it(` регуляркою. */
function тести() {
  const out = execFileSync("npx", ["vitest", "run", "--reporter=json", "--silent"], {
    encoding: "utf8",
    timeout: 300_000,
    maxBuffer: 64 * 1024 * 1024,
  });
  const json = JSON.parse(out.slice(out.indexOf("{")));
  return { files: json.testResults?.length ?? json.numTotalTestSuites, tests: json.numTotalTests };
}

const число = (text) => Number(String(text).replace(/[^\d]/g, ""));

const ТВЕРДЖЕННЯ = [
  ...[
    ["src/pages/QuoteDetailsPage.tsx"],
    ["src/pages/DesignTaskPage.tsx"],
    ["src/pages/QuotesPage.tsx"],
    ["src/pages/DesignPage.tsx"],
  ].flatMap(([page]) => [
    {
      де: "docs/LARGE_FILES_MAP.md",
      про: `${page} — рядків`,
      знайти: new RegExp(`^## ${page.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")} \\(~([\\d\\s]+) lines`, "m"),
      факт: () => рядків(page),
    },
    {
      де: "docs/LARGE_FILES_MAP.md",
      про: `${page} — кілобайт`,
      знайти: new RegExp(`^## ${page.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")} \\(~[\\d\\s]+ lines, (\\d+) KB`, "m"),
      факт: () => кілобайт(page),
    },
    {
      де: "CLAUDE.md",
      про: `${page} — рядків у навігаційній підказці`,
      знайти: new RegExp(
        `${page.split("/").pop().replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\`? \\(~([\\d\\s]+)`,
        "m"
      ),
      факт: () => рядків(page),
    },
  ]),
  {
    де: ".github/workflows/ci.yml",
    про: "кількість тестів",
    знайти: /на \d\d\.\d\d\.\d{4} їх ([\d\s]+) у [\d\s]+ файл(?:ах|і)/m,
    факт: () => тести().tests,
  },
  {
    де: ".github/workflows/ci.yml",
    про: "кількість тестових файлів",
    знайти: /на \d\d\.\d\d\.\d{4} їх [\d\s]+ у ([\d\s]+) файл(?:ах|і)/m,
    факт: () => тести().files,
  },
];

const ЛАГОДИМО = process.argv.includes("--fix");

/** Число в тому ж вигляді, що й було: «9 900» лишається з пробілами, «1444» — без. */
const якБуло = (старе, нове) =>
  /\s/.test(старе) ? String(нове).replace(/\B(?=(\d{3})+(?!\d))/g, " ") : String(нове);

const сьогодні = new Date();
const дві = (n) => String(n).padStart(2, "0");
const ISO = `${сьогодні.getFullYear()}-${дві(сьогодні.getMonth() + 1)}-${дві(сьогодні.getDate())}`;
const УКР = `${дві(сьогодні.getDate())}.${дві(сьогодні.getMonth() + 1)}.${сьогодні.getFullYear()}`;

/** Дата знімка поруч із числом — інакше документ казав би «на 24.08» про сьогоднішнє число. */
const оновитиДати = (текст) =>
  текст
    .replace(/as of \d{4}-\d\d-\d\d/g, `as of ${ISO}`)
    .replace(/станом на \d\d\.\d\d\.\d{4}/g, `станом на ${УКР}`)
    .replace(/на \d\d\.\d\d\.\d{4} їх/g, `на ${УКР} їх`);

const розбіжності = [];
const виправлено = [];
const кеш = new Map();
const змінені = new Set();

for (const твердження of ТВЕРДЖЕННЯ) {
  const текст = кеш.get(твердження.де) ?? readFileSync(твердження.де, "utf8");
  кеш.set(твердження.де, текст);

  // Пересобираємо регулярку з прапорцем `d`, щоб знати МЕЖІ групи й переписати
  // саме число, не чіпаючи решти рядка.
  const шаблон = new RegExp(твердження.знайти.source, `${твердження.знайти.flags}d`);
  const match = текст.match(шаблон);
  if (!match) {
    розбіжності.push({ ...твердження, написано: null, факт: null, чому: "твердження зникло з файлу" });
    continue;
  }

  const написано = число(match[1]);
  const факт = твердження.факт();

  if (ЛАГОДИМО) {
    if (написано !== факт) {
      const [від, до] = match.indices[1];
      // Група буває «жадібна» й ковтає пробіл перед словом («9850 » у CLAUDE.md),
      // тож пробіли по краях зберігаємо як були — інакше вийде «9 900lines».
      const голова = match[1].match(/^\s*/)[0];
      const хвіст = match[1].match(/\s*$/)[0];
      const ядро = match[1].trim();
      кеш.set(твердження.де, текст.slice(0, від) + голова + якБуло(ядро, факт) + хвіст + текст.slice(до));
      змінені.add(твердження.де);
      виправлено.push({ ...твердження, написано, факт });
    }
    continue;
  }

  const відхилення = Math.abs(написано - факт) / Math.max(факт, 1);
  if (відхилення > ДОПУСК) {
    розбіжності.push({ ...твердження, написано, факт, відхилення });
  }
}

if (ЛАГОДИМО) {
  if (розбіжності.length > 0) {
    console.error("\nЦе автоматом не полагодити — твердження зникло з файлу:\n");
    for (const item of розбіжності) console.error(`  ${item.де} — ${item.про}`);
    process.exit(1);
  }
  if (виправлено.length === 0) {
    console.log(`Документація: ${ТВЕРДЖЕННЯ.length} тверджень уже збігаються з деревом — правити нема чого.`);
    process.exit(0);
  }
  for (const файл of змінені) writeFileSync(файл, оновитиДати(кеш.get(файл)), "utf8");
  console.log(`Документація: оновлено ${виправлено.length} із ${ТВЕРДЖЕННЯ.length} тверджень і дати знімків.`);
  for (const item of виправлено) {
    console.log(`  ${item.де} — ${item.про}: ${item.написано} → ${item.факт}`);
  }
  process.exit(0);
}

if (розбіжності.length === 0) {
  console.log(`Документація: ${ТВЕРДЖЕННЯ.length} тверджень звірено з деревом — розбіжностей немає.`);
  process.exit(0);
}

console.error("\nДокументація розійшлася з кодом:\n");
for (const item of розбіжності) {
  if (item.чому) {
    console.error(`  ${item.де} — ${item.про}: ${item.чому}`);
    continue;
  }
  const знак = item.факт > item.написано ? "виріс" : "схуднув";
  console.error(
    `  ${item.де} — ${item.про}: написано ${item.написано}, насправді ${item.факт} ` +
      `(${знак} на ${Math.round(item.відхилення * 100)}%)`
  );
}
console.error("\nПравити треба ДОКУМЕНТАЦІЮ, а не код: це знімки, і в кожного є дата поруч.");
console.error("Одним рухом: npm run docs:sync");
process.exit(1);
