-- Посилання на теку «Бренд» замовника.
--
-- Тека Замовники/{Клієнт}/Бренд створюється разом із текою клієнта і призначена
-- для матеріалів ВІД замовника: брендбук, лого, шрифти. На 31.07.2026 вона була
-- порожня у ВСІХ 12 замовників — не через недбалість, а тому що в CRM не було
-- жодного посилання на Dropbox: шляхи зберігались, але жоден екран їх не
-- показував. Дизайнер фізично не мав куди покласти брендбук.
--
-- Зберігаємо саме shared-url, а не будуємо його зі шляху: у Dropbox посилання
-- видає API окремо для кожної теки, зі шляху воно не виводиться.
--
-- Ідемпотентно: можна виконувати повторно.
-- =====================================================================

alter table tosho.customers
  add column if not exists dropbox_brand_shared_url text;

comment on column tosho.customers.dropbox_brand_shared_url is
  'Shared-посилання на теку «Бренд» замовника. Заповнюється при створенні теки або за першим запитом із CRM.';
