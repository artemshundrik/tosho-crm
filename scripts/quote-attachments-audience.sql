-- Кому призначений файл прорахунку: проєкту чи дизайнеру.
--
-- НАВІЩО. Досі файл можна було прикріпити лише в дизайн-блоці модалки
-- прорахунку, разом із ТЗ. Наслідків два, і обидва погані. Перший: блок
-- ховається, коли друку немає, — тобто прикріпити договір чи розміри від
-- замовника до прорахунку без нанесення було НІКУДИ. Другий: усе, що туди
-- клали, автоматично ставало матеріалом для дизайнера й вмикало
-- `has_files` у дизайн-задачі, хоча половина тих файлів дизайнеру не
-- потрібна й ніколи не була адресована йому.
--
-- ЧОМУ КОЛОНКА, А НЕ ШЛЯХ У STORAGE. Донедавна походження файлу вгадували
-- з `storage_path`: є `/quote-attachments/` — значить із прорахунку, ні —
-- з ТЗ (src/pages/DesignTaskPage.tsx, attachmentSourceById). Там навіть
-- стоїть коментар, що окремого поля заводити не варто «заради фільтра».
-- Тепер це вже не фільтр: від цієї ознаки залежить, що дизайнер бачить як
-- своє завдання. Ознака, від якої залежить видимість, не може жити в
-- підрядку шляху, який ніхто не заважає змінити.
--
-- ЧОМУ DEFAULT 'design', А НЕ 'project'. Дефолт тут страхує записи з тих
-- шляхів коду, які ще не оновлені, і бекфіл старих рядків. Сьогодні
-- дизайнер бачить УСІ файли прорахунку; якби старе стало 'project', на
-- активних задачах у нього мовчки зникли б матеріали, з якими він працює.
-- 'design' лишає видиме видимим, а нова поведінка діє лише для того, що
-- покладуть у нову зону після викочування.
--
-- Ідемпотентна, безпечна до повторного запуску.
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/quote-attachments-audience.sql

\set ON_ERROR_STOP on

begin;

alter table tosho.quote_attachments
  add column if not exists audience text not null default 'design';

alter table tosho.quote_attachments
  drop constraint if exists quote_attachments_audience_check;
alter table tosho.quote_attachments
  add constraint quote_attachments_audience_check
  check (audience in ('project', 'design'));

comment on column tosho.quote_attachments.audience is
  'Кому адресований файл: project — матеріали замовника для проєктного менеджера, design — матеріали для дизайнера (вмикають has_files і видимі в дизайн-задачі). Дефолт design зумисне: він зберігає дотеперішню поведінку для шляхів коду, які ще не передають значення явно.';

-- Дизайн-задача щоразу питає «покажи мої матеріали до цього прорахунку»,
-- тож індекс складений під саме цей запит. Часткового не робимо: обидва
-- значення масові, і 'project' зростатиме швидше за 'design'.
create index if not exists quote_attachments_quote_audience_idx
  on tosho.quote_attachments (quote_id, audience, created_at desc);

commit;
