-- REQ-228 — увесь наявний склад переїжджає в «Залишки на складі».
--
-- ЩО БУЛО НЕ ТАК. Засів REQ-38 (scripts/sample-stock-kind.sql) розкладав
-- позиції за категорією: «Пакування» → supply, решта → sample. На папері це
-- виглядало точно, на ділі — ні. У «Взірцях» опинились Термос Smart (395 шт),
-- Комахопастка (350), Ремінці (247), Метеостанція (200) — це складські
-- залишки, а не взірці. Взірець — одна-дві штуки на полиці, які показують
-- клієнту; сотні штук на складі це залишок, хоч би до якої категорії він
-- належав.
--
-- ЯК МАЄ БУТИ. Усі 17 наявних позицій — «Залишки на складі». Підрозділ
-- «Взірці» лишається ПОРОЖНІМ і наповнюється з нуля справжніми взірцями:
-- форма додавання товару стоїть на «Взірцях» за замовчуванням, тож новий
-- взірець заводиться без жодного перемикання.
--
-- ОДНОРАЗОВИЙ, І ЦЕ ВАЖЛИВО. Повторний прогін затер би все, що люди потім
-- переклали у «Взірці» руками, — а саме туди тепер і йде вся нова робота.
-- `db:apply` сам не дасть застосувати той самий вміст двічі; свідомий повтор
-- тут не потрібен ніколи.
--
-- Застосування: npm run db:apply scripts/sample-stock-all-to-supply.sql

begin;

update tosho.sample_stock_items
   set stock_kind = 'supply'
 where stock_kind <> 'supply';

commit;
