-- Пул постачальників скидає дві речі, які ніхто не питає — REQ-264#p1, REQ-264#p2.
--
-- ЗВІДКИ ВЗЯЛОСЯ. Розбір ваги пулу 10.09.2026: таблиця `tosho.supplier_products`
-- важить 78 МБ — це 73% усієї схеми `tosho` (107 МБ) і чверть бази (316 МБ).
-- Більшість ваги чесна (37 693 рядки товарів і 19 МБ `attrs`), але два
-- складники в ній не роблять узагалі нічого.
--
-- ── 1. ПОКАЖЧИК ЗА КОНТРАГЕНТОМ (REQ-264#p1) ────────────────────────────────
--
-- `supplier_products_contractor_idx` заведено разом із таблицею (REQ-250) під
-- ще ненаписаний екран «товари цього контрагента»: картка постачальника мала
-- відкриватись від контрагента, а не від домену. Екран пішов іншим шляхом —
-- `SupplierProducts.tsx` питає пул за `supplier_slug`, бо саме slug є в реєстрі
-- завантажувача, а `contractor_id` заповнюється лише тоді, коли картку
-- контрагента вже завели руками.
--
-- `pg_stat_user_indexes` на проді 10.09.2026: `idx_scan = 0`. Не «мало» — нуль,
-- за весь час життя таблиці. Для порівняння, сусіди за той самий час:
-- `supplier_products_uniq` 122 412 звернень, `article_trgm` 1824, `name_trgm`
-- 236, `supplier_idx` 689.
--
-- ЦІНА ЙОГО ІСНУВАННЯ НЕ В 816 кБ, А В ЗАЛИВІ. Фіди перезаливаються двічі на
-- день (`.github/workflows/supplier-feeds.yml`), і кожен upsert мусить оновити
-- КОЖЕН покажчик рядка, який зачепив, — включно з цим. Тобто база двічі на день
-- переписує дерево, у яке ніхто жодного разу не заглянув.
--
-- ЯКЩО ЕКРАН «ТОВАРИ КОНТРАГЕНТА» ВСЕ-ТАКИ З'ЯВИТЬСЯ — покажчик повертається
-- одним рядком (`create index ... on tosho.supplier_products (contractor_id)`),
-- і на 37 тисячах рядків це секунди. Тримати його роками «про всяк випадок»
-- дорожче, ніж завести заново в той день, коли він знадобиться.
--
-- ── 2. КОЛОНКА `raw` (REQ-264#p2) ───────────────────────────────────────────
--
-- Заведена разом із таблицею з наміром «щоб не втратити те, чого схема ще не
-- знає»: покласти поруч сирий шматок фіда, якщо в ньому трапиться поле, під яке
-- колонки немає. Намір добрий, але жоден із семи розбирачів у
-- `scripts/load-supplier-feed.mjs` її не пише — незнайомі поля лягають у
-- `attrs`, і на практиці цього вистачило всім семи джерелам.
--
-- Заміряно на проді 10.09.2026: `count(*) filter (where raw is not null)` = 0
-- при 37 693 рядках. Порожня не «майже», а рівно.
--
-- ВАГИ ЦЕ НЕ ЗВІЛЬНИТЬ, І НЕ В НІЙ СПРАВА. `null` у Postgres лежить у бітовій
-- мапі рядка й місця не займає — вимірюваного виграшу від цього `drop` не буде.
-- Прибираємо через ІНШЕ: колонка обіцяє дані, яких немає. Наступний, хто
-- відкриє таблицю (я в новій сесії або людина через пів року), побачить
-- «сирий фід» і витратить час на з'ясування, чи можна на нього спертись, —
-- а спертись не можна ні на один рядок.
--
-- ЯКЩО СИРІ ФІДИ ВСЕ-ТАКИ ЗНАДОБЛЯТЬСЯ — це буде інша задача з іншою формою
-- (радше окрема таблиця знімків із датою, ніж колонка поруч із товаром), тож
-- відроджувати саме цю колонку однаково ніхто не став би.
--
-- ЧОМУ ПЕРЕД `drop` СТОЇТЬ ПЕРЕВІРКА. Між заміром і застосуванням минає час, і
-- за цей час хтось міг почати писати в `raw` — наприклад, я сам у сусідній
-- гілці. `drop column` мовчки забрав би ці дані назавжди. Тому файл спершу
-- питає базу й падає, якщо в колонці бодай один рядок: краще зупинитись і
-- перечитати, ніж тихо стерти.
--
-- ЧОГО ЦЕЙ ФАЙЛ НЕ ЧІПАЄ. `attrs.description` (14 МБ, 21 472 рядки) лишається
-- як є: описи товарів Аванпринта збережені навмисно під тексти документів і
-- специфікацій (рішення Артема 10.09.2026, докладніше — коментар біля
-- `parseHoroshop` у `scripts/load-supplier-feed.mjs`). Те, що їх поки ніхто не
-- читає, — це «ще не дійшли руки», а не «зайве».
--
-- Ідемпотентний: `if exists` на обох діях, повторний прогін нічого не ламає.
--
-- Одна транзакція — від `npm run db:apply` (psql -1); свого `begin` тут немає
-- навмисно: він закривав би її раніше й ламав атомарність усього файлу.

\set ON_ERROR_STOP on

-- ── Сторожа: колонка `raw` має бути порожня ─────────────────────────────────
-- Стоїть ПЕРЕД обома діями, а не лише перед `drop column`: якщо база скаже, що
-- дані з'явились, ми не хочемо застосувати навіть половину файлу.
do $guard$
declare
  filled bigint;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'tosho' and table_name = 'supplier_products' and column_name = 'raw'
  ) then
    execute 'select count(*) from tosho.supplier_products where raw is not null' into filled;
    if filled > 0 then
      raise exception
        'У tosho.supplier_products.raw % рядків із даними — не видаляю. Хтось почав її наповнювати після заміру 10.09.2026; розберись, звідки це пишеться, перш ніж застосовувати цей файл.',
        filled;
    end if;
  end if;
end
$guard$;

-- ── 1. Покажчик за контрагентом: нуль звернень ──────────────────────────────
drop index if exists tosho.supplier_products_contractor_idx;

-- ── 2. Порожня колонка сирого фіда ──────────────────────────────────────────
alter table tosho.supplier_products drop column if exists raw;

