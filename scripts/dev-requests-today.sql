-- Полиця «Сьогодні» переїжджає з браузера в базу.
--
-- ЩО БУЛО НЕ ТАК. Вибране на сьогодні лежало в localStorage — «це особиста
-- замітка на один день, а не факт про картку». Міркування не витримало першого
-- ж робочого дня: Артем позначає справи за компʼютером, а потім відкриває
-- беклог із телефона — і полиця там порожня. Виглядало як зникнення задач, хоча
-- в базі не бракувало жодної картки.
--
-- Замітка справді особиста, але «особиста» не означає «прив'язана до браузера».
-- Дошку відкривають із трьох пристроїв за день, і будь-який стан, що не
-- переживає зміну пристрою, читається як втрата даних.
--
-- ЧОМУ КОЛОНКИ, А НЕ ОКРЕМА ТАБЛИЦЯ. Керувати чергою можуть лише owner і SEO
-- (політика dev_requests_update) — тобто дві людини. Окрема таблиця «хто що взяв
-- на сьогодні» вирішувала б конфлікт, якого на двох майже не буває: він
-- можливий, лише якщо обидва позначать ОДНУ Й ТУ САМУ картку, і тоді останній
-- перепише позначку першого. Ціна помилки — одна знята позначка; ціна зайвої
-- таблиці — ще одні RLS, ще один запит і ще одне місце, де стан може розійтися.
--
-- Ідемпотентна, безпечна до повторного запуску.
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/dev-requests-today.sql
\set ON_ERROR_STOP on

begin;

alter table tosho.dev_requests
  add column if not exists today_by uuid,
  add column if not exists today_at timestamptz;

comment on column tosho.dev_requests.today_by is
  'Хто взяв картку на сьогодні. NULL — не взята. Замітка особиста: у «Черзі» показуються лише свої.';
comment on column tosho.dev_requests.today_at is
  'Коли взяли. Задає порядок у полиці — той, у якому картки туди клали.';

-- Полиця читається запитом «мої на сьогодні» на кожне відкриття дошки, і без
-- індексу це був би повний перебір карток команди. Частковий: узятих одночасно
-- одиниці, і повний індекс був би переважно порожнім.
create index if not exists dev_requests_today_idx
  on tosho.dev_requests (team_id, today_by, today_at)
  where today_by is not null;

commit;

notify pgrst, 'reload schema';
