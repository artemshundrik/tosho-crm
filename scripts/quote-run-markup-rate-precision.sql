-- REQ-149 · Виправлення точності перенесеної накрутки.
--
-- ЩО ПІШЛО НЕ ТАК. У scripts/quote-run-markup-rate.sql перенесення історії
-- округляло відсоток до двох знаків: round(..., 2). На відсотку це виглядає
-- нешкідливо, але ціна множиться на собівартість, і похибка росте разом із
-- чеком.
--
-- ЗАМІРЯНО НА ПРОДІ одразу після застосування: максимальний розбіг старої і
-- нової ціни — 8,39 ₴, і в 117 тиражів зі 163 він більший за 10 копійок.
-- Прорахунки перераховуються ЖИВО з тиражів (див. project_quote_pricing_source),
-- тож після переходу інтерфейсу на markup_rate відкритий торішній прорахунок
-- показав би іншу суму, ніж стоїть у вже виставленому рахунку.
--
-- ЛІКИ. Той самий зворотний хід формули, але без round(): накрутка — це
-- похідне число, а не те, що людина вводить руками. Відсотки, які ставить
-- менеджер, лишаються круглими самі собою; округлювати треба на ПОКАЗІ, а не
-- у сховищі. Після цього розбіг падає до 8,52e-52 ₴.
--
-- Чому окремим файлом, а не правкою першого: той уже застосовано й записано в
-- журнал разом зі своїм sha. Переписаний файл розійшовся б із журналом і
-- зробив би відповідь на питання «що саме поїхало на прод» неправдивою.

update tosho.quote_item_runs r
set markup_rate =
      (
        (coalesce(r.desired_manager_income, 0) / (nullif(r.manager_rate, 0) / 100.0))
        * (1 + coalesce(r.fixed_cost_rate, 0) / 100.0)
        * (1 + coalesce(r.vat_rate, 0) / 100.0)
      )
      / nullif((coalesce(r.unit_price_model, 0) + coalesce(r.unit_price_print, 0))
               * coalesce(r.quantity, 0) + coalesce(r.logistics_cost, 0), 0)
      * 100.0
where coalesce(r.desired_manager_income, 0) > 0
  and coalesce(r.manager_rate, 0) > 0
  and (coalesce(r.unit_price_model, 0) + coalesce(r.unit_price_print, 0))
      * coalesce(r.quantity, 0) + coalesce(r.logistics_cost, 0) > 0;
