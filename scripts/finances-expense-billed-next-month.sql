-- Finance module — журнальна витрата з рахунком НАСТУПНОГО місяця (REQ-314).
--
-- НАВІЩО. Нагадування «закрити місяць» приходить 25-го про поточний місяць і
-- 5-го про минулий. Воді й прибиранню це підходить: їх вносять у межах свого
-- місяця. А рахунок за комуналку по офісу виставляють 6–8 числа наступного
-- місяця, тож 25 вересня прийшло «До кінця вересня не внесено — 1 витрата.
-- Богданівська 7: Комунальні послуги», коли вносити було ще нічого, — і його
-- прочитали як докір за серпень, який давно внесли. Бейдж «не внесено за
-- вересень» у Фінансах при цьому світився весь вересень.
--
-- Позначена так витрата свій місяць закриває 10-го числа наступного: у стадіях
-- soft (25-го) і final (5-го) її немає, нагадування приходить окремою стадією
-- billed 10-го (scripts/finance-month-close-cron.sql), а бейдж загоряється з
-- того ж 10-го (src/features/finances/monthClose.ts). Це вибір людини в
-- картці витрати («Рахунок приходить наступного місяця»), а не здогад.
--
-- Safe to run multiple times.

alter table tosho.finance_expenses
  add column if not exists billed_next_month boolean not null default false;

comment on column tosho.finance_expenses.billed_next_month is
  'Журнальна витрата, рахунок за яку приходить наступного місяця (комуналка). Її місяць закривається 10-го числа наступного: нагадування й бейдж «не внесено» — з 10-го, а не 25-го й 5-го.';

-- Бекфіл: комуналка — рівно той випадок, заради якого це зроблено. На 26.09.2026
-- таких журнальних витрат одна (Богданівська 7); решту журнальних (вода,
-- прибирання, продукти) вносять у межах місяця, їх не чіпаємо.
update tosho.finance_expenses e
   set billed_next_month = true
  from tosho.finance_expense_categories c
 where c.id = e.category_id
   and c.name = 'Комунальні послуги'
   and e.is_recurring
   and e.amount_varies
   and e.event_type is null
   and e.archived_at is null
   and not e.billed_next_month;
