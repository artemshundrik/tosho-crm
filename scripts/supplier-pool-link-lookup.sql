-- Покажчики під пошук товару за посиланням у пулі (REQ-285#p1).
--
-- НАВІЩО. Менеджер вставляє посилання на товар, і CRM тепер спершу шукає його
-- в `tosho.supplier_products`, а лише потім іде шкребти чужий сайт
-- (`netlify/functions/_lib/supplierPoolLookup.ts`). Драбинка з двох запитів:
-- рівність по `url` і, якщо не знайшлось, рівність по парі
-- `(supplier_slug, article)`. Обидва зараз читають таблицю повністю: з п'яти
-- наявних покажчиків жоден із цих стовпців не веде. По `url` немає взагалі
-- нічого, а `supplier_products_article_trgm` — тригрaмний, для рівності він
-- не годиться.
--
-- 49 774 рядки, і запит ходить НА КОЖНУ ВСТАВКУ ПОСИЛАННЯ — а посилань у файлі
-- буває тридцять. Повний скан на кожне з них з'їв би весь виграш, заради якого
-- пул і читається.
--
-- ЧОМУ ЗВИЧАЙНІ BTREE, А НЕ ТРИГРAМИ Й НЕ `security definer`. Сусідній
-- `search_supplier_pool` довелось робити definer саме тому, що RLS не пускає
-- `ILIKE` у тригрaмний покажчик: `pg_catalog.texticlike` не leakproof, умову
-- політики Postgres рахує першою й чесно читає всю таблицю (заміряно 16.09.2026:
-- 5 508 мс у середньому по `pg_stat_statements` роллю `authenticated`).
-- Рівність цієї вади не має: `texteq` leakproof, тож планувальник зводить її
-- в `Index Cond` і під політикою теж. Отже, тут досить звичайного клієнта
-- користувача — без definer, без дубля умов політики, без ризику, що політика
-- й функція розійдуться.
--
-- ЧОМУ ЧАСТКОВІ. Адреси немає в 5787 рядків (увесь Мідошен — у нього просто
-- немає сайту з товарами, прайс приходить ексельками), і тримати їх у
-- покажчику сенсу немає: за `null` ніхто не шукає.
--
-- ЧОМУ БЕЗ `concurrently`. `npm run db:apply` веде файл однією транзакцією
-- (`psql -1`), а `create index concurrently` у транзакції заборонено. На
-- 49 774 рядках побудова займає частки секунди, тож блокування запису на цей
-- час дешевше за окремий позатранзакційний шлях.
--
-- Ідемпотентний: повторний прогін нічого не дублює.

\set ON_ERROR_STOP on

-- Перша сходинка драбинки: точний збіг адреси. Написання адреси нормалізує
-- клієнт (кінцевий слеш, `www.`, мітки реклами) і надсилає список кандидатів
-- одним `in` — саме тому тут проста рівність, а не обчислюваний ключ.
create index if not exists supplier_products_url_idx
  on tosho.supplier_products (url)
  where url is not null;

-- Друга сходинка: артикул У МЕЖАХ постачальника. Порядок стовпців саме такий —
-- `supplier_slug` першим: без нього артикул неоднозначний (3781 артикул із
-- 40 876 зустрічається більш ніж в одного постачальника), і пара звужує вибірку
-- до одного магазину ще в покажчику.
create index if not exists supplier_products_supplier_article_idx
  on tosho.supplier_products (supplier_slug, article)
  where article is not null;

analyze tosho.supplier_products;
