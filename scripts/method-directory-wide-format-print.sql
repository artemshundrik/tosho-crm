-- Метод нанесення «Широкоформатний друк» для виду «Банер» (REQ-264#p11).
--
-- ЗВІДКИ. 09.10.2026 у прорахунку TS-1026-0002 (мобільний стенд X-банер)
-- менеджер не знайшов методу ні серед методів виду «Банер» (їх там не було
-- жодного), ні в «Інших методах…» спільного довідника. Додати нову назву з
-- вікна прорахунку не можна свідомо (див. useKindImprintOptions.ts), тож
-- просили дописати.
--
-- ЯК ЦЕ ПРАЦЮЄ. Рядок `catalog_methods` без `directory_id`: тригер
-- `catalog_methods_bind_directory` сам знайде або заведе запис у
-- `tosho.method_directory` і підставить канонічну назву. Тобто один insert
-- дає і запис довідника (видно в «Інших методах…» для будь-якого виду), і
-- метод виду «Банер» (стоїть першим у смузі нанесення банера).
--
-- ПОВТОРНИЙ ЗАПУСК безпечний: `on conflict` на (kind_id, name) нічого не
-- робить, а тригер на конфлікті довідника лише торкає updated_at.

insert into tosho.catalog_methods (team_id, kind_id, name, price)
select k.team_id, k.id, 'Широкоформатний друк', null
from tosho.catalog_kinds k
where k.id = 'e50afcb8-1e92-41aa-ad84-eabc26a244fd' -- Широкоформат / Банер
on conflict (kind_id, name) do nothing;
