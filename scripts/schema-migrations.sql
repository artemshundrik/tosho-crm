-- Журнал застосованих SQL-скриптів (REQ-104).
--
-- НАВІЩО. У scripts/ лежить 99 файлів .sql, і всі вони їхали на прод руками
-- через psql. Ніде не записано, що вже застосоване, а що ні: єдиним джерелом
-- правди була пам'ять того, хто застосовував. Реальна ціна цього вже
-- траплялась — 20.08.2026 перейменування функції поїхало в код, а SQL із
-- розкладом крона на прод не поїхав, і нагадування мовчали добу.
--
-- ЩО ЦЕ НЕ Є. Це не міграції в сенсі Supabase CLI: тут немає ні порядку
-- застосування, ні відкату, ні локального стека. Це ЖУРНАЛ — відповідь на одне
-- питання: «цей файл уже застосований на проді, і чи саме в цьому вигляді».
-- Повний перехід на CLI з pgTAP лишається окремою роботою; журнал — її перший
-- крок і те, з чого вона потім прочитає історію.
--
-- ЧОМУ ІСТОРІЯ, А НЕ ОДИН РЯДОК НА ФАЙЛ. Скрипт часто застосовують повторно
-- після правки, і знати треба не лише «застосований», а «яка саме редакція і
-- коли». Тому ключ сурогатний, а унікальності немає навмисно: повтор дозволено,
-- але свідомо — це вирішує scripts/db-apply.mjs, а не база.

create table if not exists tosho.schema_migrations (
  id bigint generated always as identity primary key,
  -- Шлях від кореня репозиторію: scripts/reminders-cron.sql
  name text not null,
  -- sha256 вмісту файлу на момент застосування — саме він відповідає на
  -- питання «а це та сама редакція, що зараз у дереві?».
  sha256 text not null,
  applied_at timestamptz not null default now(),
  -- Хто застосував: береться з $USER машини, лише щоб було кого спитати.
  applied_by text,
  -- Для бекфілу й ручних випадків: звідки взялась ця дата.
  note text
);

create index if not exists schema_migrations_name_idx on tosho.schema_migrations (name);

-- RLS вмикаємо без жодної політики й без грантів: журнал читає й пише лише той,
-- хто підключається напряму (psql під власником) або service_role. Через
-- PostgREST його не видно взагалі — і це навмисно, у застосунку він не потрібен.
alter table tosho.schema_migrations enable row level security;

revoke all on tosho.schema_migrations from anon, authenticated;
