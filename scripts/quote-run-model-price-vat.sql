-- Чи включає вартість товару ПДВ — прапорець біля самої суми (REQ-232).
--
-- НАВІЩО. У полі «Вартість товару / од.» ніде не сказано, з ПДВ там сума чи
-- без, а постачальники різні: ТОВ-платник виставляє з ПДВ, ФОП третьої групи —
-- без. Тобто в одній колонці на 460 тиражів лежить мікс брутто й нетто, і
-- «накрутка 40 %» у двох сусідніх тиражах означає різні гроші. Той самий мікс
-- лежить в основі орієнтира маржі («54,1 % по цьому виду товару») і всієї
-- матриці накрутки за розміром чека.
--
-- ЩО ЦЕ ПОЛЕ РОБИТЬ І ЧОГО НЕ РОБИТЬ. Воно ЛИШЕ ПОЗНАЧАЄ сенс суми. Формула
-- ціни (`computeRunSalePricingFromMarkup` у src/lib/quoteRuns.ts) його не
-- читає й не читатиме в цій задачі: жодна вже порахована картка не має
-- зрушити. Рішення Артема 01.09.2026 — спершу зібрати чисті дані, і лише
-- потім, окремою задачею, вмикати арифметику й розбиратись зі старими
-- тиражами.
--
-- ЧОМУ NULLABLE І ЧОМУ БЕЗ DEFAULT. Три стани, а не два: 'incl', 'excl' і
-- «ще не обрано». Дефолт будь-якого зі значень зробив би з невідомого
-- твердження — рівно ту помилку, від якої це поле й рятує. Порожнеча тут не
-- недогляд схеми, а факт: для 460 наявних тиражів ми справді не знаємо
-- відповіді, і вигадувати її бекфілом не можна.
--
-- Обов'язковість живе в застосунку, а не в NOT NULL: гейт вмикається лише
-- тоді, коли вартість товару міняють у цій сесії. Інакше кожна стара картка
-- стала б незберігаємою при першому дотику до будь-чого сусіднього.
--
-- Застосування: npm run db:apply scripts/quote-run-model-price-vat.sql
-- ---------------------------------------------------------------------------

alter table tosho.quote_item_runs
  add column if not exists unit_price_model_vat text
  check (unit_price_model_vat in ('incl', 'excl'));

comment on column tosho.quote_item_runs.unit_price_model_vat is
  'Чи включає unit_price_model ПДВ: incl — з ПДВ, excl — без ПДВ, null — не обрано. Лише позначка сенсу суми: у розрахунок ціни НЕ входить (REQ-232).';

