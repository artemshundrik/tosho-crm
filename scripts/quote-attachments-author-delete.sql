-- REQ-33 — автор вкладення може видалити СВОЄ вкладення.
--
-- Що було. Політика видалення вимагала рівно одного: командну роль
-- `super_admin` або `manager`. Про автора файлу в ній не було ні слова, тож
-- виходило дві протилежні кривди одночасно:
--
--   · людина з роллю `viewer` (у нас це дизайнери — 100 файлів від 2 людей)
--     не могла прибрати НІЧОГО, навіть щойно завантажений власний файл;
--   · будь-який менеджер міг видалити чужий файл із чужого прорахунку.
--
-- Інтерфейс тим часом ховав кнопку ще жорсткіше — «я менеджер цього прорахунку
-- І я завантажив цей файл», — тож помилкове вкладення в чужому прорахунку
-- лишалось назавжди: кнопки немає, а причини не написано.
--
-- Що стало. Видаляє той, хто завантажив, АБО менеджер/адмін команди. Роль
-- менеджера лишаємо навмисно: файли лишаються після звільнених, і прибирати їх
-- має хто може.
--
-- `is_team_member` тут не для краси: він несе перевірку `is_user_blocked`, якої
-- інакше в гілці «автор» не було б, і звільнений співробітник міг би підчищати
-- за собою вже після відключення.
--
-- Ідемпотентна, безпечна до повторного запуску.
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/quote-attachments-author-delete.sql

begin;

drop policy if exists quote_attachments_delete on tosho.quote_attachments;

create policy quote_attachments_delete
  on tosho.quote_attachments
  for delete
  to authenticated
  using (
    is_team_member(team_id)
    and (
      uploaded_by = auth.uid()
      or has_team_role(team_id, array['super_admin', 'manager'])
    )
  );

commit;
