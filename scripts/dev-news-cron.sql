-- ПОРЯДОК ВАЖЛИВИЙ:
--   1. scripts/dev-news.sql застосовано,
--   2. функція dev-news задеплоєна на прод,
--   3. вигляд перевірено через ?dry=1,
--   4. і аж тоді цей файл.
-- Інакше джоб стукатиме в 404 — мовчки, бо net.http_post лише ставить запит у
-- чергу й про відповідь не знає нічого (див. scripts/check-cron-endpoints.mjs).
--
-- Час у cron — UTC. 06:00 UTC = 09:00 Київ улітку, 08:00 узимку. Зсув
-- прийнятий свідомо, як і в решті розкладів: підбірка не прив'язана до подій
-- робочого дня, і година туди-сюди її не псує.
--
-- ЧОМУ 09:00, А НЕ РАЗОМ ІЗ ТЕХ-ЗВІТОМ О 07:45. Тех-звіт має червону чи зелену
-- шапку про стан системи, і новини під червоною шапкою читаються як аварія.
-- Плюс о 08:15 їде бізнес-звіт — підбірка стає третьою, коли робочі два вже
-- прочитані.
--
-- Re-run безпечний: cron.schedule() робить upsert за іменем джоба.
-- ---------------------------------------------------------------------------

select cron.schedule(
  'dev-news',
  '0 6 * * *',
  $$ select net.http_post(
       url := 'https://tosho.pro/.netlify/functions/dev-news-background',
       headers := jsonb_build_object('x-cron-key', (select value from tosho.cron_config where key='cron_secret')),
       timeout_milliseconds := 30000) $$
);

