-- ---------------------------------------------------------------------------
-- Погоджена позиція — прапорець на самій позиції прорахунку (REQ-267#p1).
--
-- НАВІЩО. «Затверджено» досі було станом УСЬОГО прорахунку, а поняття «клієнт
-- узяв оцю позицію, а ці дві — ні» не існувало ніде. Прорахунок із трьох
-- альтернатив затверджував усі три: TS-0826-0036 (три парасольки по 30 шт)
-- порахувався як 43 823 ₴ замість реальних 13 199 ₴ за одну обрану. Скарга
-- менеджера 11.09.2026: «рахувала 3 види парасоль, а обрали тільки 1; перевела
-- на затверджено і воно одразу затвердило все 3 варіанта».
--
-- ЧОМУ ЦЕ НЕ ТЕ САМЕ, ЩО `quote_item_runs.is_approved`. Той прапорець
-- відповідає на питання «який ТИРАЖ у межах однієї позиції взяв клієнт» і
-- вмикається, лише коли тиражів більше одного. Тут у кожної позиції був рівно
-- один тираж, тож питання не ставилось узагалі. Це сусідній рівень, а не той
-- самий.
--
-- ТРИ СТАНИ, А НЕ ДВА — І САМЕ ТОМУ КОЛОНКА NULLABLE, БЕЗ DEFAULT:
--   null  — питання не ставили (усі наявні рядки, усі чернетки) → У ПІДСУМОК ВХОДИТЬ
--   true  — клієнт узяв → входить
--   false — клієнт не взяв → НЕ входить
--
-- `not null default true` тут був би зручнішим на вигляд і брехнею по суті:
-- рядок щойно створеної чернетки читався б як «погоджено клієнтом», хоч
-- клієнта ще ніхто не питав. Розрізняти null і true треба й на екрані — інакше
-- менеджер, яка щойно підтвердила «так, усі три», не побачить різниці між
-- «відповіла» і «діалог не зберігся».
--
-- Правило читання одне на весь застосунок — `isQuoteItemIncluded` у
-- src/lib/quoteItemApproval.ts: `is_approved !== false`. Тобто бекфіл НЕ
-- ПОТРІБЕН: усі 305 наявних прорахунків лишаються рахуватись бітом у біт так
-- само, як рахувались до цієї міграції.
--
-- ЧОМУ НЕМАЄ ЧАСТКОВОГО УНІКАЛЬНОГО ІНДЕКСУ, на відміну від тиражів.
-- Погоджених позицій може бути скільки завгодно: прорахунок на три різні
-- товари, де клієнт узяв усі три, — нормальний і найчастіший випадок. Тиражі
-- взаємовиключні, позиції — ні.
--
-- Застосування: npm run db:apply scripts/quote-item-approved.sql
-- ---------------------------------------------------------------------------

alter table tosho.quote_items
  add column if not exists is_approved boolean;

alter table tosho.quote_items
  add column if not exists approved_at timestamptz;

alter table tosho.quote_items
  add column if not exists approved_by uuid;

comment on column tosho.quote_items.is_approved is
  'Чи взяв клієнт цю позицію. null = не питали (входить у підсумок), true = взяв, false = не взяв (у підсумок і в замовлення НЕ входить).';

comment on column tosho.quote_items.approved_at is
  'Коли менеджер зафіксував вибір клієнта по цій позиції.';

comment on column tosho.quote_items.approved_by is
  'Хто зафіксував вибір клієнта по цій позиції (auth.users.id).';

