-- Лід може жити на Telegram замість телефону (REQ-298).
--
-- НАВІЩО. Менеджер знайомиться з маркетологом у Telegram, і телефону не має
-- взагалі: на сайті компанії стоїть загальний номер, який нічого не дає. Форма
-- вимагала номер, тож такого ліда завести було нічим — люди або вигадували
-- номер, або не заводили ліда зовсім.
--
-- ЯК ЗБЕРІГАЄМО. Нік БЕЗ «@» — так само, як telegram у контактах замовника
-- (tosho.customers.contacts). Тоді посилання t.me/<нік> будується однаково з
-- обох джерел, і при переведенні ліда в замовника нік переїжджає як є.
--
-- ЧОМУ КОЛОНКА ВІЛЬНА. Правило «телефон АБО Telegram» живе в застосунку, а не
-- в базі: у трьохстах наявних лідів ніка немає й не буде, і будь-яке обмеження
-- на рівні таблиці зробило б їх невалідними заднім числом.

\set ON_ERROR_STOP on

alter table tosho.leads add column if not exists telegram text;

comment on column tosho.leads.telegram is
  'Telegram-нік ліда без «@». Разом із phone_numbers дає правило «телефон або Telegram» (REQ-298).';
