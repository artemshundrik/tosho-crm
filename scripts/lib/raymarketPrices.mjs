/**
 * Єдиний код кольору «білий» у Stedman. Перевірено на всіх 45 кодах кольорів
 * сайту (16.09.2026): білий рівно один, решта — кольори. У моделях RAY колір
 * записаний словом («U0102-White»), і його теж треба впізнати, бо в майбутньому
 * прайсі поділ може з'явитись і там.
 */
const WHITE_CODES = new Set(["WHI", "WHITE"]);

/**
 * `sku` сторінки → артикул і код кольору. `null` — якщо в полі не артикул.
 *
 * Беремо ЦІЛИЙ код до риски разом із буквеним хвостом, а не «починається з
 * U0102»: інакше `U0102P` зійшов би за `U0102` й отримав чужу ціну.
 *
 * З хвоста відкидається рівно одна літера — `M` або `W`, і тільки вона. Це
 * стать (`U0401M` і `U0401W` — те саме худі), а в прайсі на неї один рядок
 * «men/women/unisex», тож у ціні вона нічого не міняє. Решта літер лишається:
 * `L` у `U0405L` і `P` у `U0102P` — частина артикула, і обидва позначають ІНШИЙ
 * товар. Відкидати «будь-яку літеру в кінці» означало б злити їх з базовою
 * моделлю; відкидати нуль літер — розвести `U0401M` і `U0401W` на два артикули,
 * яких у прайсі немає.
 */
export function raymarketArticle(sku) {
  if (typeof sku !== "string") return null;
  const raw = sku.trim();
  if (!raw) return null;
  const m = /^((?:ST|[UK])\d+[A-Z]*)(?:[-\s]+(.*))?$/i.exec(raw);
  if (!m) return null;
  const article = m[1].toUpperCase().replace(/(?<=\d[A-Z]*)[MW]$/, "");
  return { article, color: (m[2] ?? "").trim() };
}

/**
 * `sku` сторінки → ціна з прайса. `null` — товару в прайсі немає (артикул не
 * той, або поле взагалі не артикул).
 *
 * Повертає `price` базового діапазону й усю драбину `bands`: у пул іде перше
 * число, решта лягає в `attrs`, щоб великий розмір не виглядав тією ж ціною.
 */
export function raymarketPrice(sku) {
  const parsed = raymarketArticle(sku);
  if (!parsed) return null;
  const slot = BY_ARTICLE.get(parsed.article);
  if (!slot) return null;

  const white = WHITE_CODES.has(parsed.color.toUpperCase());
  const row = slot.any ?? (white ? slot.white : slot.color);
  if (!row) return null;

  const [baseBand, basePrice] = row.bands[0];
  return {
    article: parsed.article,
    color: parsed.color || null,
    kind: row.kind,
    price: basePrice,
    band: baseBand,
    bands: row.bands.map(([size, price]) => ({ size, price })),
  };
}

