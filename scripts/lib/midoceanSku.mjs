/**
 * АРТИКУЛ ПРАЙСА Д1 → SKU MIDOCEAN — чисті рядки, без мережі.
 *
 * Навіщо це окремо від завантажувача. Midocean — єдине наше джерело, де фото
 * не треба ні шукати обходом, ні виводити з чужої розмітки: CDN віддає кадр за
 * адресою, складеною просто з коду товару. Тобто вся розвідка тримається на
 * одному перетворенні рядка, і саме його варто закріпити тестом окремо.
 *
 * Прайс приходить у їхньому внутрішньому вигляді: `MMO320003X`. Це той самий
 * `MO3200-03`, тільки з `M` спереду, `X` ззаду і без риски:
 *
 *   MMO320003X   → MO3200-03   ручка, колір 03
 *   MAR125316X   → AR1253-16   і сам постачальник підтверджує це в назві:
 *                              «Калькулятор сірий, AR1253-16»
 *   MMO24090607X → MO2409-06   два зайві розряди — їхній внутрішній хвіст
 *   MKC1803X     → KC1803      батарейка: коду кольору немає взагалі
 *
 * Розкладаються ВСІ 5441 рядки серпневого прайса (замір 16.09.2026).
 *
 * ⚠️ SKU З НАЗВИ ТОВАРУ ЗВІРЯТИ МОЖНА ЛИШЕ ПО МОДЕЛІ. У 454 рядках код
 * лишився в тексті назви, і спокусливо взяти його як контрольний — але в 34 із
 * них там код БАЗОВОГО кольору, а не свого: «Косметичка двоколірна MO9815-03»
 * стоїть підписом і в MMO981505X, і в MMO981510X, і в MMO981513X. Правду про
 * колір каже тільки артикул. Тому `midoceanModel` — для звіряння, а повний SKU
 * з назви — ні.
 */

/** Розміри, які CDN справді віддає. Решта — 403, тому перелік, а не аргумент. */
export const MIDOCEAN_IMAGE_SIZES = ["60X60", "240X240", "340X340", "700X700", "original"];

const ARTICLE_RE = /^M([A-Z]{2})(\d{4,})X$/;

/**
 * `MMO320003X` → `MO3200-03`. Чужий рядок — `null`, без здогадів.
 *
 * Правило: перші чотири розряди — модель, наступні два — код кольору, решта
 * відкидається. Розрядів рівно чотири — товар без кольору (SKU = модель).
 */
export function midoceanSkuFromArticle(article) {
  if (typeof article !== "string") return null;
  const match = article.trim().toUpperCase().match(ARTICLE_RE);
  if (!match) return null;
  const [, family, digits] = match;
  const model = `${family}${digits.slice(0, 4)}`;
  return digits.length >= 6 ? `${model}-${digits.slice(4, 6)}` : model;
}

/** `MO3200-03` → `MO3200`. Товар без кольору лишається собою. */
export function midoceanModel(sku) {
  const at = String(sku ?? "").indexOf("-");
  return at === -1 ? String(sku ?? "") : String(sku).slice(0, at);
}

/**
 * Адреса знімка. Кадру за нею може й не бути — CDN відповідає на неіснуючий
 * ключ кодом 403, — тож завантажувач кожну адресу перепитує HEAD-запитом
 * перед записом: порожня плитка на картці позиції гірша за відсутнє фото.
 */
export function midoceanImageUrl(sku, size = "700X700") {
  if (!MIDOCEAN_IMAGE_SIZES.includes(size)) {
    throw new Error(`Невідомий розмір знімка «${size}». CDN віддає: ${MIDOCEAN_IMAGE_SIZES.join(", ")}`);
  }
  return `https://cdn1.midocean.com/image/${size}/${String(sku).toLowerCase()}.jpg`;
}
