-- ---------------------------------------------------------------------------
-- Коли пакет востаннє випускав нову версію.
--
-- НАВІЩО. Сторінка вміла казати, що вийшла новіша версія, але не казала, КОЛИ.
-- А це питання іншого роду: пакет, останній реліз якого був два роки тому, —
-- ризик не через відставання, а через те, що дірку в ньому ніхто не закриє.
-- Побачити це можна лише за датою.
--
-- ЗВІДКИ ДАНІ. Пошуковий ендпоінт npm віддає дату останньої публікації в
-- кілограмі байтів (≈1 КБ на пакет), на відміну від повного packument на 2–3 МБ.
-- Питає той самий щоденний крон.
--
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/stack-published-at.sql
-- ---------------------------------------------------------------------------

alter table tosho.stack_versions
  add column if not exists latest_published_at timestamptz;

comment on column tosho.stack_versions.latest_published_at is
  'Коли в npm востаннє публікували будь-яку версію пакета. Давня дата — сигнал, що пакет покинутий, а не що ми відстали.';
