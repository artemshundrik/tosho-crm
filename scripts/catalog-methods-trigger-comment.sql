-- Колонка, яку заповнює тригер, тепер сама про це каже.
--
-- ПРОБЛЕМА. `tosho.catalog_methods.directory_id` — NOT NULL без DEFAULT, але
-- жоден виклик у коді його не передає: значення проставляє BEFORE INSERT/UPDATE
-- тригер `catalog_methods_bind_directory` (він же заводить запис у довіднику,
-- якщо такої назви ще немає). Для бази це коректно, а от генератор типів
-- (scripts/gen-db-types.mjs) тригерів не бачить: він судить лише за
-- is_nullable + default_value, тому робить колонку ОБОВʼЯЗКОВОЮ в `Insert`.
--
-- Наслідок був неприємний: повна регенерація типів ламала `npx tsc --noEmit`
-- трьома помилками в цілком робочому коді (QuotesPage, useModelEditor), і через
-- це нові таблиці доводилось дописувати в database.types.ts руками.
--
-- ЧОМУ САМЕ КОМЕНТАР, А НЕ СПИСОК У СКРИПТІ. Факт «це заповнює тригер»
-- належить колонці, а не генератору: його видно в psql і в Supabase UI, він
-- переживає перейменування файлів і не розходиться з базою. Генератор шукає
-- мітку [fills-by-trigger] і робить таку колонку необовʼязковою на вставці,
-- лишаючи її NOT NULL на читанні — тобто типи стають ТОЧНІШИМИ, а не
-- слабшими.
--
-- ЧОМУ НЕ ЗНЯЛИ NOT NULL. Це послабило б і тип на ЧИТАННІ: `directory_id` став
-- би `string | null`, і кожне місце, яке його читає, мусило б обробляти null,
-- якого не буває. Обмеження в базі правильне — неправильним було лише те, що
-- генератор про тригер не знав.
--
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/catalog-methods-trigger-comment.sql
-- ---------------------------------------------------------------------------

comment on column tosho.catalog_methods.directory_id is
  'Метод у спільному довіднику. Заповнює тригер catalog_methods_bind_directory перед записом: якщо не передано, знаходить або заводить запис у tosho.method_directory за нормалізованою назвою. Код цю колонку не передає. [fills-by-trigger]';

