-- ---------------------------------------------------------------------------
-- Затверджений тираж — прапорець на самому тиражі.
--
-- НАВІЩО. У прорахунку може бути кілька тиражів на одну позицію (180 шт і
-- 270 шт із різними цінами), і клієнт погоджує ОДИН із них. Досі цього вибору
-- не існувало ніде: «Активний тираж» на картці — то лише вкладка, відкрита в
-- браузері, а `orderRecords.ts` при створенні замовлення брав
-- `runs.find(...)`, тобто ПЕРШИЙ створений тираж. Тобто рішення клієнта не
-- зберігалось узагалі, а замовлення мовчки бралось за найстарішим варіантом.
-- Скарга менеджера 25.08.2026: «не можу обрати затверджений варіант, в
-- замовлення воно переносить все».
--
-- ЧОМУ КОЛОНКА, А НЕ ВИБІР У ВІКНІ СТВОРЕННЯ ЗАМОВЛЕННЯ. Рішення ухвалюється
-- тоді, коли клієнт відповів, — за дні до створення замовлення. Якщо не
-- записати його в цю мить, до вікна воно не доживе, і його доведеться
-- згадувати. Заразом підсумок картки перестає залежати від того, яка вкладка
-- зараз відкрита.
--
-- БЕКФІЛУ НЕМАЄ І НЕ БУДЕ. Позначити «перший тираж = затверджений» для
-- наявних прорахунків означало б вигадати бізнес-дані: ми не знаємо, що саме
-- погодив клієнт. Порожній прапорець читається кодом як «не обрано», і там,
-- де тираж один, він і так однозначний.
--
-- Застосування: npm run db:apply scripts/quote-run-approved.sql
-- ---------------------------------------------------------------------------

alter table tosho.quote_item_runs
  add column if not exists is_approved boolean not null default false;

comment on column tosho.quote_item_runs.is_approved is
  'Тираж, який погодив клієнт. Саме з нього беруться ціна й кількість у замовлення. false у всіх = вибір не зроблено.';

-- ---------------------------------------------------------------------------
-- Один затверджений тираж на позицію.
--
-- coalesce у ключі — бо `quote_item_id` буває null (старі тиражі без привʼязки
-- до позиції), а NULL в унікальному індексі не конфліктує сам із собою: без
-- coalesce обмеження на таких рядках мовчки не діяло б.
-- ---------------------------------------------------------------------------
create unique index if not exists quote_item_runs_single_approved_per_item
  on tosho.quote_item_runs (quote_id, coalesce(quote_item_id, '00000000-0000-0000-0000-000000000000'::uuid))
  where is_approved;

