-- Пошук за артикулом злазить із генерованої колонки на два індекси — REQ-178#p9.
--
-- ЩО БУЛО НЕ ТАК. `catalog_models.search_skus` (REQ-248) склеювала артикул
-- моделі з артикулами її кольорів в один текст і мала триграмний індекс. Тоді
-- це був єдиний спосіб знайти товар за кодом кольору: варіанти лежали в
-- `metadata.variants`, і шукати в JSON-масиві індексом не виходило.
--
-- ЧОМУ ЇЇ ТРЕБА ПРИБРАТИ САМЕ ЗАРАЗ. Відколи варіант став рядком
-- (`tosho.catalog_variants`, REQ-250#p1), колонка лишилась ОСТАННЬОЮ ниткою,
-- що прив'язує пошук до старого сховища: вона рахується з `metadata`, тож
-- прибрати звідти `variants` означало б тихо зламати пошук по артикулу — і
-- зламати так, що всі перевірки лишились би зеленими, бо колонка просто почала
-- б віддавати менше рядків. Ця нитка й тримала JSON живим.
--
-- ЧОМУ ДВА ІНДЕКСИ, А НЕ ОДИН. Артикул моделі й артикули її кольорів — різні
-- факти, і один з другого не виводиться. Замір на проді 07.09.2026: 71 модель
-- має власний артикул, і у 15 із них немає ЖОДНОГО варіанта. Пошук лише по
-- `catalog_variants` втратив би ці 15, пошук лише по моделі — усі коди
-- кольорів. Тому обидва джерела питаються окремо (`src/lib/quoteSkuMatches.ts`,
-- `queries.ts:fetchCatalogVariantsBySku`), і кожне має свій індекс.
--
-- Індекс по варіантах уже є — `catalog_variants_sku_trgm` із
-- scripts/catalog-variants-table.sql. Тут додається пара до нього по моделі.
--
-- ПОРЯДОК МАЄ ЗНАЧЕННЯ: спершу індекс, потім drop. Інакше між двома прогонами
-- пошук по артикулу моделі йшов би повним сканом.
--
-- Ідемпотентний: повторний прогін нічого не дублює.
--
-- Одна транзакція — від `npm run db:apply` (psql -1); свого `begin` тут немає
-- навмисно: він закривав би її раніше й ламав атомарність усього файлу.

\set ON_ERROR_STOP on

-- ── Пара до catalog_variants_sku_trgm: власний артикул моделі ────────────────
create index if not exists catalog_models_sku_trgm
  on tosho.catalog_models using gin ((metadata->>'sku') public.gin_trgm_ops);

comment on index tosho.catalog_models_sku_trgm is
  'Пошук за ВЛАСНИМ артикулом моделі (REQ-178#p9). Пара до catalog_variants_sku_trgm: '
  'у 15 моделей із 71 артикул є, а варіантів немає — самих варіантів для пошуку замало.';

-- ── Генерована колонка більше нікому не потрібна ─────────────────────────────
-- Спершу колонка (вона залежить від функції), потім сама функція.
drop index if exists tosho.catalog_models_search_skus_trgm;
alter table tosho.catalog_models drop column if exists search_skus;
drop function if exists tosho.catalog_model_search_skus(jsonb);
