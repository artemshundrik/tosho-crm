-- Забутий таймер дизайн-задачі: автозупинка на межі 8 год + нагадування.
--
-- ЩОГОДИНИ, а не раз на добу. Раніше стояло 15:10 UTC (18:10 Київ) з міркування
-- «забутий таймер — не аварія, вистачить одного нагадування ввечері». Міркування
-- виявилось хибним, бо перевірка раз на добу означає, що 8-годинна межа працює
-- лише для таймерів, запущених до ~10:10 ранку. Усе, що стартувало пізніше,
-- перетинає 8 год уже ПІСЛЯ вечірньої перевірки й висить до наступного вечора.
--
-- Так і сталось 10.08.2026: сесію запустили о 15:41, о 18:10 їй було 2.5 год
-- (крон її законно пропустив), 8 год вона перетнула о 23:41 — і провисіла до
-- ранку. Задача при цьому була спільна, і другий дизайнер не міг узятись за
-- роботу, бо в інтерфейсі задача виглядала зайнятою.
--
-- Щогодинна перевірка робить «8 годин» справді 8 годинами (± година). Спамом це
-- не стає: сповіщення дедуплікується за датою в href, тож людина отримає його
-- раз на добу, як і раніше.
--
-- ВАЖЛИВО: планувати лише ПІСЛЯ деплою функції на prod.
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/design-timer-reminders-cron.sql
-- (перепланування: select cron.unschedule('design-timer-reminders'); перед цим)
-- ---------------------------------------------------------------------------

select cron.schedule(
  'design-timer-reminders',
  '10 * * * *',
  $$ select net.http_post(
       url := 'https://tosho.pro/.netlify/functions/design-timer-reminders',
       headers := jsonb_build_object('x-cron-key', (select value from tosho.cron_config where key='cron_secret')),
       timeout_milliseconds := 30000) $$
);

