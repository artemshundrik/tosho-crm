-- Finance module — архів витрат (REQ-190).
--
-- НАВІЩО. Журнальна витрата («сума змінна») тепер коштує рівно стільки, скільки
-- в її записах: немає записів за місяць — 0 грн і бейдж «не внесено». Без способу
-- сказати «цю статтю ми більше не ведемо» закинуті витрати («Кондиціонери» з
-- нулем записів за весь час) світилися б жовтим щомісяця вічно — і бейдж
-- перестали б читати. Раніше цю роль грала умова «є історія за 3 місяці», але
-- вона ж і глушила найгучніші випадки: нову витрату з нулем записів.
--
-- Архів — це ДАТА, а не прапорець: витрата рахується в місяцях до архівації
-- включно (її записи лишаються фактом того місяця) і зникає з наступних.
-- Safe to run multiple times.

begin;

alter table tosho.finance_expenses
  add column if not exists archived_at timestamptz;

comment on column tosho.finance_expenses.archived_at is
  'Коли витрату здали в архів. Не null = у місяцях ПІСЛЯ цього її немає ні в списку, ні в підсумках; місяці до архівації лишаються як були.';

-- Під вибірку «активні витрати команди» (архівні майже завжди відфільтровані).
create index if not exists finance_expenses_team_archived_idx
  on tosho.finance_expenses (team_id, archived_at);

notify pgrst, 'reload schema';

commit;
