-- не підписує накрутку НІКОЛИ (scripts/quote-print-markup-no-accountant.sql).
--
-- Стара версія при цьому лишилась у базі й далі відповідає за старим правилом —
-- каже «так» про головбуха на поліграфічному прорахунку. Ніхто її не кличе:
-- тригер tosho.enforce_quote_markup_approval_flow() перевівся на дволанкову
-- ще в quote-print-markup-approver.sql, у застосунку виклику немає взагалі.
--
-- ЧОМУ ЦЕ НЕ «ПРОСТО СМІТТЯ». Вона видана `authenticated`, тобто жива через
-- PostgREST як rpc: будь-який залогінений користувач може її покликати й
-- отримати відповідь за скасованим правилом. Двері нікуди не ведуть — записи
-- стереже тригер, який бере правильну версію, — але табличка на дверях бреше,
-- і наступний, хто шукатиме «хто підписує накрутку», знайде дві відповіді.
--
-- Дволанкової версії це не чіпає: `drop function` розрізняє перевантаження за
-- списком аргументів, тож (uuid, uuid) лишається на місці разом із грантами.
--
-- Застосування: npm run db:apply scripts/quote-markup-approver-drop-legacy.sql
-- ---------------------------------------------------------------------------

