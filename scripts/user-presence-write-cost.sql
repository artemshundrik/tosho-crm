-- ПРИСУТНІСТЬ: 24 РЯДКИ, ЩО ВАЖИЛИ 28 МБ.
--
-- ЩО ЗАМІРЯНО 26.08.2026 на проді:
--   рядків живих            24
--   рядків мертвих          2 472
--   оновлень за 5 місяців   118 995
--   з них HOT               17  (0.014%)
--   купа                    21 МБ
--   індекси                 7.5 МБ
--
-- ЧОМУ ТАК. HOT-оновлення — це коли Postgres переписує рядок, не чіпаючи
-- індекси; саме воно тримає невеликі таблиці, які часто оновлюють, у розумному
-- розмірі. Тут воно не спрацьовує майже ніколи, і на те дві незалежні причини:
--
--   1. `user_presence_team_seen_idx` побудований по `last_seen_at`, а кожен пінг
--      присутності оновлює саме цю колонку. Оновлення індексованої колонки НЕ
--      буває HOT за визначенням.
--   2. fillfactor типовий (100): вільного місця в сторінці немає, тож новій
--      версії рядка нікуди лягти поруч зі старою — а без цього HOT неможливий
--      навіть тоді, коли індекси не заважають.
--
-- ЩО РОБИМО.
--
-- `user_presence_team_entity_idx` ПРИБИРАЄМО: за п'ять місяців у нього 0
-- сканувань, тобто його ніхто жодного разу не читав, — але кожен пінг у нього
-- пише. Це чистий податок. Запит, під який його колись заводили
-- (`getEntityViewers`), працює з даними, які вже в пам'яті клієнта, а не з бази.
--
-- `user_presence_team_seen_idx` ЛИШАЄТЬСЯ: 40 768 сканувань — він справді
-- потрібен, це вибірка «хто був онлайн за останні пів години».
--
-- fillfactor 70 — три десятих сторінки лишаємо порожніми під нові версії рядків.
-- Для таблиці на 24 рядки це дрібниця за розміром і різниця в рази за кількістю
-- записів у майбутньому.
--
-- VACUUM FULL повертає вже витрачені 28 МБ. Він бере виключне блокування, але
-- тут це не страшно: 24 рядки переписуються за мілісекунди. Стоїть ОСТАННІМ —
-- щоб зміна fillfactor уже діяла на перебудовану таблицю.
--
-- ЧОГО ЦЕЙ ФАЙЛ НЕ РОБИТЬ. Не чіпає ні даних, ні політик RLS, ні первинного
-- ключа. Присутність — величина, яку перераховують кожні кілька хвилин; навіть
-- якби рядки зникли зовсім, вони відновились би самі.

begin;

drop index if exists public.user_presence_team_entity_idx;

alter table public.user_presence set (fillfactor = 70);

commit;

-- Поза транзакцією: VACUUM усередині блоку не виконується.
vacuum (full, analyze) public.user_presence;
