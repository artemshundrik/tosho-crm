-- Пункти великої задачі: чекліст усередині картки.
--
-- НАВІЩО. Велика робота доти мала два однаково погані виходи: простиня в описі
-- (стан видно лише тому, хто її прочитав) або десяток окремих карток, які
-- ховають решту дошки. Пункти лишають роботу однією карткою й показують
-- прогрес, не відкриваючи її.
--
-- ЧОМУ jsonb, А НЕ ОКРЕМА ТАБЛИЦЯ. Пункти читаються ТІЛЬКИ разом зі своєю
-- карткою — ні фільтром, ні звітом, ні окремим списком. Таблиця дала б
-- зʼєднання на кожному відкритті дошки й нічого натомість. Коли пункт дозріє
-- до власного місця на дошці, він стане повноцінною карткою з parent_id — і це
-- вже інша сутність, а не рядок цього масиву.
--
-- ЧОТИРИ СТАНИ, А НЕ ГАЛОЧКА. Галочка змішує «ще не брались» і «чекаємо
-- відповіді від людини» — а це різні речі: перше означає «руки не дійшли»,
-- друге «зроблено все, що можна без неї». Картка з трьома пунктами в стані
-- waiting виглядає закинутою, хоча насправді заблокована, і саме через це
-- велика задача тихо зависає на тижні.
--
-- ЧОМУ ПИТАННЯ — ТЕЖ ПУНКТ. Розбір великої задачі повертає не лише роботу, а
-- й те, чого бракує, щоб братись («договір — на скільки днів строк?»).
-- Питання живе тим самим життям: воно комусь адресоване, чекає й закривається
-- відповіддю. Окрема сутність для нього породила б другий список із тими
-- самими станами.
--
-- Форма пункту:
--   {
--     "id":    "p1",                       -- стабільний у межах картки
--     "kind":  "task" | "question",
--     "text":  "Друк накладної з дошки",
--     "state": "todo" | "doing" | "waiting" | "done",
--     "group": "Документи",                -- необовʼязково
--     "who":   "CEO",                      -- на кого чекаємо
--     "since": "2026-07-28",               -- відколи чекаємо; з неї «зависло N днів»
--     "note":  "…",                        -- розгорнутий текст під рядком
--     "answer":"…"                         -- для питання: що відповіли
--   }
--
-- Перелік станів НЕ фіксуємо констрейнтом — з тієї ж причини, що й zone та
-- module_key: значення звіряє застосунок (src/features/devRequests/checklist.ts),
-- щоб у базі не завівся другий список, який розійдеться з першим.
--
-- Ідемпотентна, безпечна до повторного запуску.
-- Застосування: psql "$BACKUP_DB_URL" -f scripts/dev-requests-checklist.sql

\set ON_ERROR_STOP on

begin;

alter table tosho.dev_requests
  add column if not exists checklist jsonb not null default '[]'::jsonb;

comment on column tosho.dev_requests.checklist is
  'Пункти великої задачі. Масив обʼєктів {id, kind, text, state, group, who, since, note, answer}. Перелік станів — у src/features/devRequests/checklist.ts.';

-- Масив, а не обʼєкт: без цього одна помилка в коді перетворила б чекліст на
-- {} і всі пункти зникли б мовчки.
alter table tosho.dev_requests
  drop constraint if exists dev_requests_checklist_is_array;
alter table tosho.dev_requests
  add constraint dev_requests_checklist_is_array
  check (jsonb_typeof(checklist) = 'array');

commit;
