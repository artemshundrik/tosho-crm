-- Файл прорахунку може належати КОНКРЕТНІЙ позиції (REQ-246).
--
-- НАВІЩО. Дизайн-задача заводиться на позицію («Дизайн: Кепка ATHLETIC»), а
-- файли досі належали прорахунку цілком: `quote_attachments` має лише
-- `quote_id` і `audience`. Наслідок — на прорахунку з двома товарами обидві
-- задачі бачать один спільний список, і дизайнер кепки відкриває макет
-- горнятка. Розділити їх без цієї колонки неможливо (це прямо описано в
-- коментарі `QuoteDesignTasksPanel.tsx`).
--
-- ЧОМУ САМЕ ПОЗИЦІЯ, А НЕ ЗАДАЧА. Задача — це рядок у `public.activity_log`
-- (окремої таблиці `design_tasks` у базі немає), тож зовнішнього ключа на неї
-- не побудувати. Позиція ж — справжній рядок `quote_items`, і саме на неї
-- задача вже посилається через `metadata.quote_item_id`. Тому зв'язок
-- «файл → позиція» одночасно надійніший і корисніший: він жи́ве й до того, як
-- задачу створили, і після того, як її закрили.
--
-- ЩО З НАЯВНИМИ РЯДКАМИ. Нічого: колонка порожня за замовчуванням, а
-- порожньо означає «файл усього прорахунку» — рівно та поведінка, що була.
-- Тому міграція нічого не переписує й нічого не ламає.
--
-- `on delete set null`, а не `cascade`: прибрана позиція не має забирати з
-- собою бриф клієнта чи ескіз. Файл лишається у прорахунку, просто перестає
-- бути «чиїмось».

alter table tosho.quote_attachments
  add column if not exists quote_item_id uuid
    references tosho.quote_items (id) on delete set null;

comment on column tosho.quote_attachments.quote_item_id is
  'Позиція прорахунку, до якої належить файл. NULL — файл усього прорахунку (REQ-246).';

-- Читаємо їх завжди в межах одного прорахунку, тож індекс складений.
create index if not exists quote_attachments_quote_item_idx
  on tosho.quote_attachments (quote_id, quote_item_id);
