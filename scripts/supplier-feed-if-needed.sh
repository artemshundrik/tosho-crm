#!/usr/bin/env bash
# Перезалив важкого обходу постачальника з ЦЬОГО ноутбука, а не з GitHub.
#
# НАВІЩО ВЗАГАЛІ НЕ КРОН. `bergamo.ua` віддає GitHub-раннеру 403 на
# `sitemap.xml` — обхід падає на першому ж кроці й у базу не пише нічого
# (перевірено 12.09.2026, runs/34698079368). З ноутбука та сама адреса з тим
# самим User-Agent віддає 200 і 440 кБ: сайт ріже датацентрові адреси. Проти
# обходу Бергамо не заперечує — у їхньому ж `robots.txt` адреса мапи сайту
# опублікована, а сторінки товарів не закриті. Тобто питання не в дозволі, а
# в тому, ЗВІДКИ ходити. Картка: REQ-269.
#
# ФОРМА ТА САМА, ЩО В БЕКАПУ. `backup-database-if-needed.sh` теж кличеться
# щогодини й сам вирішує, чи пора. Причина в тому, що ноутбук не мусить бути
# ввімкненим у призначену годину: агент дожене, коли його відкриють. Крон із
# точною годиною на особистій машині просто губив би прогони.
#
# Запуск руками (наприклад, щоб не чекати тижня): SUPPLIER_FEED_MAX_AGE_DAYS=0
# bash scripts/supplier-feed-if-needed.sh bergamo
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SUPPLIER="${1:-bergamo}"
PSQL="${PSQL_BIN:-/opt/homebrew/opt/libpq/bin/psql}"

# Скільки днів каталог живе, поки ми його не перезаливаємо. Тиждень — та сама
# цифра, що стояла в неділішньому кроні: 2658 сторінок чужого сайту не
# змінюються щогодини.
MAX_AGE_DAYS="${SUPPLIER_FEED_MAX_AGE_DAYS:-7}"
# Скільки годин чекати після НЕВДАЛОЇ спроби. Без цього запобіжника впалий
# обхід (мережа, 403, обірваний прайс) повторювався б щогодини: `maxFailRatio`
# у завантажувачі не дає записати частковий обхід, тобто дата останнього заливу
# лишається старою — і ми ходили б по чужому сайту 24 рази на добу.
MIN_RETRY_HOURS="${SUPPLIER_FEED_MIN_RETRY_HOURS:-6}"

LOG_DIR="${ROOT}/logs"
mkdir -p "${LOG_DIR}"
LOCK_DIR="${LOG_DIR}/.feed-${SUPPLIER}.lock"
STAMP="${LOG_DIR}/.feed-${SUPPLIER}.attempt"

if [ -z "${BACKUP_DB_URL:-}" ]; then
  echo "$(date -u '+%Y-%m-%d %H:%M:%SZ') ${SUPPLIER}: немає BACKUP_DB_URL — підвантажте .env.backup."
  exit 1
fi

# Домен беремо з реєстру в самому завантажувачі, а не дублюємо тут: реєстр —
# єдине джерело правди про постачальника, і тест його вже стереже.
# `|| true` тут не косметика: `set -e` убиває скрипт на самій підстановці, бо
# grep без влучення повертає 1, — і повідомлення нижче не побачив би ніхто.
# Спіймано на пробі: невідомий постачальник давав молчазний код 1 у лозі агента.
SLUG="$(grep -A3 "^  ${SUPPLIER}: {" "${ROOT}/scripts/load-supplier-feed.mjs" \
  | sed -n 's/.*slug: "\([^"]*\)".*/\1/p' | head -1 || true)"
if [ -z "${SLUG}" ]; then
  echo "$(date -u '+%Y-%m-%d %H:%M:%SZ') ${SUPPLIER}: такого постачальника немає в реєстрі завантажувача."
  exit 1
fi

say() { echo "$(date -u '+%Y-%m-%d %H:%M:%SZ') ${SUPPLIER}: $*"; }

# ── чи пора ─────────────────────────────────────────────────────────────────
# Питаємо БАЗУ, а не файл-позначку, і це навмисно: залив, зроблений руками,
# так само зсуває дату. Інакше ручний прогін у середу не скасував би
# автоматичний у неділю, і ми пройшли б чужий сайт двічі за тиждень.
hours="$("${PSQL}" "${BACKUP_DB_URL}" -X -A -t -c \
  "select coalesce(floor(extract(epoch from (now() - max(updated_at)))/3600)::int, 999999)
     from tosho.supplier_products where supplier_slug = '${SLUG}'" 2>/dev/null | tr -d ' ')" || hours=""
if [ -z "${hours}" ]; then
  say "база не відповіла — спробуємо наступної години."
  exit 0
fi
if [ "${hours}" -lt $((MAX_AGE_DAYS * 24)) ]; then
  say "каталогу ${hours} год, межа $((MAX_AGE_DAYS * 24)) — ще рано."
  exit 0
fi

# ── чи не зарано після невдачі ──────────────────────────────────────────────
if [ -f "${STAMP}" ]; then
  since=$(( ( $(date +%s) - $(stat -f %m "${STAMP}") ) / 3600 ))
  if [ "${since}" -lt "${MIN_RETRY_HOURS}" ]; then
    say "попередня спроба була ${since} год тому — чекаємо ${MIN_RETRY_HOURS}."
    exit 0
  fi
fi

# ── чи не йде вже ───────────────────────────────────────────────────────────
# Обхід Бергамо триває ~35 хвилин, а агент прокидається щогодини: за поганого
# збігу дві копії пішли б по чужому сайту одночасно. `mkdir` атомарний, тож
# годиться як замок без зовнішніх залежностей.
if ! mkdir "${LOCK_DIR}" 2>/dev/null; then
  say "обхід уже йде (замок ${LOCK_DIR}) — нічого не робимо."
  exit 0
fi
trap 'rmdir "${LOCK_DIR}" 2>/dev/null || true' EXIT

touch "${STAMP}"
say "каталогу ${hours} год — заливаємо."
# Рядки поступу (їх сотні) до логу не тягнемо, але статус беремо в САМОГО
# завантажувача через PIPESTATUS, а не в `grep`: за `pipefail` успішний обхід,
# усі рядки якого відфільтрувались, прозвітував би «не залилось».
set +e
node "${ROOT}/scripts/load-supplier-feed.mjs" "${SUPPLIER}" 2>&1 | grep -vE '^  пройдено '
status=${PIPESTATUS[0]}
set -e
if [ "${status}" = "0" ]; then
  say "готово."
else
  say "не залилось (код ${status}) — каталог у базі лишився попереднім, повторимо через ${MIN_RETRY_HOURS} год."
  exit 1
fi
