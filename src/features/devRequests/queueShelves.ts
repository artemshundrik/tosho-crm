/**
 * Полиці «Черги» — вигляду, який відповідає на «за що хвататись».
 *
 * НАВІЩО НЕ КОЛОНКИ. Колонка каже, на якому етапі картка. Це правильне питання
 * для того, хто рухає роботу через процес, і зайве для того, хто щоранку обирає
 * наступну справу. Замір 26.08.2026: 27 карток із 50 стояли у «Вхідних» — тобто
 * 54% дошки в першій колонці, і три чверті ширини екрана займали майже порожні
 * стовпчики.
 *
 * ПОЛИЦІ ВІДПОВІДАЮТЬ НА РІЗНІ ПИТАННЯ, а не на різні етапи:
 *   `today`      — що я взяв на сьогодні (максимум три, обирає людина);
 *   `free`       — що можна брати просто зараз: нічого не блокує;
 *   `blocked`    — що стоїть НЕ через мене: у чекліста є пункт «Чекає»;
 *   `papercuts`  — накопичувачі дрібниць: одна картка на напрям, назавжди;
 *   `shipped`    — зроблено локально, чекає найближчого деплою;
 *   `triage`     — ще не розібрано; згорнуте, бо це робота на раз на тиждень.
 *
 * ЧОМУ ЦЕ ЧИСТА ФУНКЦІЯ. Полиці — це правила, а не верстка: «заблоковане не
 * може лежати в „можна брати“» має бути перевіряним твердженням, а не
 * випадковим наслідком порядку умов у JSX.
 */

export type QueueShelfId = "today" | "free" | "blocked" | "papercuts" | "shipped" | "triage";

export type QueueShelves = Record<QueueShelfId, DevRequest[]>;

/**
 * Стелі на «Сьогодні» НЕМАЄ — рішення Артема 27.08.2026.
 *
 * Спершу тут стояло три місця, і обмеження вважалось сенсом полиці: три справи
 * на день — це стільки, скільки людина справді встигає, а четверта позиція
 * перетворює полицю на другий беклог. Артем це правило зняв: у нього день не
 * ділиться на три однакові шматки, і дрібне впереміш із великим на три місця не
 * лягає.
 *
 * Що з цього лишається справедливим: полиця має чиститись. Тому `pruneToday`
 * нікуди не подівся — картка, яку викотили чи відхилили, зникає з неї сама,
 * інакше без стелі вона за тиждень стане списком позавчорашніх намірів.
 */

/**
 * Позначка картки-накопичувача дрібниць.
 *
 * НАВІЩО ВОНИ ВЗАГАЛІ. Замір 26.08.2026 пояснив, звідки береться приплив у сім
 * карток на день: 59 викочених карток зі 103 закрились ОДНИМ комітом. Тобто
 * більшість — це дрібниця, якій картка з темою, типом, зоною, напрямком і
 * пріоритетом важча за саму роботу. Практика зветься papercuts і давно
 * відпрацьована в Ubuntu, GitHub і Linear: дрібний баг не заводить окремої
 * задачі, а стає рядком у постійному списку свого напряму. Такі картки не
 * закриваються ніколи — їх розгрібають пачкою, коли доходять руки.
 *
 * ЧОМУ ЗА НАЗВОЮ, А НЕ ЗА НОВИМ ПОЛЕМ. Прапорець у базі довелось би заводити
 * міграцією, тримати у формі й пояснювати — заради ознаки, яку людина й так
 * бачить у назві. Префікс читається однаково і в CRM, і в Telegram, і в списку
 * запитів, а картка лишається звичайною карткою: її можна фільтрувати,
 * коментувати й закрити, якщо напрям віджив.
 */
export const PAPERCUT_PREFIX = "Дрібниці:";

/** Чи це накопичувач дрібниць. Регістр і зайві пробіли значення не мають. */
export function isPapercutCard(request: Pick<DevRequest, "title">): boolean {
  return request.title.trim().toLowerCase().startsWith(PAPERCUT_PREFIX.toLowerCase());
}

/** Назва напряму з назви картки: «Дрібниці: мова інтерфейсу» → «мова інтерфейсу». */
export function papercutLabel(request: Pick<DevRequest, "title">): string {
  const title = request.title.trim();
  return title.slice(PAPERCUT_PREFIX.length).trim() || title;
}

/**
 * Розкладка карток по полицях.
 *
 * ПОРЯДОК ПЕРЕВІРОК ВАЖЛИВИЙ і саме тому зафіксований тестами. Картка потрапляє
 * рівно на одну полицю, а перша ознака сильніша за наступні:
 *
 * 1. «Взято на сьогодні» — сильніше за все: якщо людина сама поклала картку в
 *    роботу на день, вона має бачити її вгорі, навіть коли та заблокована.
 * 2. «Не розібрано» — сильніше за «заблоковане»: нерозібрана картка не може
 *    претендувати ні на «беру», ні на «чекаю», бо про неї ще нічого не вирішено.
 * 3. «Готово локально» — окремо від решти: рішень не потребує, лише деплою.
 * 4. «Стоїть за людьми» — перед «можна брати», інакше картка, яка чекає на СЕО
 *    27 днів, лежала б у списку доступного й щодня марно претендувала на увагу.
 */
export function splitQueue(requests: DevRequest[], todayIds: readonly string[]): QueueShelves {
  const today = new Set(todayIds);
  const shelves: QueueShelves = {
    today: [],
    free: [],
    blocked: [],
    papercuts: [],
    shipped: [],
    triage: [],
  };

  for (const request of requests) {
    if (today.has(request.id)) shelves.today.push(request);
    else if (request.status === "triage") shelves.triage.push(request);
    // Накопичувач перевіряємо ДО решти: він ніколи не буває ні готовим, ні
    // заблокованим — у нього просто інше призначення, і в списку доступного він
    // щодня вдавав би роботу, якої ніхто не бере.
    else if (isPapercutCard(request)) shelves.papercuts.push(request);
    // БЛОКУВАННЯ СИЛЬНІШЕ ЗА «ГОТОВО ЛОКАЛЬНО» — правило перевернуто 27.08.2026.
    // Доти картка зі статусом «Готово локально» одразу йшла в «чекає деплою», і
    // перевірка на блокування до неї не доходила. На проді це давало неправду:
    // REQ-123 стояла в «чекає деплою», хоч її хвіст чекав на чужий реліз
    // typescript-eslint — жоден наш пуш його не наближає. Полиця обіцяла, що
    // досить викотити, і брехала. Тепер спершу питаємо, чи стоїть воно за
    // людиною: якщо так — це «Стоїть за людьми», хоч би скільки коду вже було
    // написано.
    else if (isBlockedOnPerson(request)) shelves.blocked.push(request);
    else if (request.status === "done_local") shelves.shipped.push(request);
    else shelves.free.push(request);
  }

  return shelves;
}

/**
 * Чи можна цю картку взяти на сьогодні.
 *
 * Нерозібране й готове-локально сюди не пускаємо: перше ще не рішення, друге
 * рішень уже не потребує. Заблоковане пускаємо свідомо — буває, що саме сьогодні
 * ти й збираєшся вибити ту відповідь.
 */
export function canTakeToday(request: DevRequest): boolean {
  // Накопичувач дрібниць брати МОЖНА — правило змінено 27.08.2026 разом зі
  // зняттям стелі. Доти воно спиралось рівно на неї: полиця мала три місця, і
  // список, який не закінчується, зайняв би одне назавжди. Місць більше не
  // рахують, а «сьогодні розгрібаю дрібниці мови інтерфейсу» — цілком нормальний
  // намір на день.
  return request.status === "queued" || request.status === "in_progress";
}

/**
 * Чистка вибраного на сьогодні.
 *
 * Картка, яку викотили або відхилили, зникає з полиці сама — інакше «Сьогодні»
 * за тиждень перетворилась би на список позавчорашніх намірів, а місця в ній
 * рівно три. Порядок збережених id зберігаємо: він і є порядком, у якому людина
 * їх туди клала.
 */
export function pruneToday(ids: readonly string[], requests: DevRequest[]): string[] {
  const alive = new Map(requests.map((request) => [request.id, request]));
  return ids.filter((id) => {
    const request = alive.get(id);
    return request ? canTakeToday(request) : false;
  });
}

