import { pluralUk } from "@/lib/lastSeen";
import type { DevRequest } from "./types";

/**
 * Чиста логіка картки на дошці запитів.
 *
 * Винесена з компонента навмисно: тут правила, які легко зламати непомітно —
 * «звичайний пріоритет не підписуємо», «порожній напрямок називаємо словами»
 * і «кнопка меню не починає перетягування». У JSX кожне виглядає як дрібниця,
 * а ламається тихо, тож усі живуть окремо й під тестами.
 */

/**
 * Позначка на обгортці меню картки.
 *
 * Атрибут, а не клас: класи на дошці міняє верстка, і випадкове
 * перейменування мовчки повернуло б перетягування картки за кнопку меню.
 */
export const CARD_MENU_ATTR = "data-request-card-menu";

type ClosestCapable = { closest?: (selector: string) => unknown };

/**
 * Чи жест почався всередині меню картки.
 *
 * НАВІЩО: перевірити це в самому `dragstart` не вийде — подія стріляє на
 * КАРТЦІ (джерело перетягування — найближчий draggable-предок), тож із
 * `event.target` не видно, що миша натиснула кнопку меню. Тому дивимось на
 * `pointerdown`, який приходить першим у ланцюжку подій натискання.
 */
export function isCardMenuTarget(target: unknown): boolean {
  const node = target as ClosestCapable | null;
  if (!node || typeof node.closest !== "function") return false;
  return node.closest(`[${CARD_MENU_ATTR}]`) != null;
}

/** Чим відкрили меню картки. */
export type MenuOpenSource = "pointer" | "keyboard";

/**
 * Чи повертати фокус на «⋯» після того, як меню закрилось.
 *
 * НАВІЩО: Radix після закриття сам ставить фокус назад на кнопку. Для
 * клавіатури це єдиний правильний хід — інакше Tab почав би обхід сторінки
 * спочатку. Але браузер вважає такий програмний фокус «як з клавіатури» й
 * малює навколо кнопки рінг, тож після кліку мишею на картці лишався синій
 * ореол, який нічим не прибрати, крім кліку деінде.
 *
 * Тому фокус повертаємо рівно тому, хто ним користується. Глушити сам рінг
 * (`focus:outline-none` чи `focus-visible:ring-0`) — не варіант: він єдине,
 * що показує клавіатурному користувачу, де він зараз.
 */
export function shouldRestoreMenuFocus(source: MenuOpenSource): boolean {
  return source === "keyboard";
}

/**
 * Наскільки гучно звучить мітка.
 *  - `loud` — видно з відстані (терміново);
 *  - `normal` — рядова мітка;
 *  - `quiet` — присутня, але не тягне на себе увагу (не горить, порожній
 *    напрямок).
 */
export type ChipWeight = "quiet" | "normal" | "loud";

export type CardMetaKey = "zone" | "theme" | "module" | "author" | "asked" | "private";

export type CardMeta = {
  key: CardMetaKey;
  label: string;
  weight: ChipWeight;
  /** Підказка на наведення: нікнейм автора, пояснення лічильника. */
  hint?: string;
};

/**
 * Як підписано напрямок, якого ще немає. ТІЛЬКИ для дровера.
 *
 * На КАРТЦІ цього підпису більше немає (див. buildCardMeta). Він мав робити
 * пропуск видимим, але вийшло навпаки: розбір лишає напрямок порожнім часто, і
 * чіп «напрямок не визначено» стояв майже на кожній картці — однаковий,
 * найдовший у ряду й ні про що. Дошку сканують очима, і такий чіп там просто
 * шум, що витісняє тему, зону й автора.
 *
 * У дровері підпис лишається: там це відповідь на пряме питання «який
 * напрямок», і порожній рядок справді читався б як «поля немає».
 */
export const MODULE_UNSET_LABEL = "напрямок не визначено";

export type CardMetaOptions = {
  /**
   * Хто дивиться. Свій автор із мітки зникає: усі картки заводить власник, і
   * підпис «Артем» стояв на кожній — однаковий, найдовший у ряду й ні про що.
   * Чужий автор лишається: саме він і є інформацією («це просила Юлія»).
   */
  viewerId?: string | null;
};

/**
 * Нижній рядок картки: зона, тема, напрямок, автор, «просили N», «закрита».
 *
 * Ані типу, ані пріоритету тут немає — обидва підняті у верхній рядок: тип
 * словом і тоном (KIND_TONE/KIND_ICONS), пріоритет стовпчиками (PriorityBars).
 * Пріоритет пішов звідси 2026-08-09: чіп зі словом можна лише прочитати, а
 * пріоритет сканують по колонці згори вниз, не читаючи.
 *
 * ПОРЯДОК: тема → від кого → сигнали. Тема першою й єдина кольорова — вона ж
 * вісь, за якою дошку групують, тож слугує якорем, від якого око читає решту.
 * Правило кольору одне на весь ряд: кольорова рівно одна мітка. Доти цю роль
 * грала зона, але зони на картці більше немає (див. нижче).
 *
 * Ця функція — ЄДИНЕ джерело нижнього ряду для всіх виглядів (дошка, стіна
 * «Ідей»). Малювати мітки окремо в компоненті не можна: саме так вони й
 * розійшлися між дошкою та «Ідеями» першого разу.
 */
export function buildCardMeta(request: DevRequest, options: CardMetaOptions = {}): CardMeta[] {
  const meta: CardMeta[] = [];

  // ЗОНИ Й НАПРЯМКУ ТУТ БІЛЬШЕ НЕМАЄ — рішення 26.08.2026, і воно скасовує
  // спробу 2026-08-09 «сховати найчастішу зону». Тоді лікували не той бік:
  // здавалося, що мітка не працює через одне значення на 12 картках із 17.
  //
  // Замір 26.08.2026 показав справжню біду. Карток стало 50, у них 137 сірих
  // чипів, і 38 карток носили по три класифікації одразу: зона («що чіпає»),
  // напрямок («де в CRM») і тема («яка це справа»). Три осі на кожній картці —
  // це поля для ФІЛЬТРІВ, намальовані як оздоблення. Роботу за ними не
  // обирають: ніхто не бере задачу тому, що в неї зона «Вигляд».
  //
  // Що коштувала ця тріада: на картці лишалось непоміченим те, що справді
  // вирішує, — підпис «чекає СЕО · 27 дн» із ChecklistBar. Він там був увесь
  // час, тим самим кеглем, четвертим у ряду однакових плашок.
  //
  // Зона й напрямок нікуди не зникли: вони лишаються у фільтрах дошки, у
  // дровері картки і в групуванні. З КАРТКИ прибрано саме показ.
  if (request.theme) {
    meta.push({
      key: "theme",
      label: request.theme,
      weight: "normal",
      hint: "Тема: інші картки цієї ж роботи",
    });
  }

  const isOwnCard =
    Boolean(options.viewerId) && request.authorUserId === options.viewerId;
  const author = isOwnCard ? null : resolveAuthor(request);
  if (author) {
    meta.push({ key: "author", label: author.label, weight: "normal", hint: author.hint });
  }

  if (request.askedByCount > 1) {
    meta.push({
      key: "asked",
      label: `просили ${request.askedByCount}`,
      weight: "normal",
      hint: "Стільки людей просили те саме",
    });
  }

  if (request.isPrivate) {
    meta.push({
      key: "private",
      label: "закрита",
      weight: "normal",
      hint: "Видно лише власнику й CEO",
    });
  }

  return meta;
}

/**
 * Чи підсвічувати картку цілком.
 *
 * Правило те саме, що й у гучної мітки, і тримається однією функцією
 * навмисно: підсвітка картки й слово «Терміново» мають вмикатись разом. Якби
 * умова стояла в JSX окремо, вони б із часом розійшлись — і на дошці
 * зʼявилась би червона картка без пояснення або пояснення без картки.
 */
export function isUrgentCard(request: DevRequest): boolean {
  return request.priority === "high";
}

const DAY_MS = 24 * 60 * 60 * 1000;
/** Місяць у днях — рівно, без календаря: різниця в 1-2 дні на такій шкалі нічого не значить. */
const DAYS_IN_MONTH = 30;
const DAYS_IN_YEAR = 365;

/**
 * «Лежить 7 місяців» — вік картки в списку «Ідеї».
 *
 * НАВІЩО: купа відкладеного тим і небезпечна, що виглядає однаково свіжою в
 * будь-якому віці. Без віку «Ідеї» за пів року стають другим цвинтарем — тим
 * самим, від якого їх і відділяли від черги. Мітка тримає це видимим: коли
 * зазираєш у список, одразу зрозуміло, що більшість старих ідей уже не про цю
 * CRM. Це НЕ нагадування й не сповіщення — нічого не спрацьовує й нікого не
 * смикає, картка просто носить свій вік із собою.
 *
 * ШКАЛА ГРУБА НАВМИСНО: дні → місяці → роки, і завжди одна одиниця. Тут
 * потрібне «давно чи ні», а не точність: «лежить 7 місяців 12 днів» додає
 * знаків і не додає жодного рішення. Тому й формат свій, а не formatLastSeenAgo
 * (той показує дві суміжні одиниці — це правильно для «коли людину бачили», але
 * надлишково для «коли це записали»). Відмінювання спільне — pluralUk.
 *
 * null — дати немає або вона нечитабельна: краще без мітки, ніж «лежить NaN».
 */
export function formatIdleAge(createdAt: string, now: Date = new Date()): string | null {
  const created = new Date(createdAt).getTime();
  if (Number.isNaN(created)) return null;

  const days = Math.floor(Math.max(0, now.getTime() - created) / DAY_MS);
  if (days < 1) return "сьогодні";
  if (days < DAYS_IN_MONTH) return `лежить ${pluralUk(days, "день", "дні", "днів")}`;
  if (days < DAYS_IN_YEAR) {
    return `лежить ${pluralUk(Math.floor(days / DAYS_IN_MONTH), "місяць", "місяці", "місяців")}`;
  }
  return `лежить ${pluralUk(Math.floor(days / DAYS_IN_YEAR), "рік", "роки", "років")}`;
}

/**
 * Скільки днів картка лежить. Поруч із formatIdleAge, а не замість: підпис
 * читає людина, а число потрібне тому, хто вирішує, чи підсвічувати вік.
 * Розбирати підпис назад у дні («чи є там слово „місяців“») — саме той спосіб
 * зламатись тихо, від якого тут і рятує окрема функція.
 */
export function idleDays(createdAt: string, now: Date = new Date()): number {
  const created = new Date(createdAt).getTime();
  if (Number.isNaN(created)) return 0;
  return Math.floor(Math.max(0, now.getTime() - created) / DAY_MS);
}

/**
 * Автор картки: ім'я з Telegram, а якщо його немає — нікнейм.
 *
 * Обидва поля необов'язкові й незалежні: у Telegram username можна не мати
 * взагалі. Показувати лише «@username» означало б, що частина карток лишиться
 * без автора; показувати обидва — шум у мета-рядку, тож нікнейм ховаємо в
 * підказку, коли ім'я вже видно.
 */
export function resolveAuthor(request: DevRequest): { label: string; hint?: string } | null {
  if (request.displayName) {
    return {
      label: request.displayName,
      hint: request.tgUsername ? `@${request.tgUsername}` : undefined,
    };
  }
  if (request.tgUsername) return { label: `@${request.tgUsername}` };
  return null;
}
