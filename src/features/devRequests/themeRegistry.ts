/**
 * Напрям картки: іконка й тон на кожну тему.
 *
 * НАВІЩО. `theme` у базі — вільний рядок (scripts/dev-requests-zone-theme.sql),
 * і це свідомо: нормалізувати тему в окрему таблицю означало б завести дерево
 * зі статусами, які конфліктують між батьком і дітьми. Але вільний рядок не
 * має вигляду, і 26.08.2026 усі дванадцять тем виглядали однаковою фіолетовою
 * пігулкою з однаковою іконкою шарів. Мітка, однакова на п'ятдесяти картках, —
 * це вже не мітка, а шпалери.
 *
 * ЩО ТУТ Є, А ЧОГО НЕМАЄ. Тут лише ВИГЛЯД. Перелік тем не тримається цим
 * файлом: тема, якої тут немає, працює як була — просто без свого кольору
 * (див. `themeLook`). Тобто реєстр не може заблокувати нову тему й не мусить
 * оновлюватись раніше за неї.
 *
 * ТРИ ТОНИ ТЕМАМ НЕ ДАЮТЬСЯ ВЗАГАЛІ — вони зайняті СТАНОМ:
 *   `warning` — «чекає СЕО · 27 дн» (ChecklistBar);
 *   `accent`  — «частина в проді» (там-таки);
 *   `danger`  — термінова картка підсвічується цілком.
 * Перша спроба цього реєстру віддала «гроші замовлення» тону `warning`, а
 * «мову інтерфейсу» — `accent`, і на дошці це побачилось одразу: на REQ-15
 * жовтий чип теми стояв упритул до жовтого «чекає СЕО», на REQ-151 фіолетова
 * тема — поруч із фіолетовим «частина в проді». Стан і належність почали
 * означати одне й те саме, тобто нічого. Правило звідси й народилось: КОЛІР
 * СТАНУ СИЛЬНІШИЙ ЗА КОЛІР НАЛЕЖНОСТІ, і теми в нього не лізуть.
 *
 * ЧОМУ ІКОНКИ РІЗНІ, А ТОНИ ПОВТОРЮЮТЬСЯ. Після вирахування трьох зайнятих
 * лишається п'ять тонів на дванадцять тем. Це не бідність палітри, а межа ока:
 * більше ніж вісім кольорових категорій людина все одно не розрізняє — тому
 * практика й радить не заводити дев'ятий колір, а групувати. Тож ідентичність
 * несе ІКОНКА (унікальна в усіх дванадцяти), а тон лише групує. Колір ніколи
 * не єдина ознака — і напис із назвою теми стоїть поруч завжди.
 *
 * Найбільші напрями отримали найрозрізненіші тони; збіги лишились серед тем на
 * одну-три картки, де плутати нічого. Заміряно валідатором палітри: найгірша
 * пара при нормальному зорі ΔE 25.7 — з великим запасом; пара
 * `festive`↔`success` при дальтонізмі дає 6.1, і це саме той випадок, коли
 * практика дозволяє такий розрив за наявності другої ознаки — у нас їх дві,
 * іконка й підпис.
 */

export type ThemeLook = {
  icon: ComponentType<{ className?: string }>;
  tone: Tone;
};

/**
 * Тема → вигляд. Ключ — рядок теми в базі, дослівно.
 *
 * Порядок записів — за розміром напряму на 26.08.2026: найбільші вгорі. Так
 * видно, кому дістались найрізкіші тони, і що зіткнення тонів лишились лише
 * серед дрібних тем, де сплутати нічого.
 */
export const THEME_LOOK: Record<string, ThemeLook> = {
  // Три найбільші напрями — три найрозрізненіші тони з дозволених.
  "гроші замовлення": { icon: Banknote, tone: "teal" },
  "мова інтерфейсу": { icon: Palette, tone: "festive" },
  "довіра до релізу": { icon: ShieldCheck, tone: "success" },
  "економіка прорахунку": { icon: Calculator, tone: "info" },
  // Далі напрями на три картки й менше: тони починають повторюватись, і це
  // нормально — на дошці вони майже ніколи не стоять поруч, а іконка своя.
  "особистий бот": { icon: Bot, tone: "teal" },
  "знання й анонси": { icon: BookOpen, tone: "info" },
  стек: { icon: Package, tone: "success" },
  обговорення: { icon: MessagesSquare, tone: "festive" },
  // Наскрізне й службове — навмисно тихе: воно не має відтягувати око від
  // продуктових напрямів, заради яких на дошку й дивляться.
  "зовнішні сервіси": { icon: Plug, tone: "neutral" },
  "майстерня Claude": { icon: Wrench, tone: "neutral" },
  "мобільна адаптація": { icon: Smartphone, tone: "neutral" },
  поліграфія: { icon: Printer, tone: "neutral" },
};

/**
 * Вигляд теми, якої в реєстрі немає.
 *
 * Шари — навмисно найзагальніша іконка з усіх: вона має читатись як «тема без
 * свого обличчя», а не претендувати на сенс. Нейтральний тон із тієї ж
 * причини.
 */
export const THEME_FALLBACK: ThemeLook = { icon: Layers, tone: "neutral" };

/**
 * Вигляд теми. Порожня тема вигляду не має взагалі — і це не те саме, що
 * невідома: у першому випадку мітки немає, у другому вона є, але сіра.
 */
export function themeLook(theme: string | null | undefined): ThemeLook | null {
  const key = (theme ?? "").trim();
  if (!key) return null;
  return THEME_LOOK[key] ?? THEME_FALLBACK;
}

/** Чи має тема власний вигляд у реєстрі. Для тестів і для сторінки Dev. */
export function isKnownTheme(theme: string | null | undefined): boolean {
  const key = (theme ?? "").trim();
  return key in THEME_LOOK;
}

/** Усі теми реєстру — для фільтра дошки й вітрини. Порядок як в об'єкті. */
export const KNOWN_THEMES = Object.keys(THEME_LOOK);
