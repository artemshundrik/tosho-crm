/**
 * Напрям картки: іконка й тон на кожну тему.
 *
 * НАВІЩО. `theme` у базі — вільний рядок (scripts/dev-requests-zone-theme.sql),
 * і це свідомо: нормалізувати тему в окрему таблицю означало б завести дерево
 * зі статусами, які конфліктують між батьком і дітьми. Але вільний рядок не
 * має вигляду, і 26.08.2026 усі дванадцять тем виглядали однаковою фіолетовою
 * пігулкою з однаковою іконкою шарів. Мітка, однакова на п'ятдесяти картках, —
 * це вже не мітка, а шпалери.
 *
 * ЩО ТУТ Є, А ЧОГО НЕМАЄ. Тут лише ВИГЛЯД. Перелік тем не тримається цим
 * файлом: тема, якої тут немає, працює як була — просто без свого кольору
 * (див. `themeLook`). Тобто реєстр не може заблокувати нову тему й не мусить
 * оновлюватись раніше за неї.
 *
 * ПРАВИЛА ВИБОРУ Й НАЗВИ ТЕМИ — у docs/DEV_REQUESTS_DESIGN.md §7.4. Коротко:
 * тема заводиться від ДВОХ карток, назва — 2-3 слова з малої, синонім наявної
 * теми не заводиться ніколи. Цей файл — те, де нова тема отримує обличчя, і
 * заразом джерело підказок у полі «Тема» (`KNOWN_THEMES` → `NewDevRequestDialog`).
 *
 * ТРИ ТОНИ ТЕМАМ НЕ ДАЮТЬСЯ ВЗАГАЛІ — вони зайняті СТАНОМ:
 *   `warning` — «чекає СЕО · 27 дн» (ChecklistBar);
 *   `accent`  — «частина в проді» (там-таки);
 *   `danger`  — термінова картка підсвічується цілком.
 * Перша спроба цього реєстру віддала «гроші замовлення» тону `warning`, а
 * «мову інтерфейсу» — `accent`, і на дошці це побачилось одразу: на REQ-15
 * жовтий чип теми стояв упритул до жовтого «чекає СЕО», на REQ-151 фіолетова
 * тема — поруч із фіолетовим «частина в проді». Стан і належність почали
 * означати одне й те саме, тобто нічого. Правило звідси й народилось: КОЛІР
 * СТАНУ СИЛЬНІШИЙ ЗА КОЛІР НАЛЕЖНОСТІ, і теми в нього не лізуть.
 *
 * ЧОМУ ІКОНКИ РІЗНІ, А ТОНИ ПОВТОРЮЮТЬСЯ. Після вирахування трьох зайнятих
 * лишається п'ять тонів на вісімнадцять тем. Це не бідність палітри, а межа
 * ока: більше ніж вісім кольорових категорій людина все одно не розрізняє —
 * тому практика й радить не заводити дев'ятий колір, а групувати. Тож
 * ідентичність несе ІКОНКА (унікальна в усіх вісімнадцяти), а тон лише групує.
 * Колір ніколи не єдина ознака — і напис із назвою теми стоїть поруч завжди.
 *
 * ЩО САМЕ ГРУПУЄ ТОН — з 29.08.2026 не «розмір напряму», а РОДИНА:
 *   `teal`    — гроші, які рухаються: замовлення, щомісячні рахунки, бот-гаманець;
 *   `festive` — обличчя CRM: мова інтерфейсу, екран входу, обговорення;
 *   `success` — довіра до інженерії: реліз, стек, дошка запитів;
 *   `info`    — прорахунок і знання;
 *   `neutral` — наскрізне й службове: воно навмисно тихе й не має відтягувати
 *               око від продуктових напрямів, заради яких на дошку й дивляться.
 * Так тон перестав бути випадковим: до 29.08 він роздавався за розміром теми,
 * і «стек» виявився зеленим просто тому, що в ньому було чотири картки. Родина
 * пояснює, чому дві теми одного кольору, — розмір не пояснював нічого.
 *
 * НОВИХ ТОНІВ НЕ З'ЯВИЛОСЬ. П'ять нових тем 29.08.2026 узяли тони, які в
 * наборі вже були, тож замір палітри лишається чинним: найгірша пара при
 * нормальному зорі ΔE 25.7 — з великим запасом; пара `festive`↔`success` при
 * дальтонізмі дає 6.1, і це саме той випадок, коли практика дозволяє такий
 * розрив за наявності другої ознаки — у нас їх дві, іконка й підпис.
 */

export type ThemeLook = {
  icon: ComponentType<{ className?: string }>;
  tone: Tone;
};

