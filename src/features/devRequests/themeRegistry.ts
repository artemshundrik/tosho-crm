/**
 * Вигляд теми, якої в реєстрі немає.
 *
 * Шари — навмисно найзагальніша іконка з усіх: вона має читатись як «тема без
 * свого обличчя», а не претендувати на сенс. Нейтральний тон із тієї ж
 * причини.
 */
export const THEME_FALLBACK: ThemeLook = { icon: Layers, tone: "neutral" };

/**
 * Вигляд теми. Порожня тема вигляду не має взагалі — і це не те саме, що
 * невідома: у першому випадку мітки немає, у другому вона є, але сіра.
 */
export function themeLook(theme: string | null | undefined): ThemeLook | null {
  const key = (theme ?? "").trim();
  if (!key) return null;
  return THEME_LOOK[key] ?? THEME_FALLBACK;
}

/** Чи має тема власний вигляд у реєстрі. Для тестів і для сторінки Dev. */
export function isKnownTheme(theme: string | null | undefined): boolean {
  const key = (theme ?? "").trim();
  return key in THEME_LOOK;
}

/** Усі теми реєстру — для фільтра дошки, вітрини й підказок у формі. */
export const KNOWN_THEMES = Object.keys(THEME_LOOK);
