import {
  Banknote,
  BookOpen,
  Bot,
  Layers,
  MessagesSquare,
  Package,
  Palette,
  Plug,
  Receipt,
  ShieldCheck,
  Wrench,
} from "lucide-react";
import type { ComponentType } from "react";

import type { Tone } from "@/lib/statusTones";

/**
 * Напрям картки: іконка й тон на кожну тему.
 *
 * НАВІЩО. `theme` у базі — вільний рядок (scripts/dev-requests-zone-theme.sql),
 * і це свідомо: нормалізувати тему в окрему таблицю означало б завести дерево
 * зі статусами, які конфліктують між батьком і дітьми. Але вільний рядок не
 * має вигляду, і 26.08.2026 усі теми виглядали однаковою фіолетовою пігулкою з
 * однаковою іконкою шарів. Мітка, однакова на п'ятдесяти картках, — це вже не
 * мітка, а шпалери.
 *
 * ЩО ТУТ Є, А ЧОГО НЕМАЄ. Тут лише ВИГЛЯД. Перелік тем не тримається цим
 * файлом: тема, якої тут немає, працює як була — просто без свого кольору
 * (див. `themeLook`). Тобто реєстр не може заблокувати нову тему й не мусить
 * оновлюватись раніше за неї.
 *
 * ЧОМУ ТЕМ РІВНО ДЕСЯТЬ. 29.08.2026 їх було вісімнадцять — і це виявилось
 * гірше за початкову «Без теми». Роздрібнення робить рівно те, від чого тема
 * рятує: «екран входу», «мова інтерфейсу», «картка прорахунку» й «мобільна
 * адаптація» — чотири групи однієї роботи; «гроші замовлення», «економіка
 * прорахунку», «процес прорахунку» — три групи одного напряму. Артем на це
 * сказав: «ти це розбиваєш прямо капець», і був правий — щоб побачити весь
 * інтерфейс, доводилось тримати в голові, під якою з чотирьох міток його
 * шукати. Правила, які втримують теми крупними, — у
 * docs/DEV_REQUESTS_DESIGN.md §7.4; коротко: сторінка чи екран темою не буває,
 * нова тема заводиться від ТРЬОХ карток, а тема, у якій лишилась одна, —
 * підводиться під сусідню.
 *
 * ТРИ ТОНИ ТЕМАМ НЕ ДАЮТЬСЯ ВЗАГАЛІ — вони зайняті СТАНОМ:
 *   `warning` — «чекає СЕО · 27 дн» (ChecklistBar);
 *   `accent`  — «частина в проді» (там-таки);
 *   `danger`  — термінова картка підсвічується цілком.
 * Перша спроба цього реєстру віддала «гроші замовлення» тону `warning`, а
 * «мову інтерфейсу» — `accent`, і на дошці це побачилось одразу: на REQ-15
 * жовтий чип теми стояв упритул до жовтого «чекає СЕО», на REQ-151 фіолетова
 * тема — поруч із фіолетовим «частина в проді». Стан і належність почали
 * означати одне й те саме, тобто нічого. Правило звідси й народилось: КОЛІР
 * СТАНУ СИЛЬНІШИЙ ЗА КОЛІР НАЛЕЖНОСТІ, і теми в нього не лізуть.
 *
 * ТОН ГРУПУЄ, ІКОНКА РОЗРІЗНЯЄ. Після вирахування трьох зайнятих лишається
 * п'ять тонів — і на десять тем це рівно по дві на тон, тобто пари, а не
 * випадкові збіги:
 *   `teal`    — гроші: ті, що приходять із замовлень, і ті, що йдуть щомісяця;
 *   `festive` — обличчя CRM: інтерфейс і розмова в картці;
 *   `success` — інженерія: щоб не впало і щоб не застаріло;
 *   `info`    — люди й знання: анонси, вікі, особистий бот;
 *   `neutral` — службове: воно навмисно тихе й не має відтягувати око від
 *               продуктових напрямів, заради яких на дошку й дивляться.
 * До 29.08.2026 тон роздавався за розміром теми, і «стек» був зеленим просто
 * тому, що в ньому лежало чотири картки. Родина пояснює, чому дві теми одного
 * кольору, — розмір не пояснював нічого.
 *
 * Набір тонів не мінявся від першого заміру палітри, тож він лишається
 * чинним: найгірша пара при нормальному зорі ΔE 25.7 — з великим запасом; пара
 * `festive`↔`success` при дальтонізмі дає 6.1, і це саме той випадок, коли
 * практика дозволяє такий розрив за наявності другої ознаки — у нас їх дві,
 * іконка й підпис.
 */

export type ThemeLook = {
  icon: ComponentType<{ className?: string }>;
  tone: Tone;
};

/**
 * Тема → вигляд. Ключ — рядок теми в базі, дослівно.
 *
 * Порядок — парами за родиною тону, всередині пари більша тема першою.
 */
export const THEME_LOOK: Record<string, ThemeLook> = {
  // Гроші. Одна тема на весь шлях від прорахунку до оплати: специфікація,
  // собівартість, націнка, рахунок, документи замовлення. Розділяти її на
  // «економіку», «картку» й «гроші» вже пробували — див. доку вище.
  "прорахунки й гроші": { icon: Banknote, tone: "teal" },
  // Не «прорахунки й гроші»: там гроші приходять, тут щомісяця йдуть — Netlify,
  // Supabase, AI-моделі. Одна тема на всі рахунки за роботу самої CRM.
  "рахунок за хмару": { icon: Receipt, tone: "teal" },

  // Обличчя CRM. Сюди йде все видиме: мова й вигляд, екран входу, мобільна
  // адаптація, косметика будь-якої сторінки. Окрема тема на екран — це тема на
  // МІСЦЕ, а місце вже є в `module_key` і в назві картки.
  інтерфейс: { icon: Palette, tone: "festive" },
  обговорення: { icon: MessagesSquare, tone: "festive" },

  // Інженерія: щоб не впало (бекапи, перевірки, спостережність) і щоб не
  // застаріло (залежності, платформа).
  "довіра до релізу": { icon: ShieldCheck, tone: "success" },
  стек: { icon: Package, tone: "success" },

  // Люди й знання.
  "знання й анонси": { icon: BookOpen, tone: "info" },
  "особистий бот": { icon: Bot, tone: "info" },

  // Наскрізне й службове. «Майстерня Claude» — усе, чим і на чому роблять цю
  // CRM: інструменти розробки, підагенти, дошка запитів, агентські інтерфейси
  // самої CRM.
  "майстерня Claude": { icon: Wrench, tone: "neutral" },
  "зовнішні сервіси": { icon: Plug, tone: "neutral" },
};

/**
 * Вигляд теми, якої в реєстрі немає.
 *
 * Шари — навмисно найзагальніша іконка з усіх: вона має читатись як «тема без
 * свого обличчя», а не претендувати на сенс. Нейтральний тон із тієї ж
 * причини.
 */
export const THEME_FALLBACK: ThemeLook = { icon: Layers, tone: "neutral" };

/**
 * Вигляд теми. Порожня тема вигляду не має взагалі — і це не те саме, що
 * невідома: у першому випадку мітки немає, у другому вона є, але сіра.
 */
export function themeLook(theme: string | null | undefined): ThemeLook | null {
  const key = (theme ?? "").trim();
  if (!key) return null;
  return THEME_LOOK[key] ?? THEME_FALLBACK;
}

/** Чи має тема власний вигляд у реєстрі. Для тестів і для сторінки Dev. */
export function isKnownTheme(theme: string | null | undefined): boolean {
  const key = (theme ?? "").trim();
  return key in THEME_LOOK;
}

/** Усі теми реєстру — для фільтра дошки, вітрини й підказок у формі. */
export const KNOWN_THEMES = Object.keys(THEME_LOOK);
