const ICONS = {
  print_diary: BookMarked,
  print_calendar_quarterly: CalendarDays,
  print_calendar_flip: CalendarFold,
  print_calendar_house: Tent,
  print_brochure: BookOpenText,
  print_certificate: Award,
  print_flyer: Files,
} as const;

export function PrintModelArt({ presetKey, className }: { presetKey: string | null; className?: string }) {
  const Icon = (presetKey && ICONS[presetKey as keyof typeof ICONS]) || FileText;
  // `size` — це лише width/height на самому svg, тож клас `h-12 w-12` із місця
  // виклику його перебиває. Саме так тут працював і мальований варіант.
  return <Icon size={42} strokeWidth={1.6} className={className} aria-hidden="true" />;
}
