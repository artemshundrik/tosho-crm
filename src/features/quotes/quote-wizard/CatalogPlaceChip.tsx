import { Tag } from "lucide-react";

import { cn } from "@/lib/utils";

/**
 * Підпис місця товару в каталозі бейджиком — «Щоденники», «Календарі · Квартальні».
 *
 * ЧОМУ БЕЙДЖ, А НЕ РЯДОК ТЕКСТУ. У поліграфії назва моделі й рівень каталогу
 * майже збігаються: під заголовком «Щоденник» сірим дрібним стояло «Щоденники»
 * — і це читалось як помилка, повтор тієї самої назви в іншому відмінку, а не
 * як структура каталогу. Бейдж із піктограмою каже те саме інакше: не другий
 * підзаголовок, а мітка. Вид — факт із каталогу, а не дія, тож рамки кнопки
 * тут немає, лише підкладка.
 *
 * ОДИН НА ДВА МІСЦЯ. Так вид уже показує рядок чернетки у вікні додавання
 * позицій; картка прорахунку показує ту саму річ, і два описи однієї мітки
 * розійшлись би з першою ж правкою розміру.
 */
export function CatalogPlaceChip({ label, className }: { label: string; className?: string }) {
  return (
    <span
      className={cn(
        "inline-flex h-8 shrink-0 items-center gap-1.5 whitespace-nowrap rounded-full bg-muted px-3",
        "text-xs font-medium text-muted-foreground",
        className
      )}
    >
      <Tag className="h-3.5 w-3.5" />
      {label}
    </span>
  );
}
