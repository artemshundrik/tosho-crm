/**
 * План пошуку в пулі за назвою з ТЗ (REQ-182#p27, живий доказ 24.09.2026).
 *
 * ЧОМУ НЕ ПРОСТО `searchSupplierPool(draft.name)`. `search_supplier_pool`
 * приймає термін і шукає його ILIKE ЦІЛОЮ ФРАЗОЮ (`docs/QUOTE_IMPORT_DESIGN.md`
 * §2б). Клієнт пише «Флісова жилетка» (прикметник-іменник), пул зве той самий
 * товар «Жилет флісовий Mercury» — інший порядок слів і інша форма. Жоден
 * варіант фрази не збігається з жодним варіантом назви пулу, хоч у пулі на той
 * момент лежало 24 профільні товари. Міняти саму функцію не можна (тюнінгована
 * під RLS-обхідний trgm-індекс, `scripts/supplier-pool-search.sql`) — тож фікс
 * лягає тут, до виклику.
 *
 * ЗАДУМ: РОЗБИТИ НА СЛОВА Й СПРОБУВАТИ КОЖНЕ. Замість цілої фрази — один
 * «стем» слова як термін RPC (він і ловить лежить-у-словнику форму: «фліс»
 * знаходить «флісовий», «флісу», «флісова» — усі мають той самий 4-літерний
 * префікс), а решта стемів — умова «і назва товару містить ЦЕ теж»
 * (`mustContain`, фільтр уже на клієнті). Останнє значуще слово йде ПЕРШИМ
 * терміном: в українській «прикметник іменник» головне слово — іменник, і
 * стоїть він останнім («жилетка» в «флісова жилетка»), тож саме його форма
 * найкраще звужує пул, а прикметник лишається обов'язковою домішкою.
 *
 * СТЕМ, А НЕ ЦІЛЕ СЛОВО. Українські форми відмінюються («жилетка» →
 * «жилета», «жилет»), а пул часто називає товар іншою частиною мови
 * («жилетка» клієнта проти «жилет» постачальника). Спільний префікс
 * (`slice(0, length - 3)`, не коротший за 4) ловить обидва без словника
 * відмінків — грубо, як і транслітерація в `supplierPoolRows.ts`, і з тієї ж
 * причини: мета не лінгвістична точність, а зловити те, що людина й так
 * впізнає.
 */

export type PoolQueryPlan = { term: string; mustContain: string[] };

/** Найкоротше слово, яке ще варте власного запиту в пул: менше — самі прийменники й одиниці. */
const MIN_WORD_LENGTH = 4;

/** Літера будь-якої абетки — кордон слова ставить усе, що не літера (цифри, дефіси, розділові). */
const WORD_BOUNDARY = /[^\p{L}]+/u;

/**
 * Слова, які по формі проходять поріг довжини, але значення не несуть.
 * Здебільшого зайве відсікає вже сама довжина («для», «шт», «мл», «500» —
 * останнє не літери взагалі), цей список — лише те, що довше трьох літер.
 */
const STOP_WORDS = new Set(["with", "для", "від", "або", "the", "and"]);

function significantWords(name: string): string[] {
  return name
    .split(WORD_BOUNDARY)
    .filter((word) => word.length >= MIN_WORD_LENGTH)
    .filter((word) => !STOP_WORDS.has(word.toLowerCase()));
}

/** «флісова» → «фліс», «жилетка» → «жиле», «шопер» → «шопе» — спільний префікс форм слова. */
function stem(word: string): string {
  const lower = word.toLowerCase();
  return lower.slice(0, Math.max(MIN_WORD_LENGTH, lower.length - 3));
}

/**
 * До трьох планів пошуку: `{term, mustContain}` для `searchSupplierPool`.
 * Один слово — один план без `mustContain` (нема з чим звужувати). Кілька
 * слів — головне (останнє значуще) слово першим терміном, далі решта в
 * порядку появи; кожен план тримає ВСІ інші стеми як обов'язкову домішку, щоб
 * «фліс» сам по собі не тягнув усе флісове підряд, а лише те, що й «жилетка».
 */
export function planPoolQueries(name: string): PoolQueryPlan[] {
  const stems = significantWords(name).map(stem);
  if (stems.length === 0) return [];
  if (stems.length === 1) return [{ term: stems[0], mustContain: [] }];

  const lastIndex = stems.length - 1;
  const order = [lastIndex, ...stems.slice(0, lastIndex).map((_, index) => index)];

  return order.slice(0, 3).map((index) => ({
    term: stems[index],
    mustContain: stems.filter((_, otherIndex) => otherIndex !== index),
  }));
}
