/**
 * Яке фото показує картка позиції прорахунку (REQ-285#p6).
 *
 * ДЖЕРЕЛ ТРИ, І ПОРЯДОК МІЖ НИМИ — НЕ СМАК.
 *
 *   1. КАРТИНКА З ПОСИЛАННЯ (`metadata.catalogVariant.imageUrl`) — фото САМЕ
 *      ЦЬОГО товару в САМЕ ЦЬОМУ кольорі.
 *   2. ФОТО МОДЕЛІ КАТАЛОГУ — парасолька над усіма кольорами.
 *   3. ВКЛАДЕННЯ — лише для позицій без моделі: там людина принесла файл сама.
 *
 * ЧОМУ ПОСИЛАННЯ ПОПЕРЕДУ МОДЕЛІ, хоч модель обрала людина. Модель у каталозі
 * ОДНА НА ВСІ КОЛЬОРИ, і фото в неї — той колір, який завели першим. У
 * прорахунку TS-0926-0029 стоїть «Записна книжка А5, Soft» блакитна (артикул
 * 1291-12), а модель несе фіолетову з іншого прорахунку (1291-16): картка
 * показувала фіолетову книжку з блакитним артикулом. Тобто перевага моделі не
 * уточнює позицію, а заперечує її.
 *
 * ЦЕ ВИПРАВЛЕННЯ МОГО Ж ПОПЕРЕДНЬОГО ЗАХОДУ, і воно тут на видноті навмисно.
 * Спершу модель поставили першою — бо eney.com.ua віддавав `og:image` рівним
 * власному логотипу, і три позиції малювали синій напис ENEY замість товару.
 * Але лікувати це порядком джерел було лікуванням симптому: справжня причина —
 * що ми взяли логотип за фото. Її закрито там, де вона жила (`_lib/ogTags.ts`
 * відкидає службову графіку на ВСІХ джерелах, а пул постачальників дає готове
 * фото замість здогаду), тож порядок повертається до природного: конкретне
 * перед загальним.
 *
 * ЗУМ МАЄ СВОЮ ДРАБИНКУ. У каталозі фото живе у двох розмірах: мініатюра для
 * рядка й повне для перегляду. Тому в `zoomUrl` повне фото моделі стоїть перед
 * мініатюрою — але після картинки з посилання, за тим самим правилом.
 */

export type ProductPreview = {
  type: "image";
  url: string;
  zoomUrl: string;
};

export type ProductPreviewSources = {
  /** Мініатюра моделі каталогу. */
  catalogImage: string | null;
  /** Повне фото моделі — для перегляду. */
  catalogZoomImage: string | null;
  /** Картинка, підтягнута за посиланням постачальника. */
  variantImageUrl: string | null;
  /** Вкладення позиції, якщо це картинка й моделі немає. */
  attachmentImage: string | null;
};

export function pickProductPreview(sources: ProductPreviewSources): ProductPreview | null {
  const { catalogImage, catalogZoomImage, variantImageUrl, attachmentImage } = sources;
  const url = variantImageUrl ?? catalogImage ?? attachmentImage;
  if (!url) return null;
  return {
    type: "image",
    url,
    zoomUrl: variantImageUrl ?? catalogZoomImage ?? attachmentImage ?? catalogImage ?? url,
  };
}
