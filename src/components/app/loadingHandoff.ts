import { useEffect, useState } from "react";

/**
 * Передача естафети між каркасами завантаження.
 *
 * ЩО ЛІКУЄ. Холодний вхід у розділ — це не одне очікування, а ланцюжок із
 * трьох-чотирьох: перевірка сесії, чанк сторінки, дані сторінки, іноді ще й
 * дані вкладеного блоку. Кожен показує СВІЙ каркас, і кожен каркас відміряв
 * свої 150 мс окремо. Виходило: каркас → порожньо → каркас → порожньо → вміст.
 * Артем описав це точно: «мигає, повністю зникає, ніби поломка».
 *
 * ЯК ЛІКУЄМО. Затримка тепер належить не компоненту, а ПЕРЕХОДУ. Перший каркас
 * чекає свої 150 мс — це відсіює швидкі відкриття, заради яких блимати не варто.
 * Але щойно якийсь каркас показався, наступні з'являються МИТТЄВО, поки триває
 * той самий перехід: естафета передається без порожнього кадру.
 *
 * ЧОМУ МОДУЛЬ, А НЕ КОНТЕКСТ. Учасники естафети живуть у різних піддеревах і
 * навіть по різні боки від провайдерів: екран запуску (AppShell) малюється до
 * того, як з'явиться макет, фолбек маршруту — всередині Suspense, каркас
 * сторінки — вже в самій сторінці. Спільний модульний стан бачать усі, і жоден
 * зайвий рендер він не викликає.
 *
 * ПАУЗА 600 мс — це вікно, у якому «наступний каркас» ще вважається тим самим
 * очікуванням. Довша пауза означає, що людина вже побачила вміст, і нове
 * очікування чесно починається з нуля.
 */

const HANDOFF_GRACE_MS = 600;

let activeCount = 0;
let lastHiddenAt = 0;

/** Чи триває зараз очікування, у якому каркас уже показувався. */
export function isLoadingHandoffActive() {
  if (activeCount > 0) return true;
  if (lastHiddenAt === 0) return false;
  return Date.now() - lastHiddenAt < HANDOFF_GRACE_MS;
}

/** Зайняти слот «каркас на екрані». Повертає функцію звільнення. */
export function acquireLoadingHandoff() {
  activeCount += 1;
  let released = false;
  return () => {
    if (released) return;
    released = true;
    activeCount = Math.max(0, activeCount - 1);
    if (activeCount === 0) lastHiddenAt = Date.now();
  };
}

/**
 * Чи показувати каркас просто зараз.
 *
 * Перший в естафеті чекає `delayMs`, наступні — ні. Поки компонент показує
 * каркас, він тримає слот, щоб той, хто прийде за ним, не починав відлік знову.
 *
 * `active` ОБОВ'ЯЗКОВИЙ там, де хук живе в компоненті, який не зникає разом з
 * очікуванням, — наприклад у макеті. Без нього слот, зайнятий один раз, не
 * звільнявся б ніколи: макет змонтований завжди, і естафета вважалася б вічно
 * активною, а отже кожен наступний каркас з'являвся б без затримки взагалі.
 */
export function useSkeletonVisible(active = true, delayMs = 150) {
  const [visible, setVisible] = useState(() => active && isLoadingHandoffActive());

  useEffect(() => {
    if (!active) {
      setVisible(false);
      return;
    }
    if (visible) return acquireLoadingHandoff();
    const timer = setTimeout(() => setVisible(true), delayMs);
    return () => clearTimeout(timer);
  }, [active, visible, delayMs]);

  return active && visible;
}

/**
 * Тримати естафету, нічого не малюючи від себе.
 *
 * Для екранів, які вже показують власне очікування (екран запуску CRM, власні
 * каркаси сторінок): вони не питають дозволу, але мусять передати естафету далі,
 * інакше наступний каркас знову почне з порожнього кадру.
 */
export function useHoldsLoadingHandoff(active = true) {
  useEffect(() => {
    if (!active) return;
    return acquireLoadingHandoff();
  }, [active]);
}
