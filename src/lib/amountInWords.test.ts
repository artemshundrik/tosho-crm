import { describe, expect, it } from "vitest";
import { amountInWords } from "./amountInWords";

describe("amountInWords — гривні", () => {
  it("нуль", () => {
    expect(amountInWords(0, "UAH")).toBe("Нуль гривень 00 копійок");
  });

  it("одна гривня — жіночий рід і однина", () => {
    expect(amountInWords(1, "UAH")).toBe("Одна гривня 00 копійок");
  });

  it("дві гривні — жіночий рід", () => {
    expect(amountInWords(2, "UAH")).toBe("Дві гривні 00 копійок");
  });

  it("п'ять гривень — родовий множини", () => {
    expect(amountInWords(5, "UAH")).toBe("П'ять гривень 00 копійок");
  });

  it("одинадцять гривень — виняток на 11", () => {
    expect(amountInWords(11, "UAH")).toBe("Одинадцять гривень 00 копійок");
  });

  it("двадцять одна гривня — одиниця в кінці", () => {
    expect(amountInWords(21, "UAH")).toBe("Двадцять одна гривня 00 копійок");
  });

  it("сто чотирнадцять гривень — виняток на 14", () => {
    expect(amountInWords(114, "UAH")).toBe("Сто чотирнадцять гривень 00 копійок");
  });
});

describe("amountInWords — тисячі та мільйони", () => {
  it("одна тисяча — тисяча жіночого роду", () => {
    expect(amountInWords(1000, "UAH")).toBe("Одна тисяча гривень 00 копійок");
  });

  it("дві тисячі", () => {
    expect(amountInWords(2000, "UAH")).toBe("Дві тисячі гривень 00 копійок");
  });

  it("п'ять тисяч", () => {
    expect(amountInWords(5000, "UAH")).toBe("П'ять тисяч гривень 00 копійок");
  });

  it("один мільйон — чоловічий рід", () => {
    expect(amountInWords(1_000_000, "UAH")).toBe("Один мільйон гривень 00 копійок");
  });

  it("два мільйони", () => {
    expect(amountInWords(2_000_000, "UAH")).toBe("Два мільйони гривень 00 копійок");
  });
});

describe("amountInWords — приклади з реального рахунку", () => {
  it("174 960,00 — сума із ПДВ", () => {
    expect(amountInWords(174960, "UAH")).toBe(
      "Сто сімдесят чотири тисячі дев'ятсот шістдесят гривень 00 копійок"
    );
  });

  it("29 160,00 — сума ПДВ", () => {
    expect(amountInWords(29160, "UAH")).toBe(
      "Двадцять дев'ять тисяч сто шістдесят гривень 00 копійок"
    );
  });

  it("145 800,00 — сума без ПДВ", () => {
    expect(amountInWords(145800, "UAH")).toBe(
      "Сто сорок п'ять тисяч вісімсот гривень 00 копійок"
    );
  });
});

describe("amountInWords — копійки", () => {
  it("копійки виводяться цифрами з відмінюванням слова", () => {
    expect(amountInWords(145800.5, "UAH")).toBe(
      "Сто сорок п'ять тисяч вісімсот гривень 50 копійок"
    );
  });

  it("одна копійка", () => {
    expect(amountInWords(0.01, "UAH")).toBe("Нуль гривень 01 копійка");
  });

  it("дві копійки", () => {
    expect(amountInWords(0.02, "UAH")).toBe("Нуль гривень 02 копійки");
  });

  it("округлення до копійки, а не обрізання", () => {
    // 0.125 точно представляється у double, тож тут перевіряється саме округлення,
    // а не двійкове представлення числа.
    expect(amountInWords(0.125, "UAH")).toBe("Нуль гривень 13 копійок");
  });

  it("перенос копійок у гривні при округленні", () => {
    expect(amountInWords(1.996, "UAH")).toBe("Дві гривні 00 копійок");
  });
});

describe("amountInWords — інші валюти", () => {
  it("долари — чоловічий рід", () => {
    expect(amountInWords(2, "USD")).toBe("Два долари 00 центів");
  });

  it("євро не відмінюється", () => {
    expect(amountInWords(2, "EUR")).toBe("Два євро 00 центів");
  });

  it("один долар", () => {
    expect(amountInWords(1, "USD")).toBe("Один долар 00 центів");
  });
});
