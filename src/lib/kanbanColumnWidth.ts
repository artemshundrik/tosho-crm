import { KANBAN_BOARDS, type KanbanBoardKey } from "./kanbanBoards";

/**
 * Ширина колонки канбан-дошки, яка ділить полотно НАЦІЛО (REQ-300).
 *
 * ЩО РОБИТЬ ФОРМУЛА. Поки на кожну колонку лишається не менше `minPx`, вони
 * розтягуються так, щоб сума ширин плюс проміжки дорівнювала ширині полотна:
 * праворуч не лишається порожнечі, яку на широкому моніторі видно найкраще.
 * Щойно полотно вужче — колонка впирається в `minPx`, стрічка стає ширшою за
 * екран, і вмикається звичний горизонтальний скрол.
 *
 * ЧОМУ `100cqw`, А НЕ `100%`. Відсоток тут рахувався б від стрічки `w-max`,
 * тобто від суми самих колонок — рівняння саме на себе. `cqw` міряє полотно,
 * тож дошці ПОТРІБЕН `container-type: inline-size` на скролері (клас
 * `[container-type:inline-size]` на `KanbanBoard`), інакше одиниця відкотиться
 * до розміру вьюпорта й колонки поїдуть.
 *
 * ЧОМУ НЕ КЛАСОМ. Tailwind збирає класи наперед, тож `basis-[${…}]` зі змінної
 * не згенерується взагалі. Ширина їде інлайновим `flex-basis` — тим самим
 * шляхом, яким її вже отримує каркас дошки (`KanbanSkeleton.columnWidth`).
 *
 * ЧОМУ ОКРЕМИЙ МОДУЛЬ І ГОТОВІ СТАЛІ. Читачів у кожної ширини троє: сама
 * дошка, каркас маршруту в реєстрі поверхонь (`layout/pageSurfaces.ts`) і
 * каркас на самій сторінці. Доки ширина стояла в них окремо, вони розходились —
 * і перехід від каркаса до дошки читався як стрибок. Тому нижче лежать не
 * рецепти, а вже пораховані значення: кількість колонок береться з того ж
 * реєстру, що й самі дошки, тож додана чи прибрана колонка перелічує ширину
 * сама.
 */

/** Проміжок між колонками — `gap-4` у `KanbanBoard`, слово в слово. */
const COLUMN_GAP_PX = 16;

export function fluidKanbanColumn({ columns, minPx }: { columns: number; minPx: number }): string {
  const gaps = Math.max(columns - 1, 0) * COLUMN_GAP_PX;
  return `max(${minPx}px, calc((100cqw - ${gaps}px) / ${columns}))`;
}

const fillBoardColumn = (board: KanbanBoardKey, minPx: number) =>
  fluidKanbanColumn({ columns: KANBAN_BOARDS[board].onBoard.length, minPx });

/** Беклог (REQ-300). 300 px — та сама ширина, що стояла там жорстко. */
export const DEV_BACKLOG_COLUMN_WIDTH = fillBoardColumn("devRequests", 300);

/**
 * Прорахунки (REQ-300, друга дошка).
 *
 * Мінімум 224 px — нижня межа колишнього `clamp(224px,…,312px)`, і він
 * лишається не заради спадковості: з найвужчої колонки рахується смуга
 * мініатюр у картці (`QuoteKanbanProducts`, п'ять по 28 px у рядок, що не
 * переноситься). Стеля 312 px натомість пішла — саме вона й лишала порожнє
 * місце праворуч, відколи колонка «Новий» зникла (REQ-299) і дошка стала
 * чотириколонковою.
 */
export const QUOTES_COLUMN_WIDTH = fillBoardColumn("quotes", 224);
