/**
 * Ширина колонки канбан-дошки, яка ділить полотно НАЦІЛО (REQ-300).
 *
 * ЩО РОБИТЬ ФОРМУЛА. Поки на кожну колонку лишається не менше `minPx`, вони
 * розтягуються так, щоб сума ширин плюс проміжки дорівнювала ширині полотна:
 * праворуч не лишається порожнечі, яку на широкому моніторі видно найкраще.
 * Щойно полотно вужче — колонка впирається в `minPx`, стрічка стає ширшою за
 * екран, і вмикається звичний горизонтальний скрол.
 *
 * ЧОМУ `100cqw`, А НЕ `100%`. Відсоток тут рахувався б від стрічки `w-max`,
 * тобто від суми самих колонок — рівняння саме на себе. `cqw` міряє полотно,
 * тож дошці ПОТРІБЕН `container-type: inline-size` на скролері (клас
 * `[container-type:inline-size]` на `KanbanBoard`), інакше одиниця відкотиться
 * до розміру вьюпорта й колонки поїдуть.
 *
 * ЧОМУ НЕ КЛАСОМ. Tailwind збирає класи наперед, тож `basis-[${…}]` зі змінної
 * не згенерується взагалі. Ширина їде інлайновим `flex-basis` — тим самим
 * шляхом, яким її вже отримує каркас дошки (`KanbanSkeleton.columnWidth`).
 *
 * ЧОМУ ОКРЕМИЙ МОДУЛЬ. Читачів двоє: сама дошка й реєстр поверхонь
 * (`layout/pageSurfaces.ts`), з якого малюється каркас маршруту ще до того, як
 * дошка існує. Доки ширина стояла в двох місцях окремо, вони розходились — і
 * перехід від каркаса до дошки читався як стрибок.
 */

/** Проміжок між колонками — `gap-4` у `KanbanBoard`, слово в слово. */
const COLUMN_GAP_PX = 16;

export function fluidKanbanColumn({ columns, minPx }: { columns: number; minPx: number }): string {
  const gaps = Math.max(columns - 1, 0) * COLUMN_GAP_PX;
  return `max(${minPx}px, calc((100cqw - ${gaps}px) / ${columns}))`;
}
