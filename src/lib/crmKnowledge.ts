  /**
   * Куди йти в CRM. Помічник дає посилання замість переказу — питання «де це
   * налаштувати» має закінчуватись переходом, а не абзацом тексту.
   */
  route?: string;
  /**
   * Модулі, яких тема стосується. Порожньо — тема загальна й потрібна завжди.
   * За цим полем правила відбираються під поточний розділ.
   */
