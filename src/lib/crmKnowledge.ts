/**
 * Стеля розміру ПОВНОГО тексту. У запит іде відфільтрований шматок, але й
 * повний обсяг тримаємо в межах: інакше на сторінці «Як ми працюємо» вийде
 * полотно, яке ніхто не дочитає.
 */
export const CRM_KNOWLEDGE_MAX_CHARS = 4200;

/**
 * Правила для промпта.
 *
 * Без модуля повертає все. З модулем — загальні теми плюс дотичні до цього
 * розділу: коли людина стоїть у Фінансах, правила про раунди правок їй нічого
 * не додають, а токени коштують у кожному запиті.
 */
export function buildCrmKnowledge(activeModule?: ModuleKey | null): string {
  const topics = activeModule
    ? CRM_KNOWLEDGE.filter((topic) => !topic.modules || topic.modules.includes(activeModule))
    : CRM_KNOWLEDGE;

  return topics
    .map((topic) => {
      const head = topic.route ? `${topic.title} (${topic.route}):` : `${topic.title}:`;
      return `${head}\n${topic.rules.map((rule) => `- ${rule}`).join("\n")}`;
    })
    .join("\n\n");
}
