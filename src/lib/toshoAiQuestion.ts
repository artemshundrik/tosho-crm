/**
 * Чи схожий рядок у палітрі на ПИТАННЯ, а не на пошук назви.
 *
 * Від цього залежить лише ПОРЯДОК: рядок «Спитати ToSho AI» присутній завжди,
 * але для питання він іде першим і підсвіченим, а для пошуку — останнім і тихим.
 * Тому помилка тут не ламає нічого: у найгіршому випадку людина побачить
 * потрібний рядок трохи нижче.
 *
 * Свідомо БЕЗ мережі й без моделі: рішення приймається на кожне натискання
 * клавіші, і платити за нього запитом до AI було б і повільно, і дорого.
 */

/** Питальні слова. Якщо рядок починається з такого — це майже напевно питання. */
const QUESTION_WORDS = new Set([
  "як",
  "яка",
  "який",
  "яке",
  "які",
  "чому",
  "чого",
  "скільки",
  "хто",
  "кого",
  "кому",
  "коли",
  "де",
  "куди",
  "що",
  "чи",
  "навіщо",
  "звідки",
]);

/**
 * Дієслова-команди. «Покажи прорахунки» — це не пошук слова «покажи», це
 * прохання. Форми беремо ті, якими люди пишуть насправді, без словника.
 */
const COMMAND_VERBS = new Set([
  "покажи",
  "показати",
  "склади",
  "скласти",
  "порахуй",
  "порахувати",
  "знайди",
  "розкажи",
  "поясни",
  "підсумуй",
  "порівняй",
  "перевір",
  "напиши",
  "зроби",
  "згенеруй",
  "переклади",
]);

/**
 * Довгий рядок — теж ознака. Назву замовника чи номер прорахунку не шукають
 * пʼятьма словами, а от питання рідко буває коротшим.
 */
const LONG_PHRASE_WORDS = 5;

export function looksLikeQuestion(value: string): boolean {
  const normalized = value.trim().toLowerCase();
  if (!normalized) return false;
  if (normalized.endsWith("?")) return true;

  const words = normalized.split(/\s+/).filter(Boolean);
  if (words.length === 0) return false;

  const first = words[0].replace(/[^\p{L}\p{N}]/gu, "");
  if (QUESTION_WORDS.has(first)) return true;
  if (COMMAND_VERBS.has(first)) return true;

  return words.length >= LONG_PHRASE_WORDS;
}
