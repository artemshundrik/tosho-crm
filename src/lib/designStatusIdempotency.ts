/**
 * ПОВТОРНЕ ПЕРЕВЕДЕННЯ В ТОЙ САМИЙ СТАТУС — НЕ ПОДІЯ.
 *
 * ЩО ЛАМАЛОСЯ. Дизайн-задача змінює статус із двох місць: дошка (`DesignPage`)
 * і картка задачі (`DesignTaskPage`). Обидва входи перевіряли статус за своїм
 * ЗНІМКОМ у стані React, а не за базою. Знімок застаріває легко:
 *
 *   - на дошці оптимістичне оновлення стоїть ПІСЛЯ читання metadata, тож між
 *     кидком картки й перемальовкою є ціле мережеве коло. Посадка картки чекає
 *     рівно LANDING_WAIT_FRAMES кадрів і, не дочекавшись, повертає її у стару
 *     колонку — людина кидає вдруге, і другий кидок бере той самий застарілий
 *     об'єкт задачі, проходить усі перевірки й пише подію та сповіщення ще раз;
 *   - у картці той самий ефект дає подвійний клік або повернення на вкладку,
 *     яку хтось уже посунув з іншого місця.
 *
 * ЦІНА. 31.08.2026 дві задачі з трьох з'їхали двічі за 3.4 і 6.4 секунди, і
 * замість трьох повідомлень у Telegram приїхало п'ять. За 60 днів таких пар 13,
 * у чотирьох різних людей — тобто це не випадковість одного дня.
 *
 * РІШЕННЯ. Вирішує СВІЖИЙ статус із бази, який обидва входи вже читають перед
 * записом (`freshRow.metadata` / `fetchDesignTaskMetadata`), тож перевірка не
 * коштує жодного зайвого запиту. Виходимо мовчки, без тосту: для людини картка
 * вже там, куди вона її вела, і сказати їй нема чого.
 *
 * ЧОМУ ОКРЕМИЙ МОДУЛЬ. Правило одне, а читачів двоє, і обидва — сторінки на
 * тисячі рядків. Копія в кожній розійшлася б із другою на першій же правці.
 */
export function isDesignStatusAlreadyApplied(
  liveMetadata: Record<string, unknown> | null | undefined,
  nextStatus: string
): boolean {
  return (liveMetadata?.status ?? null) === nextStatus;
}
