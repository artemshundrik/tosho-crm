/**
 * Роль позиції «варіант» — група взаємовиключних позицій прорахунку (REQ-267#p2).
 *
 * НАВІЩО. Менеджер дає клієнту три щоденники — у шкірзаміннику, в папері з
 * друком і в дизайнерському папері, — і клієнт купить ОДИН. КП же складало всі
 * три й показувало суму, якої не буде в жодному замовленні: для TS-0826-0036 це
 * 43 823 ₴ там, де найдорожчий сценарій — 21 000 ₴. Позиції з роллю «варіант»
 * входять у підсумок документа не доданком, а межами «від найдешевшого варіанта
 * до найдорожчого».
 *
 * ЧОМУ БЕЗ ЗМІНИ СХЕМИ. Роль живе в `quote_items.metadata.isVariant` — jsonb,
 * який уже є. Колонка дала б перевірку типу на рівні бази, але й міграцію на
 * продівській базі заради одного прапорця, який не бере участі ні в індексах,
 * ні в join-ах, ні в RLS. Читає його ЛИШЕ документ; підсумок картки, замовлення
 * й дайджести на нього не дивляться (див. «Межі» нижче).
 *
 * ЧОМУ ЦЕ НЕ `isQuoteItemIncluded` І НЕ `pickApprovedRun` — три сусідні правила,
 * які легко сплутати:
 *   - ТИРАЖ (`quote_item_runs.is_approved`) — взаємовиключний вибір ВСЕРЕДИНІ
 *     позиції: 100/150/200 шт того самого товару.
 *   - ПОГОДЖЕННЯ ПОЗИЦІЇ (`quote_items.is_approved`, REQ-267#p1) — відповідь
 *     клієнта ПІСЛЯ затвердження: цю взяв, цю ні.
 *   - РОЛЬ «ВАРІАНТ» (цей файл) — намір менеджера ДО відповіді: ось три
 *     позиції, з яких клієнт візьме одну. Вона нічого не відсіває й нічого не
 *     затверджує, лише міняє арифметику підсумку в документі.
 *
 * МЕЖІ, і про них треба знати. Число підсумку прапорець не міняє НІДЕ, крім
 * документа: підсумок картки прорахунку, `orderRecords` і
 * `netlify/functions/_lib/quotePricing` рахують так само, як рахували, — сумою.
 * Це свідомо: картка показує все, що порахували, а замовлення збирається вже
 * після відповіді клієнта, коли взаємовиключності немає (непогоджені позиції
 * відсіяв p1).
 *
 * Єдиний виняток — ПОКАЗ: поруч із підсумком картки стоїть окремий рядок «з них
 * варіанти: від X до Y» (`variantGroupRange`). Саме число підсумку він не
 * чіпає, але менеджер бачить ті самі межі, що й клієнт у КП, — інакше по
 * телефону легко назвати суму, якої в жодному замовленні не буде.
 *
 * ОДНА ГРУПА НА ПРОРАХУНОК. Позначені позиції прорахунку утворюють рівно одну
 * взаємовиключну групу — іменованих груп немає. Прорахунок «два різні вироби,
 * у кожного по три варіанти» цією моделлю не описується; якщо такий випадок
 * зʼявиться, ключем групи стане рядок замість `true`, і читач нижче — єдине
 * місце, яке доведеться правити.
 */

/** Діапазон «від найдешевшого сценарію до найдорожчого». min === max — сума точна. */
export type MoneyRange = {
  min: number;
  max: number;
};

/**
 * Чи має позиція роль «варіант».
 *
 * Приймає `unknown`, бо викликається і на сирому jsonb із бази (документ КП), і
 * на розібраному `QuoteItemMetadata` (картка прорахунку). Один читач на обидва
 * шляхи — щоб «позначено» й «показано діапазоном» не могли розійтись.
 */
export function isVariantQuoteItem(metadata: unknown): boolean {
  if (!metadata || typeof metadata !== "object" || Array.isArray(metadata)) return false;
  return (metadata as { isVariant?: unknown }).isVariant === true;
}

/** Межі однієї позиції по її тиражах. Порожній перелік — нульовий діапазон. */
export function moneyRangeOf(totals: readonly number[]): MoneyRange {
  if (totals.length === 0) return { min: 0, max: 0 };
  return { min: Math.min(...totals), max: Math.max(...totals) };
}

export type QuoteItemRangeEntry = {
  /** Роль «варіант»: така позиція входить у групу, а не в суму. */
  isVariant?: boolean;
  /** Межі самої позиції — по її взаємовиключних тиражах. */
  range: MoneyRange;
};

/**
 * Підсумок документа: звичайні позиції складаються, варіанти — накриваються
 * спільними межами.
 *
 * ГОЛОВНЕ ПРАВИЛО ФАЙЛУ, і воно про безпеку старих документів: коли жодна
 * позиція не позначена варіантом, результат — рівно та сума, що й була до
 * появи ролі. Тому гілка «варіантів немає» повертає базу без жодного дотику до
 * `Math.min`/`Math.max`: змінюватись мала б лише поведінка позначених.
 *
 * Група з ОДНІЄЇ позиції теж безпечна: її межі — це її ж власні межі, тобто
 * той самий доданок. Позначка на одній позиції нічого не ламає, просто нічого
 * і не змінює.
 */
export function quoteItemsTotalRange(items: readonly QuoteItemRangeEntry[]): MoneyRange {
  const base = items.reduce<MoneyRange>(
    (acc, item) =>
      item.isVariant === true
        ? acc
        : { min: acc.min + item.range.min, max: acc.max + item.range.max },
    { min: 0, max: 0 }
  );

  const variants = items.filter((item) => item.isVariant === true);
  if (variants.length === 0) return base;

  const span = spanOf(variants);
  return { min: base.min + span.min, max: base.max + span.max };
}

/** Спільні межі позначених позицій — «від найдешевшого варіанта до найдорожчого». */
function spanOf(variants: readonly QuoteItemRangeEntry[]): MoneyRange {
  return variants.reduce<MoneyRange>(
    (acc, item) => ({
      min: Math.min(acc.min, item.range.min),
      max: Math.max(acc.max, item.range.max),
    }),
    { min: Number.POSITIVE_INFINITY, max: Number.NEGATIVE_INFINITY }
  );
}

/**
 * Ті самі межі групи, але ОКРЕМИМ числом — для рядка «з них варіанти» поруч із
 * підсумком картки прорахунку.
 *
 * ЧОМУ ЦЕ НЕ ЧАСТИНА ПІДСУМКУ КАРТКИ. Підсумок лишається сумою всього, що
 * порахували: на ньому висять замовлення, дайджести й `_lib/quotePricing`.
 * Рядок поруч лише показує ту частину, яку клієнт у КП побачить межами, — щоб
 * два екрани того самого прорахунку не називали різні числа мовчки.
 *
 * `null` — групи немає, і рядка бути не повинно. Поріг той самий, що в
 * `hasVariantGroup`: одна позначена позиція групи не утворює, а «від 21 000 до
 * 21 000» поруч із сумою читалось би як поломка.
 */
export function variantGroupRange(items: readonly QuoteItemRangeEntry[]): MoneyRange | null {
  const variants = items.filter((item) => item.isVariant === true);
  if (variants.length < 2) return null;
  return spanOf(variants);
}

/**
 * Чи має сенс писати в документі пояснення про варіанти.
 *
 * Дві й більше — бо саме з двох починається вибір. На одній позначеній позиції
 * підсумок не відрізняється від суми, і фраза «замовник обирає один варіант»
 * поруч із єдиним варіантом читалась би як помилка.
 */
export function hasVariantGroup(items: readonly { isVariant?: boolean }[]): boolean {
  return items.filter((item) => item.isVariant === true).length > 1;
}
