import type { User } from "@supabase/supabase-js";
import { supabase } from "./supabaseClient";

/**
 * Хто зараз у застосунку — без походу в мережу.
 *
 * НАВІЩО. `supabase.auth.getUser()` ЗАВЖДИ б'є в `/auth/v1/user`, бо його
 * робота — спитати сервер, кому належить токен. А supabase-js ще й вишиковує
 * виклики авторизації в чергу за спільним замком, тож вони не йдуть
 * паралельно: другий чекає на перший. На старті CRM таких викликів набиралось
 * близько п'яти поспіль. Заміряно на зібраній збірці 21.08.2026:
 * 62→226, 226→334, 358→442, 444→554, 556→648 — майже 590 мс суцільного
 * очікування, після якого лише й починався перший запит картки прорахунку.
 *
 * При цьому майже в усіх тих місцях від «сервера» нічого не треба: потрібен id
 * людини (щоб проставити автора), інколи ще ім'я з метаданих. Усе це вже лежить
 * у поточній сесії, і `getSession()` віддає його з локального сховища, не
 * питаючи мережу (протермінований токен він оновить сам — це і потрібно).
 *
 * ЧОМУ ЦЕ НЕ ПОСЛАБЛЕННЯ. `getUser()` цінний там, де токен ПРИЙШОВ ЗЗОВНІ і
 * йому не можна вірити, — тобто в Netlify-функціях, які перевіряють токен
 * клієнта. У браузері ж сесія і так своя: підмінивши її, людина обманула б
 * лише власний інтерфейс. Справжній кордон — RLS: Postgres бере `auth.uid()`
 * з підписаного токена, а не з поля, яке надіслав клієнт.
 *
 * НЕ ВИКОРИСТОВУВАТИ в `netlify/functions/*` — там `getUser()` на місці й
 * міняти його не можна.
 */
export async function getCurrentUser(): Promise<User | null> {
  const { data, error } = await supabase.auth.getSession();
  if (error) return null;
  return data.session?.user ?? null;
}

/** Те саме, коли потрібен лише id — найчастіший випадок. */
export async function getCurrentUserId(): Promise<string | null> {
  return (await getCurrentUser())?.id ?? null;
}
