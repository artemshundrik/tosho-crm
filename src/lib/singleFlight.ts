/**
 * Один політ на ключ: поки запит у дорозі, наступні чекають на нього, а не
 * заводять свій.
 *
 * НАВІЩО ЦЕ ОКРЕМИЙ ПРИМІТИВ. Кеш рятує лише ПІСЛЯ першої відповіді. На
 * відкритті сторінки кілька компонентів монтуються одночасно, кеш ще порожній —
 * і в базу летять однакові запити. Заміряно 20.08.2026 на дизайн-задачі:
 * my_workspace_id ×4, current_user_blocked ×3, memberships_view ×3,
 * feature_hints ×2 (той самий рядок запиту), acquire_entity_lock ×2. Кожен
 * дублікат — не просто зайвий рядок у журналі: він додає власне очікування
 * мережі в ланцюг, від якого залежить перший кадр сторінки.
 *
 * ЩО ЦЕ НЕ Є. Не кеш: результат нікуди не зберігається, і наступний виклик
 * після відповіді знову піде в базу. Саме тому цим можна накривати навіть те,
 * що кешувати НЕ МОЖНА, — перевірку блокування співробітника, взяття лока: ми
 * склеюємо лише те, що й так відбувається одночасно, а частота перевірок
 * лишається незмінною.
 */
const inFlight = new Map<string, Promise<unknown>>();

export function singleFlight<T>(key: string, run: () => Promise<T>): Promise<T> {
  const pending = inFlight.get(key) as Promise<T> | undefined;
  if (pending) return pending;

  /**
   * Прибирання — ВСЕРЕДИНІ задачі, у finally, а не в окремому .then().
   *
   * Спершу було через .then() — і тест одразу впіймав: той, хто зробив await,
   * прокидається раніше, ніж черга дійде до прибирання, тож наступний виклик
   * діставав уже виконаний політ. Виходив кеш там, де кешу бути не має —
   * найгірший варіант для перевірки блокування співробітника.
   */
  const slot: { task?: Promise<T> } = {};
  slot.task = (async () => {
    try {
      return await run();
    } finally {
      // Знімаємо лише СВІЙ політ: за час запиту хтось міг покласти новий.
      if (inFlight.get(key) === slot.task) inFlight.delete(key);
    }
  })();
  inFlight.set(key, slot.task);
  return slot.task;
}

/** Забути політ примусово — коли наступний виклик мусить піти в базу заново. */
export function forgetFlight(key: string) {
  inFlight.delete(key);
}
