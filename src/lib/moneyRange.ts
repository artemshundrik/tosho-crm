/**
 * Межі суми «від найдешевшого сценарію до найдорожчого».
 *
 * НАВІЩО ЦЕ ВЗАГАЛІ Є. Тиражі позиції — ВЗАЄМОВИКЛЮЧНІ варіанти: клієнт обирає
 * один зі 100/150/200, а не купує всі три (REQ-57). Тому в позиції з кількома
 * тиражами єдиної суми не існує, і КП показує межі. Один тираж ⇒ межі
 * збігаються ⇒ вигляд звичайного числа, як і було до появи цього типу.
 *
 * ЗВІДКИ ЦЕЙ ФАЙЛ. Був `lib/quoteItemVariants.ts` — разом із роллю позиції
 * «варіант того самого виробу». Роль прибрана (див. нижче), а межі лишились:
 * вони не про неї, а про тиражі, і на них тримаються всі чотири виходи КП.
 *
 * ЧОГО ТУТ БІЛЬШЕ НЕМАЄ. Роллю «варіант» (`quote_items.metadata.isVariant`)
 * менеджер мав позначати взаємовиключні позиції — три щоденники, з яких клієнт
 * бере один, — і тоді підсумок документа накривав їх спільними межами замість
 * того, щоб складати. За весь час існування нею не скористались ЖОДНОГО разу:
 * 0 позначених позицій із 340 на проді. Причина не в потребі, а в тому, що
 * пункт меню нічого про себе не казав, а натиснувши його, менеджер бачив, що
 * число на картці не змінилось: роль впливала тільки на документ. Прибрано
 * цілком разом із прапорцем, пігулкою «Варіант» у КП, поясненням під підсумком
 * і попередженням про варіант без ціни. Знадобиться знову — вертати треба не
 * прапорець, а розмову про те, як менеджер про нього дізнається.
 */

/** Діапазон «від найдешевшого сценарію до найдорожчого». min === max — сума точна. */
export type MoneyRange = {
  min: number;
  max: number;
};

/** Межі однієї позиції по її тиражах. Порожній перелік — нульовий діапазон. */
export function moneyRangeOf(totals: readonly number[]): MoneyRange {
  if (totals.length === 0) return { min: 0, max: 0 };
  return { min: Math.min(...totals), max: Math.max(...totals) };
}

/**
 * Складання меж: дно з дном, стеля зі стелею.
 *
 * Позиції прорахунку — РІЗНІ товари, тож вони додаються; взаємовиключність
 * живе рівнем нижче, між тиражами однієї позиції, і вже врахована в кожному
 * доданку.
 */
export function sumMoneyRanges(ranges: readonly MoneyRange[]): MoneyRange {
  return ranges.reduce<MoneyRange>(
    (acc, range) => ({ min: acc.min + range.min, max: acc.max + range.max }),
    { min: 0, max: 0 }
  );
}
