/**
 * Хто може прибрати вкладення прорахунку.
 *
 * Правило одне — «видаляє той, хто завантажив», — але живе воно у ТРЬОХ місцях:
 * сторінка прорахунку, сторінка дизайн-задачі й політика RLS
 * (scripts/quote-attachments-author-delete.sql). Тому воно тут, а не двічі
 * переписане в двох гігантських сторінках: саме через таке дублювання й виникла
 * REQ-33, коли до автора непомітно доклеїлась умова «і я менеджер цього
 * прорахунку», і файл, помилково прикріплений до чужого прорахунку, не міг
 * прибрати вже ніхто.
 *
 * В інтерфейсі правило вужче за політику в базі: RLS пускає ще й менеджерів
 * команди (щоб було кому підчистити за звільненими), але кнопку на видному
 * місці бачить лише автор.
 */

/** Текст відмови — один на обидві сторінки, щоб не розповзався формулюваннями. */
export const ATTACHMENT_DELETE_DENIED = "Видалити файл може лише той, хто його завантажив.";

/**
 * Автор вкладення — незалежно від того, чий це прорахунок і хто веде задачу.
 *
 * `null` в `uploadedBy` не прирівнюємо до `null` у `userId`: у старих рядків
 * автор бував невідомий, і без цієї перевірки неавторизований гість формально
 * «збігався» б із ними.
 */
export function canDeleteOwnAttachment(
  uploadedBy: string | null | undefined,
  userId: string | null | undefined
): boolean {
  if (!userId || !uploadedBy) return false;
  return uploadedBy === userId;
}
