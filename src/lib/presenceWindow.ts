/**
 * Чи людина «онлайн» — одне правило на весь застосунок.
 *
 * Живе окремо від хука присутності на 700 рядків саме тому, що це правило, а не
 * механіка: його треба читати, перевіряти тестом і міняти свідомо.
 */

/**
 * Наскільки свіжою має бути позначка в базі, щоб рахувати людину онлайн.
 *
 * ПРАВИЛО: вікно мусить пережити ХОЧА Б ОДИН пропущений удар серця, інакше
 * присутність блимає. Тут стояло 45 с при тому, що позначка пишеться раз на
 * 60 с у запасному режимі й раз на 5 хв, коли працює realtime, — тобто людина,
 * яка просто сидить у CRM, більшу частину часу виглядала офлайн, а підпис
 * казав «був 1 хвилину тому». Саме на це поскаржився власник 20.08.2026.
 *
 * 2,5 хвилини покривають два запасні удари. Спостерігач, у якого працює
 * realtime, і так бачить людину онлайн миттєво (Boolean(realtime) нижче) —
 * вікно вирішує лише в деградованому режимі.
 */
export const ONLINE_WINDOW_MS = 150 * 1000;
export const IDLE_WINDOW_MS = 8 * 60 * 1000;

/**
 * Наскільки позначка може випереджати наш годинник і все ще вважатись чесною.
 *
 * `last_seen_at` пише КЛІЄНТ своїм годинником (useWorkspacePresenceState), тож
 * машина, що спішить, кладе в базу час із майбутнього. Вік такої позначки
 * від'ємний, а перевірка «вік менший за вікно» від'ємне число пропускає завжди
 * — людина лишалась онлайн у всіх спостерігачів доти, доки реальний час не
 * наздожене її годинник. При збої на години це «онлайн» на години, при збої на
 * добу — на добу (REQ-184).
 *
 * П'ять хвилин — межа між дрейфом і збоєм, і взята вона з обох боків. Машина
 * без синхронізації часу за місяці набігає саме на хвилини, тож вужчий допуск
 * гасив би присутність здоровим; а зайва поблажливість коштує небагато —
 * позначка з майбутнього в межах допуску читається як «щойно», тобто людина
 * лишається онлайн щонайбільше на ці п'ять хвилин довше. Години вперед — це
 * вже несправний годинник, і його позначці не можна вірити взагалі.
 *
 * Той самий допуск діє й у підписі «коли бачили» (lib/lastSeen.ts): якби пороги
 * розійшлись, крапка й підпис під нею почали б суперечити одне одному.
 */
export const CLOCK_SKEW_TOLERANCE_MS = 5 * 60 * 1000;

/**
 * Стан присутності однієї людини — чиста функція, щоб її можна було перевірити
 * тестом окремо від хука на 700 рядків.
 */
export function derivePresence(params: {
  hasRealtime: boolean;
  ageMs: number;
  isSelf: boolean;
}): { online: boolean; idle: boolean } {
  // Обидва не спираються на час у базі: realtime — живе з'єднання, а себе
  // людина бачить онлайн, поки дивиться на екран. Годинник тут ні до чого.
  if (params.isSelf || params.hasRealtime) return { online: true, idle: false };

  // Позначка з майбутнього далі за допуск: годинник того, хто її писав,
  // несправний. Такій позначці не вірять — ні на «онлайн», ні на «щойно
  // відлучився»: вона не каже про людину нічого.
  if (params.ageMs < -CLOCK_SKEW_TOLERANCE_MS) return { online: false, idle: false };

  // У межах допуску майбутнє читаємо як «щойно»: це дрейф годинника, а не збій.
  const ageMs = Math.max(0, params.ageMs);
  const online = ageMs <= ONLINE_WINDOW_MS;
  return { online, idle: !online && ageMs <= IDLE_WINDOW_MS };
}
