/**
 * Чи людина «онлайн» — одне правило на весь застосунок.
 *
 * Живе окремо від хука присутності на 700 рядків саме тому, що це правило, а не
 * механіка: його треба читати, перевіряти тестом і міняти свідомо.
 */

/**
 * Наскільки свіжою має бути позначка в базі, щоб рахувати людину онлайн.
 *
 * ПРАВИЛО: вікно мусить пережити ХОЧА Б ОДИН пропущений удар серця, інакше
 * присутність блимає. Тут стояло 45 с при тому, що позначка пишеться раз на
 * 60 с у запасному режимі й раз на 5 хв, коли працює realtime, — тобто людина,
 * яка просто сидить у CRM, більшу частину часу виглядала офлайн, а підпис
 * казав «був 1 хвилину тому». Саме на це поскаржився власник 20.08.2026.
 *
 * 2,5 хвилини покривають два запасні удари. Спостерігач, у якого працює
 * realtime, і так бачить людину онлайн миттєво (Boolean(realtime) нижче) —
 * вікно вирішує лише в деградованому режимі.
 */
export const ONLINE_WINDOW_MS = 150 * 1000;
export const IDLE_WINDOW_MS = 8 * 60 * 1000;

/**
 * Стан присутності однієї людини — чиста функція, щоб її можна було перевірити
 * тестом окремо від хука на 700 рядків.
 */
export function derivePresence(params: {
  hasRealtime: boolean;
  ageMs: number;
  isSelf: boolean;
}): { online: boolean; idle: boolean } {
  const online = params.isSelf || params.hasRealtime || params.ageMs <= ONLINE_WINDOW_MS;
  return { online, idle: !online && params.ageMs <= IDLE_WINDOW_MS };
}
