import { useEffect, useState, startTransition } from "react";

import { useSkeletonVisible } from "@/components/app/loadingHandoff";

/**
 * Дешевий перший кадр для важких сторінок — дошок дизайну й прорахунків.
 *
 * ЩО ЛІКУЄ. Клік по сайдбару React Router загортає в transition: СТАРА сторінка
 * лишається на екрані, доки нова не відрендериться повністю. Перший рендер цих
 * двох гігантів коштує сотні мілісекунд (на деві — секунди), тож людина
 * натискала й бачила завмерлу попередню сторінку. Заміряно 24.08.2026 на деві:
 * дизайн — 2.1 с до перемикання, прорахунки — 0.65 с, тоді як підрядники —
 * 45-160 мс.
 *
 * ЯК. Перший коміт малює лише тулбар і каркас (він уже існує — REQ-19), а
 * важке тіло вмикається прапорцем усередині transition: React рендерить його
 * шматками, не тримаючи ні адресу, ні кліки.
 *
 * ЛИШЕ ПЕРШЕ МОНТУВАННЯ ЗА СЕСІЮ. На гарячих повторних заходах тіло монтується
 * одним заходом, як і до правки: там transition закінчується за ~150 мс, а
 * «дешевий перший кадр» давав видиму ваду — тулбар уже стоїть, зона дошки на
 * кадр порожня і стрибає висотою. Тому прапорець запам'ятовується на рівні
 * модуля сторінки й живе до перезавантаження вкладки.
 *
 * ПРО ПРОЗОРІСТЬ КАРКАСА. Він живе за правилами естафети REQ-19, але з порогом
 * 400 мс замість типових 150: гарячий transition укладається раніше, і з
 * меншим порогом каркас встигав блимнути там, де раніше вміст стояв одразу.
 * Справжнє завантаження (даних ще немає) показує каркас негайно, як і до правки.
 */
export function useDeferredHeavySurface({
  alreadyMounted,
  markMounted,
  dataPending,
}: {
  /** Чи монтувалась ця сторінка вже в цій сесії (модульний прапорець сторінки). */
  alreadyMounted: boolean;
  markMounted: () => void;
  /** Чи триває справжнє завантаження даних — тоді каркас показуємо негайно. */
  dataPending: boolean;
}) {
  const [ready, setReady] = useState(alreadyMounted);

  useEffect(() => {
    if (ready) return;
    markMounted();
    startTransition(() => {
      setReady(true);
    });
  }, [ready, markMounted]);

  const deferredOnly = !ready && !dataPending;
  const skeletonVisible = useSkeletonVisible(deferredOnly, 400);

  return {
    /** Чи можна малювати важке тіло. */
    ready,
    /** Чи показувати замість тіла каркас (даних немає АБО тіло ще відкладене). */
    skeletonShown: !ready || dataPending,
    /** Чи каркас має бути видимим: відкладений — прозорий перші 400 мс. */
    skeletonOpaque: !deferredOnly || skeletonVisible,
  };
}
