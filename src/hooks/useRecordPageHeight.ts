import { useLayoutEffect, type RefObject } from "react";

/**
 * Висота повноекранної розкладки сторінки-запису (прорахунок, дизайн-задача):
 * від верху сторінки до низу вікна. Спільна для обох — доти це були дві
 * дослівні копії в сторінках-гігантах.
 *
 * ВИМІРЯНА, А НЕ ПОРАХОВАНА. Було `calc(100dvh - 56px)`, тобто «вікно мінус
 * топбар». Але над сторінкою бувають і інші смуги («Дивитесь очима»), і тоді
 * сторінка виходила вищою за вікно рівно на них — зʼявлявся скрол «на два
 * пальці», хоч скролити нема чого. Тому міряємо фактичну відстань від верху
 * кореня до низу вікна, без припущень про те, що стоїть вище.
 *
 * ХУК НЕ ЗНАЄ, СКІЛЬКИ КОЛОНОК. Він лише публікує число в `--record-page-h` на
 * корені, а застосовує його CSS: сітка бере цю висоту тільки у двоколонковому
 * вигляді (`record-split:`), у вузькому сторінка скролиться як звичайна. Поріг
 * двох колонок — ширина самої сторінки (index.css), тож дублювати його тут
 * означало б розійтись із ним за першої ж правки. До REQ-294 тут стояло
 * `window.innerWidth < 1280` — і саме воно не бачило згорнутого сайдбара.
 *
 * МІРЯЄМО ВЕРХ КОРЕНЯ, А НЕ СІТКИ. Колись міряли саму сітку, сторінка все одно
 * вилазила, різницю зрізали — і замість скролу лишалась дірка на 10-15 px
 * внизу. Висоту тепер бере сітка (корінь — контейнер, сам себе умовою
 * контейнера він стилізувати не може), але верх береться кореневий, а сітка у
 * двоколонковому вигляді — єдине, що в корені стоїть у потоці: смуга дій
 * дизайн-задачі тоді схована, курсори колег — `fixed`.
 *
 * Ефект без залежностей навмисно: верх сторінки зсувається й без зміни вікна
 * (смуга «Дивитесь очима» зʼявилась чи зникла), тож перемір після кожного
 * рендера — найдешевший спосіб не пропустити цей зсув.
 */
export function useRecordPageHeight(rootRef: RefObject<HTMLElement | null>) {
  useLayoutEffect(() => {
    const node = rootRef.current;
    if (!node) return;

    const apply = () => {
      const documentTop = node.getBoundingClientRect().top + window.scrollY;
      const next = `${Math.max(360, Math.round(window.innerHeight - documentTop))}px`;
      if (node.style.getPropertyValue("--record-page-h") !== next) {
        node.style.setProperty("--record-page-h", next);
      }
    };

    apply();
    window.addEventListener("resize", apply);
    return () => window.removeEventListener("resize", apply);
  });
}
