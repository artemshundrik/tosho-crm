/**
 * Вертикальний ритм мобільної сторінки — одні числа на всі розділи.
 *
 * НАВІЩО. Мобільні гілки з'являлись по одній, і кожна привозила власні
 * відступи: `px-4 pb-3 pt-1` на прорахунках, `space-y-2 px-4 py-3` на беклозі,
 * `pb-1` під смугою статусів в одному місці й `pb-3` в іншому. На око це
 * читалось так: на «Команді» відступи від шапки до пошуку, від пошуку до
 * вкладок і від вкладок до карток більші, ніж на дизайні. Причина була не в
 * сторінці, а в тому, що числа жили в семи місцях.
 *
 * ЯК ЧИТАТИ. Три відстані, з яких складається екран:
 *   тулбар → вміст          8px  (`MOBILE_PAGE_BODY`, pt-2)
 *   смуга статусів → картки 12px (`MOBILE_CHIPS_ROW`, pb-3)
 *   картка → картка          8px (`MOBILE_CARD_LIST`, space-y-2)
 *
 * Верхні 8px мусять збігатися з `max-md:pt-2` у контентній обгортці AppLayout —
 * інакше сторінки в режимі полотна й звичайні знову розійдуться.
 */

/** Обгортка вмісту сторінки на телефоні: бічні поля + відступ від тулбара. */
export const MOBILE_PAGE_BODY = "px-4 pt-2";

/** Відступ під смугою статусів (вкладок) до першої картки. */
export const MOBILE_CHIPS_ROW = "pb-3";

/** Проміжок між картками у вертикальному списку. */
export const MOBILE_CARD_LIST = "space-y-2";
