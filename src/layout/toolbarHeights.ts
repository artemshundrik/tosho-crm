/**
 * Заміряна висота смуги дій кожної поверхні.
 *
 * НАВІЩО. Резерв висоти працює рівно настільки, наскільки вгадана висота: якщо
 * зарезервувати 88 px там, де тулбар займе 96, стрибок не зникне — він просто
 * стане меншим на 8 px. Класи `compact`/`full` дають добру оцінку (заміряно по
 * живих сторінках), але кожна сторінка трохи своя: у «Замовленнях» вищий рядок
 * заголовка, у «Що нового» другий рядок — сама лише мета.
 *
 * ЯК ЛІКУЄТЬСЯ. Перший показ тулбара — це і є замір: макет запам'ятовує його
 * висоту й далі резервує рівно стільки. Тобто перший вхід у розділ за сеанс
 * може промазати на кілька пікселів, а всі наступні — ні.
 *
 * ЧОМУ В ПАМ'ЯТІ. Висота залежить від ширини вікна й від того, що сторінка
 * поклала в тулбар, — переживати перезавантаження такому значенню шкідливо:
 * після зміни розміру вікна збережене число брехало б.
 */

const heights = new Map<string, number>();

export function rememberToolbarHeight(surfaceId: string | null | undefined, height: number) {
  if (!surfaceId || !Number.isFinite(height) || height <= 0) return;
  heights.set(surfaceId, Math.round(height));
}

export function recallToolbarHeight(surfaceId: string | null | undefined) {
  if (!surfaceId) return null;
  return heights.get(surfaceId) ?? null;
}
