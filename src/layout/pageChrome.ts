import type { CSSProperties } from "react";

import { useScrollDirection, type ScrollChrome } from "@/hooks/useScrollDirection";

/**
 * Верхня обв'язка сторінки: шапка застосунку плюс смуга дій під нею.
 *
 * НАВІЩО ОКРЕМИЙ МОДУЛЬ. Правила поведінки обв'язки — це три пов'язані рішення
 * (що ховається, наскільки, і скільки місця лишається під нею для липких шапок
 * таблиць), і в AppLayout вони існували коментарями посеред верстки. Оболонка
 * і так найбільший файл проєкту, а сторож розростання падає на кожному десятку
 * рядків — тож правила живуть тут, а там лишається виклик.
 */

export type { ScrollChrome };

/**
 * Стан обв'язки при прокрутці.
 *
 * ХОВАЄТЬСЯ ЛИШЕ СМУГА ДІЙ, шапка лишається на місці. Перша версія забирала й
 * її, і це було зайве: у шапці живуть пошук, курси валют і сповіщення — речі,
 * по які тягнешся посеред читання, а не після повернення на початок. Смуга ж
 * з'їдає більшу частину висоти (близько сотні пікселів проти 57) і потрібна
 * рівно тоді, коли по ній тягнешся.
 */
export function usePageChrome(): ScrollChrome {
  return useScrollDirection();
}

/**
 * Скільки верху екрана зайнято обв'язкою просто зараз.
 *
 * Читають цю змінну липкі шапки таблиць (`ui/table.tsx`) — щоб стати ПІД смугою
 * дій, а не за нею. Коли смуга поїхала, під нею лишається ШАПКА, а не
 * порожнеча: перша версія ставила тут нуль, і заголовок таблиці підлазив рівно
 * під фіксовану шапку, тобто ховався за нею саме тоді, коли потрібен.
 *
 * `--page-toolbar-height` публікує сама смуга, вимірявши себе
 * (PageHeaderActionsSlot). Своє число тут розійшлося б із нею мовчки — а
 * розходження в кілька пікселів і дає те саме перекриття.
 */
export function pageChromeStyle(chrome: ScrollChrome): CSSProperties {
  return {
    "--page-chrome-offset":
      chrome === "hidden"
        ? "var(--app-header-height)"
        : "calc(var(--app-header-height) + var(--page-toolbar-height, 0px))",
  } as CSSProperties;
}
