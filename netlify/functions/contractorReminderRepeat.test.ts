import { describe, expect, it } from "vitest";

import { rollReminderForward } from "./contractor-reminders";

/**
 * reminder_at зберігається справжнім UTC, а людина мислить київським настінним
 * часом. Ці тести і стережуть той стик: після переводу годинників «щотижня
 * о 10:00» мусить лишитись 10:00 за Києвом, а не з'їхати на 09:00 чи 11:00.
 *
 * Україна переводить годинники в останню неділю березня (2026-03-29) і жовтня
 * (2026-10-25): взимку UTC+2, влітку UTC+3.
 */
describe("rollReminderForward", () => {
  it("тримає київський час доби при переході на літній час", () => {
    // 22 березня 2026, 10:00 Київ (зима, UTC+2) = 08:00Z
    const next = rollReminderForward("2026-03-22T08:00:00.000Z", "weekly", new Date("2026-03-22T09:00:00.000Z"));
    // 29 березня, 10:00 Київ (уже літо, UTC+3) = 07:00Z
    expect(next).toBe("2026-03-29T07:00:00.000Z");
  });

  it("тримає київський час доби при переході на зимовий", () => {
    // 18 жовтня 2026, 10:00 Київ (літо, UTC+3) = 07:00Z
    const next = rollReminderForward("2026-10-18T07:00:00.000Z", "weekly", new Date("2026-10-18T08:00:00.000Z"));
    // 25 жовтня, 10:00 Київ (уже зима, UTC+2) = 08:00Z
    expect(next).toBe("2026-10-25T08:00:00.000Z");
  });

  it("місячний крок тримається дня, а не 30 діб", () => {
    const next = rollReminderForward("2026-01-15T08:00:00.000Z", "monthly", new Date("2026-01-15T09:00:00.000Z"));
    expect(next).toBe("2026-02-15T08:00:00.000Z");
  });

  it("31 січня + місяць = кінець лютого, а не 3 березня", () => {
    const next = rollReminderForward("2026-01-31T08:00:00.000Z", "monthly", new Date("2026-01-31T09:00:00.000Z"));
    expect(next).toBe("2026-02-28T08:00:00.000Z");
  });

  it("після короткого місяця повертається на свій день", () => {
    // Той самий якір 31-ше: лютий обрізав до 28-го, березень має дати 31-ше.
    const next = rollReminderForward("2026-01-31T08:00:00.000Z", "monthly", new Date("2026-02-28T09:00:00.000Z"));
    // 31 березня вже літній час: 10:00 Київ = 07:00Z
    expect(next).toBe("2026-03-31T07:00:00.000Z");
  });

  it("проскакує всі пропущені спрацювання за один прохід", () => {
    // Нагадування протухло на два місяці — наступне має бути попереду, а не в минулому.
    const now = new Date("2026-03-10T12:00:00.000Z");
    const next = rollReminderForward("2026-01-05T08:00:00.000Z", "weekly", now);
    expect(next).not.toBeNull();
    expect(new Date(next as string).getTime()).toBeGreaterThan(now.getTime());
  });

  it("повертає null на кривій даті", () => {
    expect(rollReminderForward("не дата", "weekly", new Date())).toBeNull();
  });
});
