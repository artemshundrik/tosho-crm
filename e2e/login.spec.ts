import { test, expect } from "./fixtures";

/**
 * Двері в застосунок.
 *
 * ЧОМУ ЦЕ ОКРЕМИЙ СЦЕНАРІЙ, ХОЧ ФОРМА ВХОДУ Й ТАК СПРАЦЬОВУЄ ПРИ ПІДГОТОВЦІ
 * СЕСІЇ. Підготовка входить один раз і зберігає сесію на весь прогін — далі всі
 * сценарії ходять уже автентифікованими й сторінки входу не бачать. Зламавши її,
 * ми не пустимо в CRM нікого, а набір лишався б зеленим на збереженій сесії.
 *
 * ЩЕ ОДНА ПРИЧИНА: це єдиний сценарій, який працює БЕЗ облікового запису. Поки
 * тестового користувача не завели, він один тримає перевірку самого набору —
 * що збірка піднімається, сторож ловить помилки консолі й гальмо на записи
 * стоїть. Без нього налагоджувати набір довелося б наосліп.
 */
test.use({ storageState: { cookies: [], origins: [] } });

test("сторінка входу відкривається й не сипле помилками", async ({ page }) => {
  await page.goto("/login");

  await expect(page.getByText("Вхід у ToSho CRM")).toBeVisible();
  await expect(page.getByRole("button", { name: /увійти/i })).toBeVisible();

  // Форма справді приймає введення: поле, у яке не можна написати, виглядає
  // так само, як робоче, — доки в нього не спробуєш написати.
  const email = page.getByLabel(/e-?mail/i);
  await email.fill("nobody@example.com");
  await expect(email).toHaveValue("nobody@example.com");
});

/**
 * Незалогінена людина на внутрішній адресі має опинитись на вході, а не в
 * порожньому екрані. Перевіряємо саме перекидання: посилання на прорахунок
 * приходить у чат, і його відкривають із будь-якого стану.
 */
test("внутрішня адреса без сесії веде на вхід", async ({ page }) => {
  await page.goto("/orders/estimates");
  await page.waitForURL(/\/login/, { timeout: 30_000 });
  await expect(page.getByRole("button", { name: /увійти/i })).toBeVisible();
});
